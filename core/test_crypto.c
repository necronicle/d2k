static void check_rfc9001_a2_packet(void) {
    uint8_t initial_secret[32], cis[32], key[16], iv[12], hp[16];
    d2k_hkdf_extract(initial_salt, sizeof initial_salt, dcid, sizeof dcid, initial_secret);
    d2k_hkdf_expand_label(initial_secret, "client in", cis, sizeof cis);
    d2k_hkdf_expand_label(cis, "quic key", key, sizeof key);
    d2k_hkdf_expand_label(cis, "quic iv", iv, sizeof iv);
    d2k_hkdf_expand_label(cis, "quic hp", hp, sizeof hp);

    /* Смещение номера пакета В ЭТОМ КОНКРЕТНОМ векторе: первый байт(1) +
     * версия(4) + длина DCID(1) + DCID(8) + длина SCID(1, SCID пуст) + длина
     * токена варинтом(1, токен пуст) + поле длины(2, при значении 0x49e оно
     * двухбайтовое) = 18. Та же формула — в TestSplitCryptoRoundTrip донора
     * z2k-detect/internal/quicprobe. Сэмпл для защиты заголовка начинается
     * через 4 байта после начала поля номера пакета (RFC 9001 §5.4.2) —
     * смещение сэмпла фиксировано и не зависит от настоящей длины номера,
     * которая ещё не известна до снятия защиты. Оба смещения — свойство
     * ЭТОГО вектора (пустые SCID и token), не общая формула разбора: общий
     * разбор произвольного пакета — работа следующей задачи. */
    const size_t pn_off = 18;
    const size_t sample_off = pn_off + 4;

    /* Маска защиты заголовка — AES-ECB одного блока сэмпла. want_mask не
     * публикуется в тексте RFC отдельно; получена независимым пересчётом
     * (crypto/aes стандартной библиотеки Go) поверх уже провалидированного
     * hp и байт сэмпла, взятых прямо из protected_packet, — см. шапку
     * файла. */
    static const uint8_t want_mask[16] = {
        0x43, 0x7b, 0x9a, 0xec, 0x36, 0xbe, 0x42, 0x34,
        0x00, 0xcd, 0xd1, 0x15, 0xd9, 0xdb, 0x32, 0x41,
    };
    uint8_t mask[16];
    d2k_aes128_ecb(hp, protected_packet + sample_off, mask);
    CHECK(memcmp(mask, want_mask, sizeof mask) == 0,
          "маска защиты заголовка (AES-128-ECB) не сошлась на пакете RFC 9001 A.2");

    /* Снятие защиты: длинный заголовок закрывает нижние 4 бита первого байта
     * (RFC 9001 §5.4.1), номер пакета — соответствующими байтами маски.
     * Длина номера (4) для ЭТОГО вектора известна заранее из текста RFC —
     * общий разбор берёт её из низких битов первого байта ПОСЛЕ снятия
     * маски, что здесь не нужно проверять отдельно. */
    uint8_t first_byte = (uint8_t)(protected_packet[0] ^ (mask[0] & 0x0f));
    CHECK(first_byte == 0xc3,
          "первый байт после снятия защиты не 0xc3 (длинный заголовок/Initial/номер длиной 4)");

    static const uint8_t want_pn[4] = { 0x00, 0x00, 0x00, 0x02 };
    uint8_t pn[4];
    for (size_t i = 0; i < 4; i++) {
        pn[i] = (uint8_t)(protected_packet[pn_off + i] ^ mask[1 + i]);
    }
    CHECK(memcmp(pn, want_pn, sizeof pn) == 0, "номер пакета после снятия защиты не 2");

    /* AAD — весь незащищённый заголовок вплоть до номера пакета включительно
     * (RFC 9001 §5.3): первый байт и номер пакета берём уже расшифрованными,
     * остальное защите не подвергалось и читается из пакета как есть. */
    uint8_t aad[22];
    aad[0] = first_byte;
    memcpy(aad + 1, protected_packet + 1, pn_off - 1);
    memcpy(aad + pn_off, pn, sizeof pn);

    /* nonce — iv, поксоренный с номером пакета по правому краю (RFC 9001
     * §5.3, тот же приём, что и nonce() в quicprobe/initial.go). */
    uint8_t nonce[12];
    memcpy(nonce, iv, sizeof nonce);
    for (size_t i = 0; i < 4; i++) {
        nonce[sizeof nonce - 1 - i] ^= pn[3 - i];
    }

    const uint8_t *ct = protected_packet + sample_off;
    const size_t ct_len = sizeof protected_packet - sample_off; /* 1178 = 1162 + тег */
    uint8_t plain[sizeof crypto_frame + 917]; /* 1162: столько в A.2 занимает CRYPTO-кадр с паддингом */
    int rc = d2k_aes128_gcm_decrypt(key, nonce, aad, sizeof aad, ct, ct_len, plain);
    CHECK(rc == 0, "AES-128-GCM не расшифровал настоящий клиентский Initial из RFC 9001 A.2");
    if (rc == 0) {
        uint8_t expected[sizeof plain];
        memset(expected, 0, sizeof expected);
        memcpy(expected, crypto_frame, sizeof crypto_frame);
        CHECK(memcmp(plain, expected, sizeof plain) == 0,
              "расшифрованный Initial разошёлся с CRYPTO-кадром и паддингом из RFC 9001 A.2");
    }
}

int main(void) {
    uint8_t initial_secret[32], cis[32];
    d2k_hkdf_extract(initial_salt, sizeof initial_salt, dcid, sizeof dcid, initial_secret);
    d2k_hkdf_expand_label(initial_secret, "client in", cis, sizeof cis);
    CHECK(memcmp(cis, want_cis, sizeof cis) == 0,
          "client_initial_secret не сошёлся с вектором RFC 9001 A.1");

    uint8_t key[16], iv[12], hp[16];
    d2k_hkdf_expand_label(cis, "quic key", key, sizeof key);
    d2k_hkdf_expand_label(cis, "quic iv",  iv,  sizeof iv);
    d2k_hkdf_expand_label(cis, "quic hp",  hp,  sizeof hp);
    CHECK(memcmp(key, want_key, sizeof key) == 0, "ключ не сошёлся с вектором");
    CHECK(memcmp(iv, want_iv, sizeof iv) == 0, "iv не сошёлся с вектором");
    CHECK(memcmp(hp, want_hp, sizeof hp) == 0, "hp не сошёлся с вектором");

    check_generic_vectors();
    check_hkdf_label_length_guard();
    check_rfc9001_a2_packet();

    if (fails) { printf("ПРОВАЛОВ: %d\n", fails); return 1; }
    printf("криптография: все проверки прошли\n");
    return 0;
}
