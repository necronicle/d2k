/* d2k_stun.h — STUN Binding: собрать запрос, узнать СВОЙ ответ.
 *
 * ЗАЧЕМ ЭТО В ПРОЕКТЕ ПРО ОБХОД DPI. Голосовой путь (voice/STUN, пункт 4
 * чеклиста) устроен иначе, чем подбор по домену, и разница начинается с
 * оракула. В TCP «прошло» доказывает ответ сервера, в QUIC его пришлось
 * выцарапывать из остаточной блокировки, потому что молчание в UDP имеет
 * четыре причины. У STUN оракул НАСТОЯЩИЙ: сервер отвечает, возвращая
 * увиденный им адрес, и ответ помечен идентификатором транзакции — тем
 * самым, который мы сами придумали. Совпадение идентификатора доказывает,
 * что ответил именно он, а не любой мусор, прилетевший на порт.
 *
 * СВЕРКА ИДЕНТИФИКАТОРА ОБЯЗАТЕЛЬНА, и это не педантизм. Датаграммный сокет
 * принимает всё, что пришло на порт; без сверки за доказательство «путь жив»
 * сошёл бы случайный пакет от постороннего сервиса. Тот же класс ошибки, что
 * в QUIC-зонде разбирался отдельно (см. qp_verify_server_response в
 * quicprobe.c): «похоже на ответ» не то же самое, что «ответ на наш вопрос».
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Ни MESSAGE-INTEGRITY, ни FINGERPRINT не проверяются:
 * первый требует общего пароля (у публичного Binding его нет — RFC 5389 §10),
 * второй защищает от путаницы с другими протоколами на том же порту, а от
 * подделки не защищает ни тот, ни другой в нашем случае. Обещать защиту,
 * которой нет, хуже, чем её не иметь. Атрибуты просто пропускаются — разбор
 * идёт по объявленным длинам с выравниванием в четыре байта (RFC 5389 §15).
 *
 * Векторы — RFC 5769 (официальные тестовые векторы STUN), §2.1, §2.2, §2.3.
 */
#ifndef D2K_STUN_H
#define D2K_STUN_H

#include <stddef.h>
#include <stdint.h>

#define D2K_STUN_TXID_LEN 12
#define D2K_STUN_HDR_LEN  20

/* Собирает Binding Request и выдаёт его идентификатор транзакции: по нему
 * потом опознаётся ответ. Идентификатор СВОЙ на каждый вызов — повторить его
 * значит не отличить ответ на прошлый вопрос от ответа на этот.
 *
 * Возвращает длину пакета (всегда D2K_STUN_HDR_LEN) или 0, если не поместился
 * либо не удалось взять случайные байты. */
size_t d2k_stun_request(uint8_t *out, size_t cap, uint8_t txid[D2K_STUN_TXID_LEN]);

/* Разбирает пришедшую датаграмму как Binding Response НА НАШ запрос.
 *
 * 0 — это ответ нам; -1 — нет (короткий, не ответ, без магической метки,
 * чужой идентификатор, противоречивые длины).
 *
 * *family — 4 или 6 по семейству адреса из XOR-MAPPED-ADDRESS, либо 0, если
 * адреса в ответе не было. НОЛЬ — НЕ ОТКАЗ: для оракула достаточно самого
 * факта ответа с нашим идентификатором, адрес — приятное дополнение. ip
 * обязан вмещать 16 байт; заполняются первые 4 или 16 по семейству. */
int d2k_stun_parse_response(const uint8_t *p, size_t n,
                            const uint8_t txid[D2K_STUN_TXID_LEN],
                            uint8_t *ip, int *family, uint16_t *port);

#endif /* D2K_STUN_H */
