/* d2k_verdict.h — дерево вердиктов: чем именно режут, если режут вообще.
 *
 * Порядок вопросов НЕСУЩИЙ, и каждый отсекает половину:
 *
 *   1. база (триггер целиком) — есть ли блокировка по содержимому вообще;
 *   2. разрез на первом байте — самый агрессивный разрез из возможных
 *      (в первом сегменте остаётся один-единственный байт). Не помог он —
 *      не поможет ни один разрез правее, и точку искать незачем;
 *   3. если разрез не помог — контроль ДРУГИМ именем на ту же цель: без
 *      него шаг 2 неотличим от «молчит вся линия», а не «режут наши байты».
 *
 * d2k НЕ утверждает «блокировка по адресу». Неудача этого конечного набора
 * вопросов не доказывает, что режут адрес: она доказывает только то, что
 * ЭТИХ вопросов не хватило, а сохранённое обратное утверждение мешало бы
 * честной повторной попытке завтра (§2.3). Соответствующий случай называется
 * D2K_V_INCONCLUSIVE и обязан говорить, чего именно не хватило (см. reason
 * в d2k_vres) — «вердикт без причины» человеку нечитаем.
 *
 * D2K_V_WHOLE в перечислении есть, но эта задача его не производит: он
 * зарезервирован под диагностику границы сигнатуры (разрез у самого конца —
 * донор называет это VerdictWholePacket), а дерево здесь останавливается на
 * трёх вопросах выше и вправо от разреза на 1 не смотрит — split на 1 годен
 * при любой границе правее, и обходу этого достаточно.
 *
 * ДОКАЗАТЕЛЬСТВОМ ПРОХОДА СЧИТАЕТСЯ ОТВЕТ СЕРВЕРА, А НЕ ЛЮБОЙ ВЕРНУВШИЙСЯ
 * БАЙТ. У триггера это только ServerHello, у контроля — любая запись TLS,
 * включая алерт (почему именно так — d2k_meas.h, приёмки). Коробка, убившая
 * наши байты, обычно не молчит: она инжектирует алерт или блок-страницу, и на
 * счёте «вернулось хоть что-то» такой ответ неотличим от чистой линии —
 * отсюда брались CLEAR и PREFIX, выведенные из ответа, которого коробка не
 * пропускала. Ответ, который приёмка не признала, НЕ выдаётся и за молчание:
 * это третье состояние (d2k_tally.unproven), и дерево делает из него третий
 * вывод — «вердикта нет», а не «решает содержимое».
 *
 * ВЕРДИКТ НЕ ВЫДАЁТ НЕИЗМЕРЕННОЕ ЗА ИЗМЕРЕННОЕ. Две оговорки обязательны и
 * живут в reason:
 *   - CLEAR на форме TLS 1.2 (и на неразобранной) — «обратное направление не
 *     проверено»: дерево меряет клиент → сервер, а в 1.2 сертификат едет
 *     открытым текстом, и коробка может пропустить запрос, убив ОТВЕТ (§6
 *     спеки; зонда обратного направления, ProbeResponse у донора, в d2k нет);
 *   - всякий вывод о РАЗРЕЗЕ (PREFIX, а равно и OPAQUE, где разрез не помог)
 *     называет паузу между кусками, на которой он снят: на другой паузе он
 *     может не повториться, а других дерево не задаёт.
 *
 * НЕПОМЕЧЕННЫЙ CLEAR НЕ ПРИНИМАЕТСЯ. Зонд без подтверждённой метки SO_MARK
 * идёт СКВОЗЬ наш собственный обход, а не мимо него (см. d2k_meas.h про
 * d2k_mark_hook) — «обходить нечего» в таком прогоне было бы
 * самоподтверждающимся: поиск закрылся бы ровно там, где обход и так
 * работает, сняв работающий план. Поэтому база, прошедшая все повторы БЕЗ
 * подтверждённой метки, даёт не CLEAR, а INCONCLUSIVE — с причиной, которая
 * называет это прямо.
 */
#ifndef D2K_VERDICT_H
#define D2K_VERDICT_H

#include <stdint.h>

#include "d2k_arm.h"
#include "d2k_meas.h"

typedef enum {
    D2K_V_CLEAR,        /* триггер целиком проходит с подтверждённой меткой — обходить нечего */
    D2K_V_PREFIX,       /* разрез на split_pos помогает — префиксный матчер без пересборки */
    D2K_V_WHOLE,        /* зарезервирован: матчеру нужен пакет целиком (см. шапку файла) */
    D2K_V_OPAQUE,       /* разрез не помогает, контроль другим именем проходит — решает содержимое */
    D2K_V_INCONCLUSIVE, /* вердикта нет: данных не хватило, см. reason */
    D2K_V_FLAKY,        /* измерению верить нельзя: разошлись повторы, сбоил транспорт, или мерить было структурно нечем — какой случай, см. reason */
    D2K_V_UNREACHABLE,  /* до цели нет даже TCP */
    /* ДВА КЛАССА, КОТОРЫХ ЗДЕСЬ НЕ БЫЛО, И ОБА — «ПЛАНОВ НЕ ПРЕДЛАГАТЬ».
     *
     * Прежнее дерево d2k их не различало и сливало в INCONCLUSIVE, то есть в
     * «данных не хватило» — а это приглашение планировщику перебирать
     * кандидатов. Оба случая обратные: данных хватило, и они говорят, что
     * десинк не поможет.
     *
     * ADDRESS — молчит и контроль на имени, за которое ручается оператор:
     * режут адрес, порт или сеть, содержимое ни при чём (донор: «никакая
     * стратегия десинка этого не снимает, ответ — туннель»).
     * RESPONSE — запрос проходит, режут ОТВЕТ: у TLS 1.2 сертификат едет
     * открытым текстом. Класс существует только там и лечится не разрезом
     * запроса. */
    D2K_V_ADDRESS,
    D2K_V_RESPONSE,
    /* ЕЩЁ ДВА КЛАССА, И ОБА ПРО QUIC. Оригинал («Поиск по домену», пакет
     * quicprobe) завёл их ровно затем, чтобы не выдавать за блокировку то,
     * что ею не является. До них оба схлопывались в INCONCLUSIVE, то есть в
     * «данных не хватило», — и планировщик честно шёл перебирать кандидатов
     * там, где перебирать нечего.
     *
     * NO_QUIC — путь жив (согласование версии отвечает), но на Initial не
     * отвечают НИ С НАШИМ именем, НИ С НЕЙТРАЛЬНЫМ. Самый вероятный смысл:
     * хост не обслуживает HTTP/3. На живом роутере таких целей десятки —
     * браузер ходит по QUIC ко всему подряд.
     *
     * LOCAL_ADDRESS — имя разрешается в приватный адрес: подменяют и роутер,
     * и AdGuard, и наш собственный редирект по хостлисту. Замер донора 04.09
     * на этой же линии: rutracker.org локально даёт 10.171.171.171, а 8.8.8.8
     * — 188.186.154.79. Объявить тут «режут адрес» значит быть неправым
     * полностью: провайдер ни при чём. */
    D2K_V_NO_QUIC,
    D2K_V_LOCAL_ADDRESS
} d2k_verdict;

/* Длина причины. 256 хватало, пока причина описывала только ВЫВОД; теперь она
 * обязана нести ещё и ОГОВОРКИ — чего этот вердикт НЕ мерил (обратное
 * направление у CLEAR на форме TLS 1.2, пауза между кусками у PREFIX). Самая
 * длинная причина дерева с оговоркой — clear на неразобранном виде
 * приветствия, 258 байт (замерено на самих строках в verdict.c; кириллица
 * в UTF-8 — два байта на букву), и в 256 она бы не поместилась.
 * Усечение snprintf съедает
 * ХВОСТ, то есть ровно оговорку: вердикт выглядел бы увереннее, чем он есть,
 * и притом молча. 384 — это 258 плюс запас на двузначные числа повторов. */
#define D2K_REASON_MAX 384

/* СВОЙСТВА КОРОБКИ, ИЗМЕРЕННЫЕ ВОПРОСНИКОМ QUIC.
 *
 * ЗАЧЕМ ОТДЕЛЬНОЙ СТРУКТУРОЙ, А НЕ ТЕКСТОМ В reason. Текст причины — 384
 * байта на весь вердикт, и семь исходов туда не помещаются даже в сокращении;
 * но дело не в размере. Свойство коробки — это ФАКТ, который читают машиной
 * (подбор плеча, сравнение с оригиналом, поле), а вытаскивать факт обратно
 * разбором человеческой фразы значит заводить второй, необъявленный формат.
 *
 * НОЛЬ ЗНАЧИТ «НЕ ИЗМЕРЕНО», И ЭТО НЕ ВКУСОВОЕ. d2k_vres везде заводится
 * memset'ом в ноль, и любая другая раскладка означала бы, что вердикт, до
 * вопросника не доживший (вход непригоден, путь мёртв, бюджет кончился),
 * молча утверждает «ни один приём не помогает» — то есть выдаёт собственную
 * неизмеренность за факт о коробке. Оригинал разводит эти два случая
 * указателем (*bool), здесь — значением 0.
 *
 * «НЕ ИЗМЕРЕНО» ставится и тогда, когда повторы РАЗОШЛИСЬ (2 из 3): у
 * датаграмм одиночная потеря — норма, а одиночный проход может быть и
 * везением (коробка под нагрузкой пропускает часть потоков — у GFW измерено
 * прямо). Свойство засчитывается только при единогласии. */
/* ТРАССА ВОПРОСНИКА: по строке на заданный вопрос.
 *
 * ЗАЧЕМ ОНА СВЕРХ СВОЙСТВ. Свойство отвечает «помог ли приём», трасса — «что
 * при этом видели»: сколько зондов ушло и сколько ответило. Разница не
 * академическая. Стенд 17.09 показал «взяли мусор» и молчание по остальным
 * шести, и по устройству игрушечного цензора один из шести обязан был взять;
 * из одних свойств отличить «приём не сработал» от «зонд не долетел по другой
 * причине» нельзя вовсе, а из трассы — видно. Ровно поэтому она есть у
 * оригинала (Result.Trace, probe.go) с самого начала.
 *
 * Размер фиксированный и маленький: трасса живёт внутри d2k_vres, который
 * копируется между потоками планировщика. */
#define D2K_QTRACE_MAX   8
/* 24 БАЙТА, А НЕ 16. Имена вопросов русские, и в UTF-8 «датаграммы» это 20
 * байт: при 16 snprintf обрубал их ПОСРЕДИ символа, и в журнал ехала битая
 * строка (поймано первым же прогоном стенда 17.09). Обрезка по байтам и
 * кириллица — давняя ловушка этого проекта, см. r-73.1. */
#define D2K_QLABEL_MAX  24

typedef struct {
    char    label[D2K_QLABEL_MAX]; /* имя вопроса; пустое — строка не занята */
    uint8_t sent;                  /* сколько зондов реально ушло на провод */
    uint8_t answered;              /* сколько подтверждённых ответов */
    int8_t  outcome;               /* D2K_PROP_* — как это легло в свойство */
} d2k_quic_step;

#define D2K_PROP_UNKNOWN 0
#define D2K_PROP_NO      1
#define D2K_PROP_YES     2

typedef struct {
    int8_t residual_blocking;
    int8_t residual_ignores_src_port;
    int8_t junk_ahead;      /* мусорная датаграмма перед Initial */
    int8_t fake_ahead;      /* фальшивый Initial с разрешённым именем перед своим */
    int8_t split_crypto;    /* приветствие двумя кадрами CRYPTO, хвост первым */
    int8_t split_datagrams; /* приветствие двумя датаграммами, хвост первой */
    int8_t version2;        /* тот же Initial во второй версии QUIC */
    int8_t clear_fixed_bit; /* погашенный фиксированный бит */
    int8_t low_source_port; /* исходный порт ниже порта назначения */
    int8_t longer;          /* датаграмма длиннее обычной */
    /* TTL, С КОТОРЫМ ПРИШЁЛ ОТВЕТ СЕРВЕРА. СЫРОЙ ФАКТ, БЕЗ ПЕРЕСЧЁТА В
     * РАССТОЯНИЕ, и это не осторожность: замер 04.09.2026 показал, что на один
     * и тот же адрес ICMP и QUIC отдают разные TTL (56 против 86; у Google 107
     * против 60) — отвечают РАЗНЫЕ УЗЛЫ, и «расстояние» из одного наблюдения
     * было бы выдуманным числом. Развёртка TTL приманки поэтому и остаётся
     * развёрткой (core/props.c), а не вычислением из этого поля.
     *
     * Ноль — не измерено. Нулевого TTL у дошедшего пакета не бывает: узел,
     * уменьшивший его до нуля, обязан пакет отбросить (RFC 791 §3.2). */
    uint8_t server_ttl_in;
} d2k_quic_props;

typedef struct {
    d2k_verdict verdict;
    char        reason[D2K_REASON_MAX]; /* заполняется ВСЕГДА и по-человечески — иначе вердикт нечитаем */
    int         split_pos;   /* точка разреза для D2K_V_PREFIX; 0, если разрез не предлагается */
    int         probes;      /* сколько опытов всего задействовал прогон (сумма по всем вопросам) */
    int         marked;      /* 1 — метка запрошена И подтверждена на каждом опыте прогона */
    /* НАЙДЕННОЕ ПЛЕЧО. Заполняется измерителем, который не только называет
     * класс блокировки, но и находит конкретное воздействие, её снимающее
     * (перенесённый «Поиск по домену», detect/). Прежнее дерево d2k такого не
     * возвращало вовсе: оно говорило «решает содержимое», а чем брать —
     * выяснял уже планировщик отдельными вопросами через датапат.
     *
     * have_arm=0 не различает «не найдено» и «этот поставщик лишь
     * классифицирует». Это различие хранится в owns_search: только для
     * старого классификатора допустим старый внешний подбор. */
    int         have_arm;
    /* This provider owns the whole domain-search workflow, including its
     * fallback probes. A missing arm is NOT permission for a second search. */
    int         owns_search;
    uint32_t    split_gap_us;
    d2k_arm     arm;
    d2k_arm_input arm_input;
    char        arm_name[64]; /* owned display name; adapter leaves arm.name NULL */
    /* Свойства коробки по QUIC (см. d2k_quic_props выше). Заполняет только
     * вопросник d2k_quic_classify; у всех прочих поставщиков вердикта поле
     * остаётся нулевым, что и означает «не измерено». */
    d2k_quic_props qprops;
    /* Трасса вопросника: заполняется по мере ЗАДАННЫХ вопросов, незаданные
     * строк не занимают (пустой label). */
    d2k_quic_step  qtrace[D2K_QTRACE_MAX];
} d2k_vres;

/* Задаёт вопросы дерева по порядку и выносит вердикт.
 *
 * trigger — снятое приветствие цели (не пересобирается, см. d2k_meas.h).
 * control — ДРУГОЕ имя на ТУ ЖЕ цель: контроль тем же именем не контроль
 *   вовсе (если само имя под блокировкой, молчать будут оба, и «режут
 *   адрес» получится из собственной ошибки ввода) — вызывающий отвечает за
 *   то, что control реально обслуживается этим сервером.
 * mark — метка SO_MARK для ВСЕХ опытов прогона (0 — не метить).
 * repeats — повторов на каждый заданный вопрос; <= 0 — то же умолчание
 *   (три), что и в d2k_meas, чтобы оба места не расходились по умолчанию.
 * gap_us — пауза между кусками разреза. Умолчания у неё нет НИГДЕ (см.
 *   d2k_meas.h): ноль означает ровно ноль, и вердикт об этом скажет. Боевое
 *   умолчание 60 мс (§7 спеки, WriteGap донора) ставит вызывающий.
 *
 * Вердикт только при единогласии: расхождение повторов на ЛЮБОМ вопросе
 * дерева — это D2K_V_FLAKY, а не округление в удобную сторону. */
d2k_vres d2k_classify(const char *ip, uint16_t port,
                       d2k_hello trigger, d2k_hello control,
                       uint32_t mark, int repeats,
                       uint32_t gap_us, uint32_t wait_ms);

#endif /* D2K_VERDICT_H */
