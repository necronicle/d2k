/* d2k_h3.h — HTTP/3 ровно настолько, чтобы получить код ответа.
 *
 * ЗАЧЕМ ТАК МАЛО. Зонду подтверждения нужен ОДИН факт: приложение ответило.
 * Для этого достаточно послать GET и прочитать `:status` из заголовков. Всё
 * остальное в HTTP/3 — тело, приоритеты, push, динамическая таблица QPACK —
 * зонду не нужно и потому не написано: неиспользуемый код нельзя ни
 * проверить, ни удержать в правде.
 *
 * QPACK БЕЗ ДИНАМИЧЕСКОЙ ТАБЛИЦЫ. Мы объявляем её ёмкость нулевой, значит
 * сервер не вправе на неё ссылаться (RFC 9204 §3.2.2), потоки кодировщика и
 * декодировщика не нужны вовсе, и подтверждать секции нечем. Это не
 * упрощение «пока»: зонд живёт один запрос, и таблица, которая учится, ему
 * не нужна никогда.
 */
#ifndef D2K_H3_H
#define D2K_H3_H

#include <stddef.h>
#include <stdint.h>

/* Содержимое КЛИЕНТСКОГО управляющего потока: его тип и пустой SETTINGS.
 * Открыть этот поток обязательно: сервер вправе закрыть соединение кодом
 * H3_MISSING_SETTINGS, и на замере это неотличимо от цензурного обрыва.
 * Возвращает длину. */
size_t d2k_h3_control(uint8_t *out, size_t cap);

/* Кадр HEADERS с запросом GET к host/path для потока запроса.
 * Возвращает длину или 0. */
size_t d2k_h3_request(const char *host, const char *path, uint8_t *out, size_t cap);

/* Ищет в принятых байтах потока запроса первый кадр HEADERS и достаёт из него
 * `:status`. 0 — статус найден и положен в *status; -1 — не найден.
 *
 * «Не найден» НЕ означает «ответа не было»: кадр мог не дойти целиком, а
 * статус — приехать способом, которого этот разбор не знает. Тогда уровень
 * доказательства не растёт, и это честнее догадки. */
int d2k_h3_status(const uint8_t *buf, size_t n, int *status);

#endif /* D2K_H3_H */
