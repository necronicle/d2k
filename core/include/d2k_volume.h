/* d2k_volume.h — проба на блокировку по объёму соединения.
 *
 * КЛАСС БЛОКИРОВКИ. Коробка пропускает рукопожатие и первые килобайты, а потом
 * рвёт установленный поток, набравший пару десятков килобайт. Разрезом
 * ClientHello он не лечится вовсе: режется не рукопожатие.
 *
 * ПОЧЕМУ ПРОБА, А НЕ НАБЛЮДЕНИЕ ЗА ЧУЖИМ ТРАФИКОМ. Наблюдение отвечает на
 * вопрос «этот хост сейчас режут?» и ошибается в обе стороны: горизонт
 * видимости датапата — первые пакеты соединения, и здоровая крупная загрузка
 * выглядит оттуда ровно как обрыв. Проба отвечает на другой вопрос — «есть ли
 * этот блок на ЭТОЙ линии к ЭТОЙ сети» — за секунды, на своей мишени, своим
 * объёмом и не трогая пользовательский трафик.
 *
 * ЗАЧЕМ ПРОБА ИДЁТ ПЕРВОЙ. Пока ответ неизвестен, вопрос «блокируют по имени
 * или по адресу» ЛЖЁТ: при блоке по объёму рукопожатие проходит с любым именем,
 * поток умирает и там и там, и ответ всегда получается «по адресу». Проба не
 * дополняет тот вопрос, а снимает его ложный ответ.
 *
 * Перенос internal/volume (Go) — не пересказ. Унаследовано, а не измерено
 * здесь: способ накачки исходящим объёмом и порог, ниже которого обрыв этому
 * классу не приписывается — из замера на этой же линии (z2k, 31.08.2026,
 * метод runnin4ik/dpi-detector).
 */
#ifndef D2K_VOLUME_H
#define D2K_VOLUME_H

#include <stddef.h>
#include <stdint.h>

/* Ступень лестницы объёма и число ступеней: накопленный объём растёт
 * 4, 8, 12 … 40 КБ и покрывает весь наблюдавшийся разброс обрыва. */
#define D2K_VOL_CHUNK  4000
#define D2K_VOL_STEPS  10

/* Ниже этого объёма обрыв нашим классом не считается. До двенадцати килобайт
 * соединения рвутся по десятку обычных причин, и вердикт был бы шумом, а не
 * измерением. */
#define D2K_VOL_MIN_KB 12

typedef enum {
    /* Мишень не ответила вовсе. Про линию не сказано ничего: это НЕ «блока
       нет». */
    D2K_VOL_UNREACHABLE = 0,
    /* Соединение умерло за порогом. Это наш класс. */
    D2K_VOL_CUT,
    /* Лестница пройдена целиком, соединение живо. */
    D2K_VOL_PASSED,
    /* Объём до порога не дорос: документ кончился раньше или обрыв случился
       слишком рано. Вердикта НЕТ, и выдавать это за «блока нет» нельзя. */
    D2K_VOL_SHORT
} d2k_vol_verdict;

typedef struct {
    d2k_vol_verdict verdict;
    int      at_kb;       /* накопленный объём, на котором всё кончилось */
    int      rtt_ms;      /* измеренный RTT до мишени */
    char     reason[160]; /* человеческая причина, заполняется всегда */
} d2k_vol_result;

/* Гоняет одну пробу исходящим объёмом: ip:port, имя sni предъявляется в TLS
 * (пустое — идём по адресу). plain != 0 — открытый HTTP, без рукопожатия;
 * отдельным параметром, а не выводом из номера порта, потому что связь «порт
 * 80 значит без TLS» верна для курируемого списка и неверна вообще.
 *
 * mark — метка SO_MARK (0 — не метить). Здесь она НУЖНА, в отличие от зонда
 * свойств: проба меряет ЛИНИЮ, а не работу плана, и уже поставленный план
 * исказил бы её. */
d2k_vol_result d2k_volume_probe(const char *ip, uint16_t port, const char *sni,
                                int plain, uint32_t mark);

const char *d2k_vol_verdict_name(d2k_vol_verdict v);

#endif /* D2K_VOLUME_H */
