/* d2k_catalog.h — каталог изученных DPI-коробок: чтение и запись файла,
 * который остаётся общим с панелью.
 *
 * ЗАЧЕМ СВОЙ РАЗБОР. Панель остаётся на Go отдельным процессом и только
 * читает catalog.json (спека §3, §10) — значит формат на диске не
 * меняется, и это ядро обязано читать и писать ИМЕННО его. Внешних
 * зависимостей у проекта нет и не будет, а формы, которые в файле
 * встречаются, ограничены шестью: объект, массив, строка, число,
 * true/false, null. Общего JSON внутри нет — есть ровно эта раскладка,
 * порождённая одним источником (internal/catalog/catalog.go, encoding/json
 * с MarshalIndent), и разбор написан под неё, а не под спецификацию JSON
 * целиком.
 *
 * ЧТО НЕ ХРАНИТСЯ КАК ПОЛЕ. У файла есть верхнеуровневые "schema" и
 * "updated" (internal/catalog/catalog.go: Catalog.Schema, Catalog.Updated),
 * но в d2k_catalog им нет соответствия. Это не потеря: schema — константа
 * 1 (SchemaVersion), другого значения Go никогда не пишет и сам не прочтёт
 * (store.go, readFile → Validate: несовпадение — отказ), а верхнеуровневый
 * updated Go при КАЖДОЙ записи перезаписывает текущим временем независимо
 * от того, что было прочитано (store.go, writeLocked: "s.cat.Updated =
 * now" — прочитанное значение в файл не возвращается никогда). Хранить
 * оба поля в этой структуре значило бы держать состояние, которое либо
 * всегда одно и то же (schema), либо всегда отбрасывается при записи
 * (updated) — d2k_catalog_load их пропускает при чтении так же, как любое
 * незнакомое поле, а d2k_catalog_save выводит "schema":1 и текущее время
 * заново на каждый вызов, воспроизводя то же поведение.
 *
 * ВРЕМЯ. В файле оно лежит строкой RFC 3339 с дробной долей секунды
 * ("2026-09-06T04:09:29.08957744Z" — время.Time.MarshalJSON, всегда UTC,
 * другие пояса эта раскладка не производит). Здесь оно хранится как целые
 * секунды эпохи Unix в int64_t: плавающей арифметики на роутере нет (нет
 * сопроцессора), а секундной точности достаточно всему, что каталог с
 * этим временем делает (давность записи, наличие подтверждения). При
 * записи время выводится обратно строкой того же вида (RFC 3339, суффикс
 * Z) — иначе Go на другом конце файл не разберёт, — но БЕЗ дробной доли:
 * она обрезается при чтении и не восстанавливается, это осознанная потеря
 * точности, а не ошибка округления.
 *
 * ПАМЯТЬ. Каталог живёт вне пакетного пути (правило "malloc запрещён"
 * относится к датапату, который держит каждый пакет), поэтому выделять
 * можно. Но d2kc (спека §3) — долгоживущий процесс, рассчитанный на
 * недели непрерывной работы, и утечка здесь калечит его так же, как
 * порча памяти калечила бы датапат: освобождение обязано идти СТРОГО
 * через d2k_catalog_free, и оно обязано быть чистым под ASan и
 * LeakSanitizer, включая пути отказа — незаконченный разбор освобождает
 * всё, что успел выделить (см. шапку catalog.c).
 *
 * ПЕРЕНОСИМОСТЬ. Это текстовый разбор побайтно по буферу — сборка
 * структуры из байт провода наложением сюда не относится (та оговорка
 * MIPS/ARM — про бинарные протоколы датапата), но многобайтовые числа всё
 * равно собираются явным сложением "v = v*10 + цифра", а не приведением
 * типов, и потому не зависят от выравнивания или порядка байт целевой
 * платформы.
 */
#ifndef D2K_CATALOG_H
#define D2K_CATALOG_H

#include <stddef.h>
#include <stdint.h>

/* Одна наблюдавшаяся примета коробки (см. internal/catalog/catalog.go,
 * Signal). kind — вид приметы ("rst", "volume", "repeat", "silent" в
 * реальных данных на 2026-09-07, но разбор не ограничивает набор:
 * незнакомый kind проходит как обычная строка). ttl_delta — знаковый:
 * разность TTL подделки и TTL сервера гуляет в обе стороны от маршрута. */
typedef struct {
    uint8_t  ttl;         /* абсолютный TTL подделанного пакета — примета коробки, не пары "коробка-сервер" */
    int      ttl_delta;   /* TTL_подделки − TTL_сервера: только наблюдение, в сравнение примет не входит */
    uint8_t  tos;
    uint16_t ipid;
    char     kind[24];
    int      volume;      /* килобайты, только для kind=="volume" */
    int      seen;        /* сколько раз примета встречена */
} d2k_cat_signal;

/* Отпечаток коробки: способ снятия (method) плюс до восьми примет.
 * Восемь — фиксированная ёмкость этой структуры (см. d2k_cat_fp.sig):
 * файл с бОльшим числом примет на одной коробке d2k_catalog_load отвергает
 * с причиной, а не обрезает молча. Наблюдаемый максимум на 2026-09-07 —
 * пять; запас в структуре есть, но он конечен так же, как в файле. */
typedef struct {
    int             method;
    d2k_cat_signal  sig[8];
    size_t          n_sig;
} d2k_cat_fp;

/* Проверенный план коробки (см. Plan). text — человекочитаемый текст
 * d2k-plan, не байты TLV: он остаётся тем же полем, что каноническую форму
 * порождает (см. план задачи и internal/plan), и не размером-ограничен —
 * выделяется на куче, владение у d2k_cat_plan, освобождается
 * d2k_catalog_free. */
typedef struct {
    char     id[40];
    char     proto[8];
    char    *text;
    int64_t  added;
    int      successes;
    int      enabled;
} d2k_cat_plan;

/* Подтверждённая привязка цели к плану (см. Binding).
 *
 * transport — поле, которого нет в Go-структуре (internal/catalog/catalog.go
 * Binding его не знает; Go-панель незнакомые поля молча пропускает при
 * разборе, поэтому совместимость односторонняя и этого достаточно — новый
 * файл читает только код, который про transport знает).
 *
 * Оно нужно потому, что у одной цели могут быть РАЗНЫЕ планы для TCP и для
 * QUIC (instagram.com отвечает на обоих транспортах, и подобранный план
 * обхода для них не обязан совпадать) — без различающего поля привязки по
 * этим двум транспортам легли бы под один и тот же ключ (kind+target) и
 * перетёрли бы друг друга. Тот же довод уже стоил структуре ключа потока в
 * датапате: d2k_key хранит proto ИМЕННО затем, что TCP- и QUIC-поток к
 * одному адресу с совпавшим портом иначе получили бы один ключ и делили бы
 * состояние (datapath/include/d2k_track.h, разбор про d2k_key.proto) — тот
 * же класс ошибки здесь предотвращён тем же приёмом.
 *
 * Значение — номер протокола IANA: 6 (TCP) или 17 (UDP/QUIC), как и в
 * d2k_key_make. Ноль — «не записано»: старые файлы, снятые до появления
 * этого поля, разбираются как есть (memset в parse_binding обнуляет
 * структуру до разбора, а старый файл ключ "transport" не содержит — поле
 * так и остаётся нулём). */
typedef struct {
    char     kind[8];      /* "name" | "addr" */
    char     target[256];
    char     plan_id[40];
    int      level;
    int64_t  confirmed;
    int      successes;
    int      enabled;
    uint8_t  transport;    /* 6 TCP, 17 UDP, 0 — не записано (старый файл) */
} d2k_cat_binding;

/* Изученная модель поведения одной DPI-коробки (см. Box). plans/binds —
 * массивы на куче переменной длины (в отличие от d2k_cat_fp.sig, здесь
 * реальные размеры — сотни привязок на коробку, см. testdata), растут по
 * мере разбора и освобождаются d2k_catalog_free. */
typedef struct {
    char             id[40];
    int64_t          created, updated;
    d2k_cat_fp       fp;
    d2k_cat_plan    *plans;
    size_t           n_plans;
    d2k_cat_binding *binds;
    size_t           n_binds;
} d2k_cat_box;

/* Весь каталог — то, что живёт в catalog.json целиком. */
typedef struct {
    d2k_cat_box *boxes;
    size_t       n_boxes;
} d2k_catalog;

/* Читает каталог из path. При успехе (0) *out заполнен и владеет всей
 * своей памятью — обязан быть освобождён через d2k_catalog_free, даже
 * если вызывающий дальше ничего с ним не делает. При отказе (не 0) *out
 * не требует освобождения: всё, что успело выделиться во время разбора,
 * уже освобождено ВНУТРИ этого вызова (см. шапку catalog.c про инвариант
 * "слот резервируется до разбора элемента"), а *out обнулён.
 *
 * err/errcap — причина отказа, человекочитаемая, заполняется ВСЕГДА при
 * отказе (err[0] гарантированно не 0) и никогда не молча: "не разобралось"
 * без объяснения нечитаемо тому, кто будет чинить (см. d2k_verdict.h про
 * тот же принцип у вердиктов). Незакрытая структура, число вне диапазона
 * своего поля, дробное число там, где ожидается целое, строка длиннее
 * буфера, отпечаток с более чем восемью приметами — всё это ОТКАЗ разбора
 * целиком, а не результат с потерянной частью: половинчатый каталог хуже
 * отсутствующего, потому что выглядит рабочим. */
int d2k_catalog_load(const char *path, d2k_catalog *out, char *err, size_t errcap);

/* Пишет каталог в path тем же видом, что производит Go (2-пробельный
 * отступ, тот же порядок ключей, время строкой RFC 3339 с суффиксом Z).
 * Файл создаётся/перезаписывается напрямую (fopen "w") — атомарность
 * записи (временный файл, fsync, rename, .prev) в контракт этой функции
 * не входит: она принадлежит вызывающему более высокого уровня (тому, кто
 * решает, КОГДА писать, — см. спеку про планировщик), а не самому
 * разбору. */
int d2k_catalog_save(const d2k_catalog *c, const char *path, char *err, size_t errcap);

/* Освобождает всё, чем владеет *c (тексты планов, массивы планов и
 * привязок в каждой коробке, массив коробок), и обнуляет *c. Безопасно
 * звать на NULL и на уже обнулённый каталог (в том числе дважды подряд) —
 * оба случая no-op, а не отказ. */
void d2k_catalog_free(d2k_catalog *c);

#endif /* D2K_CATALOG_H */
