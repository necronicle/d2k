/* d2k_net4.h — адресная арифметика IPv4: разбор, печать и «свой ли это адрес».
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Список приватных диапазонов нужен уже двум
 * измерителям — QUIC-дереву (имя, разрешённое в приватный адрес, — это
 * подмена на уровне DNS, а не блокировка провайдера) и голосовому пути (голос
 * идёт наружу, приватный адрес назначения означает чужой NAT или наш же
 * редирект). Второй экземпляр этого списка разошёлся бы с первым молча: обе
 * копии продолжали бы «работать», просто считая разное.
 *
 * Список не совпадает с RFC 1918 и это намеренно: 100.64/10 (RFC 6598)
 * приватным в смысле 1918 не считается, но за ним точно так же стоит чужой
 * NAT, и вывод про коробку провайдера там был бы выдумкой.
 */
#ifndef D2K_NET4_H
#define D2K_NET4_H

#include <stddef.h>
#include <stdint.h>

/* "192.168.1.117" -> адрес в СЕТЕВОМ порядке (как лежит в пакете).
 * 0 — разобрано, -1 — нет. Строгий: лишние символы, пустые октеты и значения
 * больше 255 отвергаются, а не обрезаются. */
int d2k_ip4_parse(const char *s, uint32_t *out);

/* Обратно в текст. Возвращает длину без нуля, 0 — не поместилось. */
size_t d2k_ip4_text(uint32_t ip_net, char *out, size_t cap);

/* 1 — адрес из диапазона, до которого провайдерская коробка физически не
 * участвует: петля (127/8), RFC 1918 (10/8, 172.16/12, 192.168/16),
 * link-local (169.254/16), CGNAT (100.64/10) и нулевой адрес. */
int d2k_ip4_private(uint32_t ip_net);

#endif /* D2K_NET4_H */
