/* d2k_link.h — связь с датапатом по управляющему сокету и порог успеха.
 *
 * Протокол не изобретается здесь: единственный источник истины —
 * datapath/include/d2k_ctl.h (кадры, номера событий и команд, коды
 * подтверждения). Этот заголовок только даёт разобранное представление
 * событий (d2k_ev) и функции, которые читают/пишут кадры по сокету —
 * побайтно, полями, тем же приёмом, что put_key в datapath/ctlsrv.c: наложение
 * структуры на буфер здесь запрещено ровно по той же причине, по которой оно
 * запрещено там (выравнивание, дыра, непереносимость).
 *
 * Ширина ключа НЕ зашивается числом. В этом проекте зашитая ширина уже
 * ломалась: когда в ключ добавили транспорт, нашлось шесть мест с литералом
 * 12, и их искали поштучно. Каноническая константа — D2K_KEY_WIRE_LEN
 * (datapath/include/d2k_ctlsrv.h) — используется в link.c напрямую; сюда,
 * в публичный заголовок, она не вынесена, потому что здесь не нужна ничья
 * реализация ключа, только его РАЗОБРАННЫЕ поля.
 */
#ifndef D2K_LINK_H
#define D2K_LINK_H

#include <stddef.h>
#include <stdint.h>

/* Номера событий/команд и коды подтверждения — оттуда же, откуда их берёт
 * датапат. d2k_ev.kind сравнивается с D2K_EV_*, d2k_link_next возвращает
 * ошибки, различимые по D2K_ACK_* через err (см. ниже). */
#include "d2k_ctl.h"

/* Разобранное событие датапата. Поля общие для всех видов события, но
 * заполнены только те, что данный вид события несёт (см. комментарии у
 * каждого поля и switch в link.c) — остальные явно занулены d2k_link_next,
 * а не оставлены мусором со стека.
 *
 * transport — ЕДИНСТВЕННОЕ, что различает TCP-поток и QUIC-поток к одному и
 * тому же адресу и порту (браузер гоняет их наперегонки, порты TCP и UDP —
 * независимые пространства нумерации, совпадение не запрещено ничем). Если
 * это поле потеряется при разборе, планы двух транспортов начнут перетирать
 * друг друга — и обнаружится это не сразу, а на живой линии.
 *
 * code/num переиспользуются по виду события — так же, как переиспользует их
 * тело события на проводе (см. d2k_ctl.h, комментарии к D2K_EV_SUSPECT/
 * D2K_EV_EXCHANGE/D2K_EV_ACK):
 *   D2K_EV_SUSPECT:  code — код причины (D2K_SUSPECT_* из d2k_journal.h);
 *                    num  — 0.
 *   D2K_EV_EXCHANGE: code — тип ПЕРВОЙ пришедшей TLS-записи (§8
 *                    спецификации) — НЕ порог успеха сам по себе, см.
 *                    seen_types и d2k_ev_has_appdata внизу файла; num —
 *                    сколько байт нагрузки пришло после приветствия;
 *                    seen_types — битовая маска ВСТРЕЧЕННЫХ типов записей,
 *                    бит (тип-20).
 *   D2K_EV_APPLIED/D2K_EV_REFUSED: только ключ — обе несут только ключ на
 *                    проводе (см. пуск event в ctlsrv.c: put_key и выход без
 *                    добавления байт), остальные поля нулевые.
 *   D2K_EV_ACK:      code — тип подтверждаемой команды (D2K_CMD_*);
 *                    num  — упаковка (ok<<8)|reason: старший из двух занятых
 *                    байт — признак успеха (0/1), младший — код причины
 *                    D2K_ACK_* (значим только при ok==0, как и на проводе).
 *                    Не отдельные поля структуры: контракт этой задачи не
 *                    даёт под ACK своих полей, а ok восстановим и без
 *                    упаковки (сервер, ctlsrv.c:ack(), при ok==1 всегда
 *                    шлёт reason==D2K_ACK_OK) — но полагаться на этот
 *                    инвариант молча означало бы читать код чужого модуля
 *                    как протокол, поэтому признак успеха везётся отдельным
 *                    байтом, как и на проводе.
 * Для D2K_EV_HELLO/D2K_EV_SUSPECT/D2K_EV_APPLIED/D2K_EV_REFUSED/D2K_EV_ACK
 * поля name/shape/shape_len значения не несут (name — пустая строка,
 * shape_len — 0). Для D2K_EV_SHAPE, наоборот, code/num/seen_types не несут
 * значения.
 *
 * seen_types добавлено сверх контракта брифа задачи, измеренной причиной:
 * code (тип ПЕРВОЙ записи с обратной стороны) на проводе — липкое поле
 * (session.c: fl->rev_first_type пишется один раз, "if (fl->rev_first_type
 * == 0)", и дальше не меняется). Обмен сообщается ДВАЖДЫ (там же, большой
 * комментарий у d2k_journal_add): когда обмен вообще пошёл, и отдельно —
 * когда впервые встретились прикладные данные (23), если они пришли НЕ
 * первой записью. Во ВТОРОМ таком событии code всё равно показывает старый
 * первый тип (например, 22) — проверка «код первой записи == 23» на нём
 * дала бы ложь, хотя прикладные данные только что пришли. Отличить это
 * может только маска встреченных типов (rev_types/d_tos на проводе,
 * ctlsrv.c) — вот она и seen_types, а порог, который её читает, —
 * d2k_ev_has_appdata (внизу файла). Проверено на настоящем ctlprobe (см.
 * test_link.c: hello + два reply — 22, потом 23 — на одном потоке). */
typedef struct {
    uint16_t kind;          /* D2K_EV_* */
    uint8_t  low_ip[4], high_ip[4];
    uint16_t low_port, high_port;
    uint8_t  transport;     /* 6 TCP, 17 UDP — см. большой комментарий выше */
    uint16_t code;          /* SUSPECT: причина; EXCHANGE: тип TLS-записи; ACK: тип команды */
    uint32_t num;           /* EXCHANGE: сколько байт; ACK: (ok<<8)|reason */
    uint8_t  seen_types;    /* EXCHANGE: маска встреченных типов, бит (тип-20) */
    /* SUSPECT: чем подозрительный пакет отличался от остальных в этом же
     * потоке. Из этих байт складывается ОТПЕЧАТОК коробки, и без них каталог
     * хранил бы факт «был сброс», по которому одну коробку от другой не
     * отличить (datapath/ctlsrv.c, ветка D2K_JRN_SUSPECT — дословно та же
     * причина). До 11.09 разбор события их молча отбрасывал: на проводе
     * шесть байт, читался один. Значимы только при kind == D2K_EV_SUSPECT;
     * остальные события их зануляют, как и прочие чужие поля. */
    uint8_t  ttl;           /* TTL самой подделки — примета коробки */
    uint8_t  ref_ttl;       /* TTL сервера из ЭТОГО ЖЕ потока — ориентир */
    uint8_t  tos;
    uint16_t ipid;
    char     name[256];     /* HELLO: имя цели, NUL-терминировано */
    uint8_t  shape[2048];   /* SHAPE: байты приветствия */
    size_t   shape_len;
} d2k_ev;

/* Открывает клиентское подключение к управляющему сокету датапата (AF_UNIX,
 * путь sock_path). Возвращает fd >= 0 при успехе, -1 при отказе с причиной в
 * err. Гонки с сервером, который ещё не вызвал accept(), здесь нет: слушающий
 * сокет уже поставлен в очередь (backlog) к моменту, когда датапат готов
 * принимать подключения, — connect() на AF_UNIX не ждёт accept() на другой
 * стороне, только listen(). */
int  d2k_link_open(const char *sock_path, char *err, size_t errcap);
void d2k_link_close(int fd);

/* Читает и разбирает ОДНО событие. Кадр читается по длине (заголовок, потом
 * ровно объявленное число байт тела) — заголовок из потока не обязан прийти
 * одним чтением, и разбор, который на это надеется, ломается ровно тогда,
 * когда событие большое (например, D2K_EV_SHAPE).
 *
 * wait_ms — сколько ждать ПОЯВЛЕНИЯ события, той же семантики, что и у
 * poll(2): отрицательное значение — ждать неограниченно, 0 — не ждать вовсе,
 * положительное — потолок в миллисекундах. Если за это время не пришло ни
 * байта — возвращает 1, и это НЕ ошибка: событие — сообщение, а не
 * обязательство (см. d2k_ctl.h), датапату нечего было послать. Если событие
 * НАЧАЛО приходить (первый байт получен), дальнейшее чтение кадра целиком
 * ждёт не ограничиваясь wait_ms — на локальном сокете между двумя нашими же
 * процессами кадр, начавшийся приходить, но не дописанный, это не тайм-аут, а
 * порванное соединение или протокольная ошибка, и вернётся -1.
 *
 * Возвращает: 0 — событие разобрано и лежит в *out; 1 — тайм-аут, событий не
 * было; -1 — ошибка (причина в err), в том числе рванное соединение и
 * невозможная длина кадра. */
int  d2k_link_next(int fd, d2k_ev *out, int wait_ms, char *err, size_t errcap);

/* Ставит план на имя цели: команда D2K_CMD_SET_NAME (длина имени, имя, план
 * TLV). plan_text — план в HEX (та же условность, что и везде в этом дереве
 * для двоичных вставок в текстовый протокол — см. datapath/ctlprobe.c,
 * команда "raw <hex>"): пустая строка — законный вход, ноль байт плана, и
 * ЭТО сервер отклонит причиной D2K_ACK_BAD_PLAN (d2k_plan_load отказывает
 * плану короче заголовка) — отказ принадлежит серверу, а не этой функции.
 *
 * transport (6 TCP, 17 UDP) проверяется здесь, потому что это единственное,
 * что о нём известно СЕГОДНЯ: команда D2K_CMD_SET_NAME на проводе не несёт
 * отдельного поля транспорта (см. d2k_ctl.h — тело буквально "длина имени,
 * имя, план TLV", проверено также по ЖИВОМУ разбору в ctlsrv.c:
 * d2k_ctlsrv_command), а таблица планов датапата ищет только по имени или
 * адресу, транспорт в поиске не участвует (d2k_plans.h). Это ограничение
 * СЕГОДНЯШНЕГО протокола, названное так же прямо в спецификации (§6:
 * «Сегодня ключ только имя или адрес, и телевизор перезаписал бы план
 * браузеру») — не то, что эта функция недоделывает. Значит транспорт здесь
 * ТОЛЬКО проверяется (6 или 17, отказ иначе) и никуда не отправляется: не
 * выдумывать для него место в кадре, которого протокол не даёт.
 *
 * Функция ТОЛЬКО отправляет команду (0 — ушла, -1 — отказ с причиной в err,
 * включая невалидные аргументы) и не ждёт подтверждения: D2K_EV_ACK приходит
 * тем же путём, что и любое другое событие, — через d2k_link_next в общем
 * цикле вызывающего. Ждать ack здесь означало бы читать чужой сокет за
 * спиной этого цикла и рисковать украсть у него событие (например,
 * D2K_EV_SHAPE, которое сервер может прислать ПЕРЕД ack на ARM_SHAPE, см.
 * d2k_link_arm_shape). */
int  d2k_link_set_name(int fd, const char *name, uint8_t transport,
                       const char *plan_text, char *err, size_t errcap);

/* Взводит ловушку формы приветствия для имени цели: команда
 * D2K_CMD_ARM_SHAPE. Как и d2k_link_set_name, только отправляет команду и не
 * ждёт ack — по той же причине: сервер может ответить формой (D2K_EV_SHAPE)
 * НЕМЕДЛЕННО, если она уже поймана (см. d2k_ctlsrv_command в ctlsrv.c), и это
 * событие придёт РАНЬШЕ ack на саму команду ARM_SHAPE — забирать его должен
 * вызывающий через d2k_link_next, а не эта функция впустую. */
int  d2k_link_arm_shape(int fd, const char *name, char *err, size_t errcap);

/* Снимает план с имени цели: команда D2K_CMD_DEL_NAME. Тело на проводе такое
 * же, как у ARM_SHAPE (длина имени u8, имя — d2k_ctl.h), поэтому и код тот
 * же с точностью до кода команды. Как и обе соседние функции, ТОЛЬКО
 * отправляет команду и не ждёт ack — по той же причине (см. выше).
 *
 * Зачем понадобилась: d2k_props_ask ставит план-КАНДИДАТ на каждый вопрос и
 * до этой функции не снимала последний из них. Пока вопрос проходит, это не
 * дефект, а замысел (прошедший план и есть стратегия — см. шапку compose.c
 * про двойное назначение), но когда НЕ прошёл ни один, на боевом датапате
 * оставался стоять план, про который измерение прямо сказало «не работает».
 * Отличие от D2K_CMD_CLEAR: CLEAR сносит ВСЮ таблицу, включая планы чужих
 * целей, которые никто не просил трогать. */
int  d2k_link_del_name(int fd, const char *name, char *err, size_t errcap);

/* Типы TLS-записей, встречающиеся в EXCHANGE (§8 спецификации,
 * docs/spec/2026-09-06-c-engine-design.md). Это НЕ протокол управляющего
 * сокета — датапат здесь только наблюдает чужой протокол (TLS, RFC 8446
 * §5.1) и передаёт увиденные типы дальше; названы для читаемости, тем же
 * приёмом, что TLSChangeCipherSpec/TLSAlert/TLSHandshake/TLSAppData в
 * internal/control/control.go. */
#define D2K_TLS_CHANGE_CIPHER_SPEC 20
#define D2K_TLS_ALERT              21
#define D2K_TLS_HANDSHAKE          22
#define D2K_TLS_APPLICATION_DATA   23

/* Порог успеха (§8) — НА СОБЫТИИ, а не на голом числе типа записи. Зеркало
 * Go-донора (internal/control/control.go):
 *
 *     func (e Event) HasAppData() bool {
 *         return e.SeenTypes&(1<<(TLSAppData-20)) != 0
 *     }
 *
 * — того же порога, применённого в трёх местах контроллера (controller.go,
 * строки 1022/1041/1238). Свободной функции «успех по одному типу записи» у
 * донора нет вовсе: это проверено, не предположено.
 *
 * Раньше здесь стояла d2k_success(uint16_t) — принимала голый тип записи, а
 * не разобранное событие. Ревью нашло, чем это опасно: seen_types объявлено
 * uint8_t, молча продвигается до uint16_t и прошло бы в такую функцию БЕЗ
 * единого предупреждения компилятора — сравнивая битовую МАСКУ с одним
 * ЗНАЧЕНИЕМ типа записи, что почти всегда ложно. Две вещи, которые в точке
 * вызова компилятору нечем отличить друг от друга, — не два равноправных
 * способа спросить про успех, а ловушка; убрана, порог живёт только здесь.
 *
 * Успех — прикладной обмен (тип 23), а не любые вернувшиеся байты и не тип
 * ПЕРВОЙ записи (см. большой комментарий у seen_types про липкое поле code
 * в d2k_ev выше): семь байт, засчитанные донором за обмен по Дискорду, — это,
 * вероятнее всего, ровно 7-байтовый TLS Alert (заголовок записи 5 байт + 2
 * байта тела), то есть отказ, а не успех. Ограничение донора «проверяет
 * начало сообщения, а не завершённый сеанс» сюда не переносится (названо
 * дефектом в §8) — seen_types растёт по мере прихода записей, а не застывает
 * на первой, и порог обязан читать именно его. */
int d2k_ev_has_appdata(const d2k_ev *ev);

#endif /* D2K_LINK_H */
