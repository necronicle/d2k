/* d2k_meas.h — оракул: чем «прошло» отличается от «убито».
 *
 * ПОБАЙТНЫЙ ПОВТОР, И ЭТО НЕСУЩЕЕ РЕШЕНИЕ. Приветствие не конструируется и не
 * пересобирается: берутся байты, снятые датапатом с настоящего клиента, и
 * повторяются как есть. Форма приветствия — измерительный прибор, коробка
 * решает по ней; самодельные байты меряют не ту коробку, что видит человек.
 *
 * Замер 06.09.2026 стоил каталога: зонд с самодельным приветствием на 93 байта
 * записал плану уровень 3 и 4796 «успехов», а настоящий клиент через тот же
 * план получал сброс мгновенно.
 */
#ifndef D2K_MEAS_H
#define D2K_MEAS_H

#include <stddef.h>
#include <stdint.h>

/* Снятое приветствие. Владение байтами остаётся у вызывающего. */
typedef struct {
    const uint8_t *bytes;
    size_t         len;
} d2k_hello;

/* Итог серии повторов.
 *
 * marked — встала ли метка на КАЖДОМ дозвоне серии. Один непомеченный дозвон
 * делает всю серию непомеченной: вердикт, снятый наполовину мимо нашего
 * обхода, наполовину сквозь него, не описывает ни линию, ни обход. */
typedef struct {
    int pass;
    int fail;
    int marked;
    int err;
} d2k_tally;

/* Один опыт: послать приветствие, разрезав в заданных местах, и посмотреть,
   вернулось ли что-нибудь. Возвращает 1 — вернулось, 0 — нет, -1 — опыт не
   состоялся (нет транспорта). */
int d2k_meas_once(const char *ip, uint16_t port, d2k_hello h,
                  const size_t *cuts, size_t n_cuts,
                  uint32_t gap_us, uint32_t wait_ms,
                  uint32_t mark, int *marked_out);

/* Серия повторов. Вердикт выносит вызывающий: здесь только счёт. */
d2k_tally d2k_meas(const char *ip, uint16_t port, d2k_hello h,
                   const size_t *cuts, size_t n_cuts,
                   uint32_t gap_us, uint32_t wait_ms,
                   uint32_t mark, int repeats);

#endif /* D2K_MEAS_H */
