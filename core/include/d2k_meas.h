/* d2k_meas.h — оракул: чем «прошло» отличается от «убито».
 *
 * ПОБАЙТНЫЙ ПОВТОР, И ЭТО НЕСУЩЕЕ РЕШЕНИЕ. Приветствие не конструируется и не
 * пересобирается: берутся байты, снятые датапатом с настоящего клиента, и
 * повторяются как есть. Форма приветствия — измерительный прибор, коробка
 * решает по ней; самодельные байты меряют не ту коробку, что видит человек.
 *
 * Замер 06.09.2026 стоил каталога: зонд с самодельным приветствием на 93 байта
 * записал плану уровень 3 и 4796 «успехов», а настоящий клиент через тот же
 * план получал сброс мгновенно.
 */
#ifndef D2K_MEAS_H
#define D2K_MEAS_H

#include <stddef.h>
#include <stdint.h>

/* Снятое приветствие. Владение байтами остаётся у вызывающего. */
typedef struct {
    const uint8_t *bytes;
    size_t         len;
} d2k_hello;

/* ПРИЁМКА: чем доказывается, что приветствие ДОШЛО.
 *
 * Доказательством прохода считается ОТВЕТ СЕРВЕРА, а не любой вернувшийся
 * байт (§8 спеки, docs/spec/2026-09-06-c-engine-design.md: «Успехом
 * считается прикладной обмен, а не любые вернувшиеся байты»). Коробка,
 * убившая наши байты, обычно не молчит: она инжектирует фатальный алерт или
 * блок-страницу — ответ есть, а имя не прошло. Засчитав его, мы объявили бы
 * блокировку обходом (acceptServerHello, internal/classify/trigger.go
 * донора), и вердикт о коробке выводился бы из ответа, которого коробка не
 * пропускала.
 *
 * Возвращает 1, если байты признаны доказательством, иначе 0. Буфер — то,
 * что реально пришло ПЕРВЫМ чтением, без дочитывания: рукопожатие здесь
 * никогда не доводится до конца (§5 спеки), нужна ровно первая запись.
 *
 * ПАРАМЕТРОМ, А НЕ ГЛОБАЛЬНЫМ ХУКОМ — в отличие от d2k_mark_hook ниже.
 * Метка одна на весь прогон, а приёмок в одном прогоне ДВЕ и разные: у
 * триггера — только ServerHello, у контроля — любая запись TLS (см. ниже).
 * Глобальная точка подмены сделала бы их общим состоянием, и вопрос
 * «а какая приёмка стояла на этом опыте» пришлось бы восстанавливать по
 * порядку вызовов. */
typedef int (*d2k_accept_fn)(const uint8_t *buf, size_t len);

/* ТРИГГЕР: доказательством считается ТОЛЬКО ServerHello — запись TLS типа 22
 * (handshake), у которой первый байт тела 0x02 (server_hello). Алерт сюда не
 * годится, хотя это тоже ответ: его инжектируют и сами коробки. */
int d2k_accept_serverhello(const uint8_t *buf, size_t len);

/* КОНТРОЛЬ: годится ЛЮБАЯ запись TLS, включая алерт. Контроль отвечает не на
 * вопрос «прошло ли имя», а на вопрос «жива ли линия»: сервер, отвечающий
 * отказом на незнакомое имя, — это всё равно сервер, до которого дошли
 * (ControlTrigger, internal/classify/trigger.go донора). А вот тишина
 * означает, что не дошло ничего, и тогда дело не в содержимом. */
int d2k_accept_tls_record(const uint8_t *buf, size_t len);

/* ЧУЖОЙ ПРОТОКОЛ: годится любой непустой ответ. Для триггера, который не
 * является записью TLS вовсе (пролог WhatsApp, сырые байты из дампа),
 * разбирать чужой протокол ради вердикта незачем — важно лишь, ответил
 * сервер или промолчал (RawTrigger, там же у донора). */
int d2k_accept_any(const uint8_t *buf, size_t len);

/* Исход ОДНОГО опыта. Три состояния, а не два: «ответ пришёл, но приёмка его
 * не признала» — это НЕ «не пришло ничего». Слить их значило бы объявить
 * молчание линии там, где линия ответила, а на молчании и ответе дерево
 * вердиктов делает разные выводы (§2.4, тройственная логика: «не измерено»
 * не подделывается «нет»-ом). */
typedef enum {
    D2K_MEAS_ERR      = -1, /* опыт не состоялся: нет транспорта или негодный вход */
    D2K_MEAS_SILENT   =  0, /* не пришло ничего: тишина, сброс, обрыв */
    D2K_MEAS_PASS     =  1, /* пришло и признано приёмкой */
    D2K_MEAS_UNPROVEN =  2  /* пришло, но приёмка не признала доказательством */
} d2k_meas_outcome;

/* Итог серии повторов.
 *
 * marked — встала ли метка на КАЖДОМ дозвоне серии. Один непомеченный дозвон
 * делает всю серию непомеченной: вердикт, снятый наполовину мимо нашего
 * обхода, наполовину сквозь него, не описывает ни линию, ни обход.
 *
 * fail — всё, что не pass; err и unproven — его ПОДМНОЖЕСТВА (тот же
 * порядок, что уже описан для err в d2k_quicprobe.h). Молчание отдельным
 * полем не считается: оно выводится как fail - err - unproven, и заводить на
 * него четвёртый счётчик значило бы хранить одно и то же число дважды. */
typedef struct {
    int pass;
    int fail;
    int marked;
    int err;
    int unproven;
} d2k_tally;

/* Один опыт: послать приветствие, разрезав в заданных местах, и посмотреть,
 * что вернулось. Возвращает одно из d2k_meas_outcome.
 *
 * accept — приёмка (см. выше). NULL означает «любой непустой ответ», как
 * пустой Accept у донора; молчаливого «любые байты сойдут» по умолчанию тут
 * нет нигде, кроме этого явного NULL.
 *
 * gap_us — пауза между кусками разреза. УМОЛЧАНИЯ У НЕЁ НЕТ, и это отличает
 * её от wait_ms: ноль означает ровно ноль, куски уходят вплотную. Тихо
 * подставить сюда «разумное» число значило бы провести не тот опыт, который
 * просили, — тот же грех, что ужать точку разреза до длины (см. контракт
 * ниже). Боевое умолчание 60 мс (§7 спеки, у донора WriteGap в withDefaults)
 * — свойство ВЫЗЫВАЮЩЕГО, и вызывающий, который его не поставил, обязан
 * сказать это в вердикте, а не подразумевать (см. d2k_verdict.h).
 *
 * Контракт точек разреза: cuts[0] < cuts[1] < ... < cuts[n_cuts-1], и каждая
 * строго внутри длины приветствия (0 < cuts[i] < h.len). Нарушение — не повод
 * молча ужать точку до длины или пропустить немонотонную: тихая подмена
 * запрошенного разреза на похожий ничем не отличается от пересборки
 * приветствия, которую этот модуль отвергает принципиально (см. шапку
 * файла). При нарушении контракта опыт не проводится вовсе. */
int d2k_meas_once(const char *ip, uint16_t port, d2k_hello h,
                  const size_t *cuts, size_t n_cuts,
                  uint32_t gap_us, uint32_t wait_ms,
                  uint32_t mark, d2k_accept_fn accept, int *marked_out);

/* Серия повторов. Вердикт выносит вызывающий: здесь только счёт. */
d2k_tally d2k_meas(const char *ip, uint16_t port, d2k_hello h,
                   const size_t *cuts, size_t n_cuts,
                   uint32_t gap_us, uint32_t wait_ms,
                   uint32_t mark, d2k_accept_fn accept, int repeats);

/* Точка подмены для тестов на И-семантику метки. Настоящая установка
 * SO_MARK требует CAP_NET_ADMIN и без этого права всегда проваливается —
 * тест на «один непомеченный дозвон гасит метку всей серии» обязан
 * утверждать одно и то же от root и от обычного пользователя, а не зависеть
 * от привилегии процесса, который его запустил (тот же приём, что markFunc
 * в internal/classify/measure.go, и по той же причине). По умолчанию
 * указывает на настоящую попытку; возвращает 0 при успехе, как setsockopt. */
typedef int (*d2k_mark_fn)(int fd, uint32_t mark);
extern d2k_mark_fn d2k_mark_hook;

/* Потолок ОДНОЙ блокирующей записи (SO_SNDTIMEO), секунды. Восемь — не «на
 * глаз»: то же число уже стоит в internal/classify/measure.go как
 * connectTimeout и transportCeiling, а туда пришло из
 * internal/volume/probe.go и из пробы донора z2k-detect/internal/tcp16, где
 * было задано замером на этой линии.
 *
 * Переменная, а не #define: короткая запись как НАБЛЮДАЕМОЕ последствие —
 * это задокументированный побочный эффект истечения именно этого таймаута
 * при недренирующем приёмнике, а не отдельная кнопка API. Тесту нужно
 * дождаться реального истечения, чтобы увидеть короткую запись, а ждать
 * восемь секунд в каждом прогоне `make check` ради одной проверки — плохой
 * компромисс. Тест уменьшает значение на время своего блока и обязан вернуть
 * его обратно. */
extern uint32_t d2k_send_timeout_s;

#endif /* D2K_MEAS_H */
