/* d2k_meas.h — оракул: чем «прошло» отличается от «убито».
 *
 * ПОБАЙТНЫЙ ПОВТОР, И ЭТО НЕСУЩЕЕ РЕШЕНИЕ. Приветствие не конструируется и не
 * пересобирается: берутся байты, снятые датапатом с настоящего клиента, и
 * повторяются как есть. Форма приветствия — измерительный прибор, коробка
 * решает по ней; самодельные байты меряют не ту коробку, что видит человек.
 *
 * Замер 06.09.2026 стоил каталога: зонд с самодельным приветствием на 93 байта
 * записал плану уровень 3 и 4796 «успехов», а настоящий клиент через тот же
 * план получал сброс мгновенно.
 */
#ifndef D2K_MEAS_H
#define D2K_MEAS_H

#include <stddef.h>
#include <stdint.h>

/* Снятое приветствие. Владение байтами остаётся у вызывающего. */
typedef struct {
    const uint8_t *bytes;
    size_t         len;
} d2k_hello;

/* Итог серии повторов.
 *
 * marked — встала ли метка на КАЖДОМ дозвоне серии. Один непомеченный дозвон
 * делает всю серию непомеченной: вердикт, снятый наполовину мимо нашего
 * обхода, наполовину сквозь него, не описывает ни линию, ни обход. */
typedef struct {
    int pass;
    int fail;
    int marked;
    int err;
} d2k_tally;

/* Один опыт: послать приветствие, разрезав в заданных местах, и посмотреть,
 * вернулось ли что-нибудь. Возвращает 1 — вернулось, 0 — нет, -1 — опыт не
 * состоялся: нет транспорта ИЛИ нарушен контракт точек разреза.
 *
 * Контракт точек разреза: cuts[0] < cuts[1] < ... < cuts[n_cuts-1], и каждая
 * строго внутри длины приветствия (0 < cuts[i] < h.len). Нарушение — не повод
 * молча ужать точку до длины или пропустить немонотонную: тихая подмена
 * запрошенного разреза на похожий ничем не отличается от пересборки
 * приветствия, которую этот модуль отвергает принципиально (см. шапку
 * файла). При нарушении контракта опыт не проводится вовсе. */
int d2k_meas_once(const char *ip, uint16_t port, d2k_hello h,
                  const size_t *cuts, size_t n_cuts,
                  uint32_t gap_us, uint32_t wait_ms,
                  uint32_t mark, int *marked_out);

/* Серия повторов. Вердикт выносит вызывающий: здесь только счёт. */
d2k_tally d2k_meas(const char *ip, uint16_t port, d2k_hello h,
                   const size_t *cuts, size_t n_cuts,
                   uint32_t gap_us, uint32_t wait_ms,
                   uint32_t mark, int repeats);

/* Точка подмены для тестов на И-семантику метки. Настоящая установка
 * SO_MARK требует CAP_NET_ADMIN и без этого права всегда проваливается —
 * тест на «один непомеченный дозвон гасит метку всей серии» обязан
 * утверждать одно и то же от root и от обычного пользователя, а не зависеть
 * от привилегии процесса, который его запустил (тот же приём, что markFunc
 * в internal/classify/measure.go, и по той же причине). По умолчанию
 * указывает на настоящую попытку; возвращает 0 при успехе, как setsockopt. */
typedef int (*d2k_mark_fn)(int fd, uint32_t mark);
extern d2k_mark_fn d2k_mark_hook;

/* Потолок ОДНОЙ блокирующей записи (SO_SNDTIMEO), секунды. Восемь — не «на
 * глаз»: то же число уже стоит в internal/classify/measure.go как
 * connectTimeout и transportCeiling, а туда пришло из
 * internal/volume/probe.go и из пробы донора z2k-detect/internal/tcp16, где
 * было задано замером на этой линии.
 *
 * Переменная, а не #define: короткая запись как НАБЛЮДАЕМОЕ последствие —
 * это задокументированный побочный эффект истечения именно этого таймаута
 * при недренирующем приёмнике, а не отдельная кнопка API. Тесту нужно
 * дождаться реального истечения, чтобы увидеть короткую запись, а ждать
 * восемь секунд в каждом прогоне `make check` ради одной проверки — плохой
 * компромисс. Тест уменьшает значение на время своего блока и обязан вернуть
 * его обратно. */
extern uint32_t d2k_send_timeout_s;

#endif /* D2K_MEAS_H */
