/* d2k_quichello.h — ПРИВЕТСТВИЕ QUIC С ДРУГИМ ИМЕНЕМ, СОБРАННОЕ ИЗ СНЯТОГО.
 *
 * ЗАЧЕМ. Дерево вопросов по QUIC (d2k_quic_classify, d2k_quicprobe.h) первым
 * делом спрашивает КОНТРОЛЬНЫМ именем: отвечает ли эта цель вообще, если имя
 * заведомо никого не интересует. Без этого вопроса «наше имя молчит» не
 * значит ничего — молчать может линия, сервер, наш же сокет.
 *
 * У TLS контроль собирается из профиля (d2k_hello_from_profile): профиль —
 * снятые с настоящего клиента байты, в которых имя заменено меткой. Для QUIC
 * такого профиля нет и быть не должно: Initial — это ЗАШИФРОВАННЫЙ пакет, и
 * «профиль» пришлось бы хранить вместе с ключами и номером пакета, то есть
 * хранить не форму приветствия, а чужую сессию целиком.
 *
 * Поэтому контроль собирается из ТОГО ЖЕ снимка, которым меряют цель:
 * приветствие расшифровывается своими же ключами (они выводятся из открытого
 * DCID, RFC 9001 §5.2), имя в нём заменяется, и пакет собирается заново. Всё,
 * кроме имени и идентификаторов соединения, остаётся байт в байт тем же, что
 * послал клиент, — а это ровно то, чего требует §4 спецификации: коробка
 * сличает форму клиентского приветствия, и мерить надо ею.
 *
 * ЧТО МЕНЯЕТСЯ, КРОМЕ ИМЕНИ, и почему иначе нельзя:
 *
 *   DCID и SCID — СВЕЖИЕ, той же длины. Повторить чужой DCID значит послать
 *   серверу второй Initial ЕГО ЖЕ соединения: для него это не новый вопрос, а
 *   странность в уже идущем рукопожатии, и ответ (или молчание) сказал бы про
 *   состояние той сессии, а не про путь.
 *
 *   Номер пакета — 0, и это не упрощение: у нового соединения он и есть
 *   нулевой.
 *
 *   Кадры — один CRYPTO со смещением 0 и добивка PADDING. Снятая датаграмма
 *   могла нести их иначе (несколько CRYPTO, PING, порядок), и это отличие
 *   объявлено прямо, а не спрятано: форма ПРИВЕТСТВИЯ сохранена побайтно,
 *   форма КАДРОВ — нет. Раскладка кадров — как раз то, что МЕНЯЕТ один из
 *   вопросов (D2K_QASK_SPLIT_CRYPTO), и менять её можно именно потому, что
 *   она и так не совпадает со снимком.
 *
 * ГРАНИЦА, КОТОРУЮ ВАЖНО ЗНАТЬ. Приветствие, не поместившееся в одну
 * датаграмму (браузер с постквантовым key_share шлёт два Initial), собрать
 * отсюда нельзя: снимок датапата — одна датаграмма, и половина приветствия
 * не приветствие. Такой случай честно отказывает, а не досочиняет недостающее.
 */
#ifndef D2K_QUICHELLO_H
#define D2K_QUICHELLO_H

#include <stddef.h>
#include <stdint.h>

/* ЧЕМ СПРОСИТЬ КОРОБКУ — способ пересборки снятого Initial.
 *
 * Оригинал («Поиск по домену», internal/quicprobe/questions.go) задаёт восемь
 * вопросов, и шесть из них — это один и тот же Initial, пересобранный
 * по-разному. Здесь перечислены те, что меняют САМ ПАКЕТ; вопросы про
 * соседние датаграммы (мусор или фальшивка перед приветствием) и про
 * исходный порт пакета не касаются и живут в вопроснике.
 *
 * ОТЛИЧИЕ ОТ ОРИГИНАЛА, И ОНО ЕДИНСТВЕННОЕ. Там Initial собирается с нуля из
 * своего ClientHello; здесь — ПЕРЕСОБИРАЕТСЯ СНЯТЫЙ. Причина та же, по
 * которой существует d2k_quic_hello_rename (см. шапку файла): коробка сличает
 * форму приветствия настоящего клиента, и мерить надо ею. Побочное следствие:
 * приветствие, не поместившееся в одну датаграмму, здесь недоступно — снимок
 * датапата одна датаграмма.
 *
 * ЧТО ИЗ ЭТОГО ДВИЖОК УМЕЕТ ИСПОЛНИТЬ — отдельный вопрос, и ответ на него
 * чаще «ничего». Оригинал называет такие находки прямо: приём сработал, а
 * исполнить его нечем. Прятать их нельзя — это самый ценный выход замера, и
 * ровно они говорят, куда движку расти. */
typedef enum {
    /* Как есть, только имя другое — то, что делает d2k_quic_hello_rename. */
    D2K_QASK_PLAIN = 0,
    /* Приветствие ДВУМЯ кадрами CRYPTO с разрывом внутри имени и в обратном
     * порядке. Точный аналог разреза TCP-потока и единственный приём,
     * ломающий РАЗБОР, а не сигнатуру. */
    D2K_QASK_SPLIT_CRYPTO,
    /* Вторая версия QUIC (RFC 9369): другая соль, другие метки вывода ключей,
     * перенумерованы типы пакетов. Коробка, зашитая на первую версию, такой
     * Initial не расшифрует вовсе. */
    D2K_QASK_VERSION2,
    /* Погашенный фиксированный бит. По RFC 9000 §17.2 второй по старшинству
     * бит обязан быть единицей, и коробка обычно по нему отличает QUIC от
     * прочего UDP; RFC 9287 разрешает его гасить по договорённости. */
    D2K_QASK_CLEAR_FIXED_BIT,
    /* Датаграмма длиннее обычной. Единственный из приёмов, который правит сам
     * пакет, а не добавляет соседей: по RFC 9000 §12.2 приёмник разбирает
     * первый пакет по его полю длины, а неразобранный хвост отбрасывает. */
    D2K_QASK_LONGER
} d2k_quic_ask;

/* Пересобирает снятый Initial выбранным способом, с именем sni.
 *
 * 0 — собрано, -1 — снимок не расшифровался/не целый, имя не подставляется,
 * способ неизвестен или результат не помещается. */
int d2k_quic_hello_ask(const uint8_t *in, size_t n, d2k_quic_ask ask,
                       const char *sni, uint8_t *out, size_t cap, size_t *out_len);

/* Собирает из снятого клиентского Initial новый — с именем sni.
 *
 * Длина датаграммы сохраняется: добивка PADDING доводит её ровно до длины
 * снимка (но не меньше 1200 байт, RFC 9000 §14.1). Длина — тоже форма: по
 * ней коробка отличает приветствие от чего угодно другого.
 *
 * 0 — собрано, -1 — снимок не расшифровался/не целый, имя не подставляется
 * или результат не помещается. */
/* Приветствие ДВУМЯ датаграммами, хвост первым (вопрос 4 оригинала).
 *
 * Отдельная функция, а не ещё один d2k_quic_ask: у вопроса два выхода, и
 * втиснуть их в один буфер значило бы отдать склеенную датаграмму, то есть
 * задать другой вопрос (RFC 9000 §12.2). Оба пакета несут ОДИН DCID — иначе
 * сервер увидит два начатых соединения с половиной приветствия в каждом.
 * Отправлять их надо в порядке tail, head, обе не меньше 1200 байт.
 *
 * 0 — собрано, -1 — снимок непригоден, имя не находится или не помещается. */
int d2k_quic_hello_split(const uint8_t *in, size_t n, const char *sni,
                         uint8_t *head, size_t head_cap, size_t *head_len,
                         uint8_t *tail, size_t tail_cap, size_t *tail_len);

int d2k_quic_hello_rename(const uint8_t *in, size_t n, const char *sni,
                          uint8_t *out, size_t cap, size_t *out_len);

/* ТОТ ЖЕ СНИМОК — ДРУГОЕ СОЕДИНЕНИЕ. Расшифровывает Initial и запечатывает
 * ЕГО ЖЕ содержимое, байт в байт, ключами от нового DCID.
 *
 * Отличие от d2k_quic_hello_rename принципиальное: там пересобирается
 * приветствие (кадр CRYPTO строится заново), здесь не меняется НИЧЕГО, кроме
 * идентификатора назначения — ни имя, ни порядок кадров, ни добивка. Форма
 * сохраняется дословно; меняется только то, что RFC 9000 §7.2 и велит
 * выбирать заново на каждое соединение.
 *
 * ЗАЧЕМ. Вопросы задаются ТРЕМЯ параллельными попытками ради единогласия
 * (см. d2k_quicprobe.h). Пока копии были побайтно одинаковыми, сервер
 * засчитывал ПЕРВУЮ и молча ронял остальные как повтор того же пакета того
 * же соединения: замерено в лаборатории 13.09.2026 на www.google.com —
 * контрольное имя давало ровно 1/3, и дерево вопросов честно объявляло
 * «измерению верить нельзя» на КАЖДОМ вопросе. Этот вопрос стоял в шапке
 * quicprobe.c как открытый и требующий замера; замер сделан, ответ — да.
 *
 * 0 — собрано, -1 — не Initial, не расшифровалось, версия не наша либо не
 * помещается. */
int d2k_quic_hello_recid(const uint8_t *in, size_t n,
                         uint8_t *out, size_t cap, size_t *out_len);

#endif /* D2K_QUICHELLO_H */
