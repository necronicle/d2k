/* d2k_hello.h — вид снятого приветствия и сборка приветствия холодного старта.
 *
 * Снимок приходит от датапата: тот уже ловит форму ClientHello настоящего
 * клиента и отдаёт эти байты контроллеру целиком (см. §4 doc/spec —
 * «Оракул: побайтный повтор снятого приветствия»). Этот модуль отвечает на
 * два вопроса про уже снятые байты и решает одну задачу сборки:
 *
 *   1. d2k_hello_shape — TLS 1.2 это было или TLS 1.3. Обход у них разный
 *      (§6 doc/spec: в 1.2 сертификат сервера едет открытым текстом и режется
 *      ОТВЕТОМ, в 1.3 виден только ClientHello), и ключ плана — цель ПЛЮС
 *      вид приветствия, а не только имя. Спутать телевизор с браузером —
 *      значит переписать чужой план своим.
 *   2. d2k_hello_sni — где в этих байтах имя, координатами, а не поиском
 *      подстроки: подстрока может случайно встретиться в шифре или в
 *      случайных полях, а после подстановки имени в профиль (ниже) старое
 *      имя ещё и физически может остаться хвостом в незанятой части буфера
 *      вызывающего.
 *   3. d2k_hello_from_profile — приветствие холодного старта: единственное
 *      место, где c2k вообще СОБИРАЕТ TLS-байты, а не повторяет снятые.
 *      Нужно оно РОВНО на первом контакте с целью, когда снимка ещё нет
 *      (см. ту же §4: «сборщик приветствий с профилями нужен только на
 *      самом первом контакте»). Как только снимок появился — дальше меряют
 *      им, а не этой сборкой.
 *
 * ЭТАЛОН РАЗБОРА — datapath/tls.c, и он же — причина, почему этот файл не
 * выглядит иначе. Та же дисциплина границ (объявленная длина против того,
 * что реально пришло — «противоречие» и «обрывок», см. шапку tls.c), те же
 * побайтные чтения многобайтовых полей (MIPS и ARM не гарантируют
 * выравнивание, наложение структуры на буфер здесь запрещено так же, как
 * там). Отличие ЕДИНСТВЕННОЕ и ровно то, для чего заведён этот файл: там нет
 * вида приветствия, а d2k_hello_shape он нужен. Отсюда — разбор здесь не
 * останавливается на первом найденном расширении (server_name), как делает
 * tls.c: пока не долистан весь блок, supported_versions может обнаружиться
 * И до, И после server_name — реальные клиенты кладут их в разном порядке
 * (см. test_hello.c: настоящее приветствие openssl несёт supported_versions
 * ПОСЛЕ server_name). Копипасты из tls.c нет: core/ и datapath/ — разные
 * цели сборки (свои Makefile, свои бинарники, см. core/quic.c с тем же
 * решением), и второй экземпляр той же логики поддерживается отдельно уже
 * сегодня.
 *
 * ПРОФИЛИ — ДАННЫЕ, А НЕ КОД. core/profiles/ (файлы *.hex) — байты, снятые
 * один раз с настоящего клиента (не «по спецификации» — коробка сличает то, что
 * реально шлёт клиент: порядок расширений, набор шифров, GREASE, длины,
 * всё вместе, и самодельное приветствие меряло другую коробку, чем видит
 * браузер, ценой целого каталога 06.09.2026, см. doc/spec §4). В файле имя
 * заменено меткой __SNI__ — синтаксически обычным 7-байтным именем хоста,
 * так что d2k_hello_sni находит её ТЕМ ЖЕ разбором по координатам, которым
 * потом ищет имя в чужом трафике: отдельного пути для профиля нет.
 *
 * БЕЗ ВЫДЕЛЕНИЙ ПАМЯТИ. Ни один буфер здесь не выделяется: разбор смотрит
 * в буфер вызывающего, сборка пишет в буфер вызывающего по границе cap.
 * Внутренний буфер профиля — статический фиксированного размера (см. hello.c)
 * и не растёт: это не пакетный путь датапата (та же оговорка, что у
 * d2k_quic_arm_blob в d2k_quicprobe.h), но привычка одна на всё ядро.
 */
#ifndef D2K_HELLO_H
#define D2K_HELLO_H

#include <stddef.h>
#include <stdint.h>

/* Вид приветствия. UNKNOWN — не ClientHello вовсе или разбор не добрался
 * даже до конца обязательных полей (обрывок, противоречие длин, не TLS).
 * Это НЕ то же самое, что LEGACY: LEGACY — уверенный ответ «это ClientHello,
 * и в нём нет supported_versions со значением 0x0304», UNKNOWN — честное
 * «этого утверждать нельзя». Путать их нельзя по той же причине, по которой
 * d2k_tls_parse не путает «не TLS» с «TLS, но не ClientHello» (см. d2k_tls.h):
 * уверенный неправильный ответ здесь хуже честного «не знаю». */
typedef enum {
    D2K_SHAPE_UNKNOWN = 0,
    D2K_SHAPE_MODERN,
    D2K_SHAPE_LEGACY
} d2k_shape;

/* Определяет вид снятого приветствия.
 *
 * Признак — расширение supported_versions (0x002b, RFC 8446 §4.2.1): если
 * оно есть и среди перечисленных в нём версий встречается 0x0304 (TLS 1.3) —
 * MODERN. Если приветствие разобралось, но такого расширения нет или в нём
 * нет 0x0304 — LEGACY: до RFC 8446 этого расширения не существовало вовсе, и
 * клиент, ограниченный потолком TLS 1.2, просто не заявляет версию, которую
 * не умеет. Если разобрать не удалось (мало байт, не TLS, не ClientHello,
 * длины полей не сходятся) — UNKNOWN.
 *
 * b/n — то, что реально есть у вызывающего (снимок может быть неполным).
 * Функция никогда не падает на коротком или чужеродном входе — на то она и
 * UNKNOWN. */
d2k_shape d2k_hello_shape(const uint8_t *b, size_t n);

/* Ищет имя (server_name/host_name) в приветствии и отдаёт его КООРДИНАТЫ.
 *
 * Возвращает 0 и заполняет *off и *len, если имя найдено и целиком помещается
 * в переданные байты. Возвращает -1, если имени нет, оно не помещается целиком,
 * длины полей противоречат друг другу, либо аргументы негодны (b==NULL при
 * n>0, off==NULL, len==NULL). Отсутствие имени — не ошибка ввода (см. d2k_tls.h
 * про ECH и безымянные соединения) и от неверных аргументов не отличается в
 * возврате нарочно: и то и другое запрещает вызывающему опираться на *off и *len,
 * а разбираться, ПОЧЕМУ имени нет, здесь как и в tls.c незачем. */
int d2k_hello_sni(const uint8_t *b, size_t n, size_t *off, size_t *len);

/* Собирает приветствие холодного старта по профилю вида s, с именем sni.
 *
 * Берёт снятый профиль (core/profiles/modern.hex или legacy.hex, встроены в
 * бинарник на сборке), заменяет метку __SNI__ на sni и пересчитывает ВСЕ
 * объемлющие длины: длину самого имени, список имён (ServerNameList),
 * расширение server_name, блок расширений, тело рукопожатия и длину записи
 * TLS — эта цепочка длин вложена целиком одна в другую, и пропуск любого
 * звена делает приветствие негодным так, что глазом это не видно (см. шапку
 * hello.c). Разница между strlen(sni) и длиной метки (7 байт) может быть и
 * отрицательной (короткое имя) — пересчёт работает в обе стороны.
 *
 * out/cap — буфер вызывающего; функция никогда не пишет за cap. Возвращает 0
 * и заполняет *out_len при успехе. Возвращает -1, если: s не MODERN/LEGACY;
 * профиль этого вида не снят (пустой — см. отметку в profiles/legacy.hex,
 * если снятие когда-нибудь не удастся и профиль останется незаполненным);
 * sni пуст; результат не помещается в cap; либо встроенный профиль почему-то
 * не разбирается как приветствие с именем (внутренняя несогласованность
 * данных, а не что-то, что может завиcеть от вызывающего). */
int d2k_hello_from_profile(d2k_shape s, const char *sni, uint8_t *out, size_t cap, size_t *out_len);

#endif /* D2K_HELLO_H */
