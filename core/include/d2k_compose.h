/* d2k_compose.h — свойства пересобирающей коробки и вывод плана для TCP.
 *
 * Вердикт D2K_V_OPAQUE (d2k_verdict.h) говорит: разрез бесполезен, коробка
 * решает по содержимому, а поток при этом пересобирается — иначе разрез бы
 * сработал. Разрез такую коробку не берёт; берёт её отравление буфера
 * пересборки. Пять свойств ниже — про то, ЧЕМ именно можно это отравление
 * вызвать: перекрытием слева, порядком сегментов, контрольной суммой,
 * разбором протокола, счётом дубликатов. Порт internal/classify/properties.go
 * (Properties, PropProbes, Compose) — это перенос, не пересказ; расхождения
 * с Go-стороной, найденные при переносе, см. в отчёте задачи 3 и в отчёте
 * задачи 5 (шаг 0).
 *
 * ТРОЙСТВЕННАЯ ЛОГИКА ОБЯЗАТЕЛЬНА (§2.4 спеки): «не измерено» и «нет» —
 * разные состояния. Ноль (D2K_P_UNKNOWN) не превращается в диагноз «нет» ни
 * при опросе, ни при выводе плана — d2k_compose добавляет плечо ТОЛЬКО там,
 * где вектор прямо об этом говорит.
 *
 * D2K_PROPS_ASK — ТЕПЕРЬ НАСТОЯЩИЙ ОРАКУЛ (задача 5, шаг 0). Пять Go-вопросов
 * (internal/classify/properties.go, PropProbes) проверяются приёмами, которые
 * требуют ручного управления TCP-сегментами: перекрытие слева — это seqovl
 * (сегмент, посланный с seq ЛЕВЕЕ настоящих данных), три остальных —
 * фальшивка с ЗАВЕДОМО БИТОЙ контрольной суммой перед настоящей нагрузкой,
 * а порядок сегментов — посылка кусков НЕ в порядке их положения в потоке.
 * Ни seq, ни контрольную сумму, ни порядок отправки обычный SOCK_STREAM-сокет
 * вызывающему не отдаёт — этим управляет только датапат (NFQUEUE), а ядру он
 * открывается через протокол связи задачи 4 (core/link.c, d2k_link.h) —
 * отсюда новый первый параметр link_fd: без него задать НИ ОДИН из пяти
 * вопросов было физически нечем (см. отчёт задачи 3 и шапку compose.c до
 * задачи 5 — она объясняла честность вектора из одних D2K_P_UNKNOWN именно
 * отсутствием этой связи). Свойство пишется ТОЛЬКО по проходу вопроса —
 * промах не пишет ничего, ровно как каждый Set в Go начинается с
 * `if !passed { return }`. */
#ifndef D2K_COMPOSE_H
#define D2K_COMPOSE_H

#include <stddef.h>
#include <stdint.h>

#include "d2k_hello.h" /* d2k_shape */
#include "d2k_meas.h"  /* d2k_hello */

/* Тройственная логика: не измерено / да / нет. Ноль означает «не измерено»,
   и это не то же самое, что «нет» (§2.4 спеки: наблюдение не превращается
   в диагноз). */
typedef enum { D2K_P_UNKNOWN = 0, D2K_P_YES = 1, D2K_P_NO = 2 } d2k_pval;

typedef struct {
    d2k_pval tolerates_left_overlap; /* держит ли сегмент, начинающийся левее данных */
    d2k_pval tolerates_reorder;      /* держит ли сегменты не по порядку прихода */
    d2k_pval validates_checksum;     /* сверяет ли контрольную сумму TCP */
    d2k_pval parses_l7;              /* разбирает ли TLS, а не просто смотрит байты */
    d2k_pval counts_duplicates;      /* считает ли разнесённые копии за одно */
} d2k_props;

/* Задаёт вопросы о свойствах коробки на настоящей цели, через датапат.
 *
 * link_fd — дескриптор связи, открытый d2k_link_open (задача 4): по нему
 * ставится план (D2K_CMD_SET_NAME), ждётся подтверждение, и читается исход
 * обмена (D2K_EV_EXCHANGE, порог d2k_ev_has_appdata). ip/port — куда сделать
 * ОДНО обращение (обычным соединением: план манглит его пакеты на пути через
 * датапат, не эта функция). trigger — реально снятое приветствие цели: его
 * же байты идут на провод как есть (§4: приветствие — измерительный прибор,
 * самодельное меряет не ту коробку), и из него же по SNI берётся имя для
 * SET_NAME — датапат матчит план по имени, а не по адресу (d2k_link.h,
 * d2k_link_set_name). control — реально снятое приветствие ДРУГОГО имени на
 * ту же цель; его байты идут ВЕРБАТИМ как содержимое фальшивок вопросов
 * «счёт дубликатов» и «разбор протокола» — тем же приёмом, каким весь этот
 * модуль настаивает на настоящих байтах, а не самодельных (см. шапку
 * compose.c): раз реальный захват уже есть, синтезировать приманку профилем
 * (как делает d2k_compose при отсутствии такого захвата) значило бы
 * заведомо понижать достоверность без всякой причины. mark — метка зонда
 * (§5.5), та же, что ставит датапат на боевые пакеты.
 *
 * Порядок вопросов — ЗЕРКАЛО classify.PropProbes (properties.go): перекрытие
 * слева, счёт дубликатов, порядок сегментов, контрольная сумма, разбор
 * протокола — цена таймаута, не вкус (см. её же комментарий). Первый ПРОШЕДШИЙ
 * вопрос обрывает опрос: это уже стратегия, второй план для той же цели
 * не нужен (тот же принцип, что в controller.go verdictCandidates про
 * "до сбора нескольких подтверждённых свойств дело физически не доходит").
 *
 * Возвращает вектор из одних D2K_P_UNKNOWN, если спросить нечем вовсе:
 * link_fd < 0, ip пуст, у trigger нет байт или нет извлекаемого имени
 * (d2k_hello_sni) — тройственная логика тут та же, что и в остальном ядре:
 * «не измерено» не подделывается «нет»-ом.
 *
 * ДВА ДОЛГА, ОСТАВЛЕННЫЕ ЭТОЙ РЕАЛИЗАЦИЕЙ ОСОЗНАННО — СНЯТЬ В КРУГЕ
 * ПЛАНИРОВЩИКА (задача 5, шаги 1-5), НЕ ЗДЕСЬ:
 *
 * 1. Если ни один из пяти вопросов не прошёл, план ПОСЛЕДНЕГО заданного
 *    зонда остаётся стоять на датапате под именем цели — d2k_link_del_name
 *    (которого сегодня и не существует в d2k_link.h) отсюда не зовётся.
 *    Решение осознанное: у Go снятие плана — дело controller.go (advance()/
 *    clear()), а не classify-слоя, и здесь та же граница ответственности —
 *    но её ОБЯЗАН закрыть тот, кто пишет d2k_sched/d2kc, иначе цель,
 *    признанная неберущейся, останется с чужим планом на линии.
 *
 * 2. D2K_PROPS_ASK_WAIT_MS (compose.c) — ОДНО число и на ack SET_NAME по
 *    локальному AF_UNIX (миллисекунды по природе), и на обмен с целью по
 *    настоящей сети (секунды по природе). Число УНАСЛЕДОВАНО (WAIT_CEIL_MS,
 *    meas.c) — это не то же самое, что ИЗМЕРЕНО ДЛЯ ЭТОГО применения: на
 *    живой линии этот потолок не проверялся ни разу, и если планировщик
 *    увидит настоящие ложные тайм-ауты обмена, чинить нужно ЗДЕСЬ, числом
 *    из замера, а не заново гадать. */
d2k_props d2k_props_ask(int link_fd, const char *ip, uint16_t port,
                        d2k_hello trigger, d2k_hello control, uint32_t mark);

/* Выводит планы из вектора. Возвращает число записанных, максимум cap.
 * Планы — текст формата d2k-plan, как в каталоге (d2k_catalog.h:
 * d2k_cat_plan.text; на Go-стороне — internal/plan.Plan.Text()). Плечо
 * появляется тогда и только тогда, когда соответствующее свойство измерено
 * и говорит, что оно применимо — КРОМЕ полностью неизмеренного вектора: это
 * особый случай с единственным честным планом «всё сразу» (см. compose.c,
 * everything_plan_text, и Go Compose — properties.go:214-221), а не «ничего
 * не выводить». Плечо, которое не поместилось целиком в sizeof(out[0]) байт
 * или не собралось (например, decoy пуст, а план в нём нуждается),
 * пропускается целиком, а не пишется усечённым и не считается в возвращённом
 * числе.
 *
 * target_shape — вид СНЯТОГО приветствия цели (d2k_hello_shape, d2k_hello.h),
 * а не приманки: коробка может по-разному относиться к TLS 1.2 и 1.3 (§6
 * спеки), и приманка вопросов «счёт дубликатов»/«разбор протокола»/«всё
 * сразу» собирается ТЕМ ЖЕ видом — мерить целевую коробку приманкой другого
 * вида значит мерить не то. D2K_SHAPE_UNKNOWN падает на LEGACY (меньший из
 * двух профилей) как безопасный запасной вариант, а не как угаданное «нет»:
 * это выбор ФОРМЫ ПРИМАНКИ, не записываемое свойство коробки, тройственная
 * логика d2k_props этим не затрагивается. */
size_t d2k_compose(const d2k_props *pr, d2k_shape target_shape, const char *decoy,
                   char out[][4096], size_t cap);

#endif /* D2K_COMPOSE_H */
