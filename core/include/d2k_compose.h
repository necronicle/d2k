/* d2k_compose.h — свойства пересобирающей коробки и вывод плана для TCP.
 *
 * Вердикт D2K_V_OPAQUE (d2k_verdict.h) говорит: разрез бесполезен, коробка
 * решает по содержимому, а поток при этом пересобирается — иначе разрез бы
 * сработал. Разрез такую коробку не берёт; берёт её отравление буфера
 * пересборки. Пять свойств ниже — про то, ЧЕМ именно можно это отравление
 * вызвать: перекрытием слева, порядком сегментов, контрольной суммой,
 * разбором протокола, счётом дубликатов. Порт internal/classify/properties.go
 * (Properties, PropProbes, Compose) — это перенос, не пересказ; расхождения
 * с Go-стороной, найденные при переносе, см. в отчёте задачи 3.
 *
 * ТРОЙСТВЕННАЯ ЛОГИКА ОБЯЗАТЕЛЬНА (§2.4 спеки): «не измерено» и «нет» —
 * разные состояния. Ноль (D2K_P_UNKNOWN) не превращается в диагноз «нет» ни
 * при опросе, ни при выводе плана — d2k_compose добавляет плечо ТОЛЬКО там,
 * где вектор прямо об этом говорит.
 *
 * D2K_PROPS_ASK — ЧЕСТНО НЕИЗМЕРЯЮЩИЙ ОРАКУЛ, И ЭТО НЕ НЕДОСМОТР. Пять
 * Go-вопросов проверяются приёмами, которые требуют ручного управления TCP-
 * сегментами: перекрытие слева — это seqovl (сегмент, посланный с seq ЛЕВЕЕ
 * настоящих данных), три остальных — фальшивка с ЗАВЕДОМО БИТОЙ контрольной
 * суммой перед настоящей нагрузкой, а порядок сегментов — посылка кусков НЕ
 * в порядке их положения в потоке. Ни seq, ни контрольную сумму, ни порядок
 * отправки обычный SOCK_STREAM-сокет вызывающему не отдаёт — этим
 * управляет только датапат (NFQUEUE), а ядру он открывается через протокол
 * связи, который поднимает задача 4 (core/link.c) ПАРАЛЛЕЛЬНО этой, в
 * отдельном дереве; по таблице зависимостей плана
 * (.superpowers/sdd/2026-09-07-engine-c-both-transports/progress.md) у
 * задачи 3 на задачу 4 зависимости нет, и на момент этой задачи core/link.c
 * не существует. Единственный оракул, который задача 3 потребляет,
 * d2k_meas (d2k_meas.h), — честные разрезы по возрастанию без перекрытий,
 * порчи и переупорядочивания (meas.c: cuts_valid, send_all) — и этого
 * недостаточно ни для одного из пяти вопросов. Раз спросить нечем,
 * d2k_props_ask отдаёт вектор из одних D2K_P_UNKNOWN: это единственно
 * честный ответ (§2.4), а не имитация измерения на чужом приёме — подробное
 * рассуждение и почему имитация была бы ХУЖЕ отказа, см. в шапке compose.c
 * и в отчёте задачи 3. */
#ifndef D2K_COMPOSE_H
#define D2K_COMPOSE_H

#include <stddef.h>
#include <stdint.h>

#include "d2k_meas.h" /* d2k_hello */

/* Тройственная логика: не измерено / да / нет. Ноль означает «не измерено»,
   и это не то же самое, что «нет» (§2.4 спеки: наблюдение не превращается
   в диагноз). */
typedef enum { D2K_P_UNKNOWN = 0, D2K_P_YES = 1, D2K_P_NO = 2 } d2k_pval;

typedef struct {
    d2k_pval tolerates_left_overlap; /* держит ли сегмент, начинающийся левее данных */
    d2k_pval tolerates_reorder;      /* держит ли сегменты не по порядку прихода */
    d2k_pval validates_checksum;     /* сверяет ли контрольную сумму TCP */
    d2k_pval parses_l7;              /* разбирает ли TLS, а не просто смотрит байты */
    d2k_pval counts_duplicates;      /* считает ли разнесённые копии за одно */
} d2k_props;

/* Задаёт вопросы о свойствах. Каждый вопрос — план, который при удаче УЖЕ
 * является стратегией: второго плана для той же цели нет. См. шапку файла
 * про то, почему ЭТА реализация честно возвращает {0} (все свойства
 * неизмерены), а не имитирует измерение оракулом, которому нечем спросить
 * ни один из пяти вопросов. */
d2k_props d2k_props_ask(const char *ip, uint16_t port, d2k_hello trigger,
                        d2k_hello control, uint32_t mark);

/* Выводит планы из вектора. Возвращает число записанных, максимум cap.
 * Планы — текст формата d2k-plan, как в каталоге (d2k_catalog.h:
 * d2k_cat_plan.text; на Go-стороне — internal/plan.Plan.Text()). Плечо
 * появляется тогда и только тогда, когда соответствующее свойство измерено
 * и говорит, что оно применимо — КРОМЕ полностью неизмеренного вектора: это
 * особый случай с единственным честным планом «всё сразу» (см. compose.c,
 * everything_plan_text, и Go Compose — properties.go:214-221), а не «ничего
 * не выводить». Плечо, которое не поместилось целиком в 2048 байт или не
 * собралось (например, decoy пуст, а план в нём нуждается), пропускается
 * целиком, а не пишется усечённым и не считается в возвращённом числе. */
size_t d2k_compose(const d2k_props *pr, const char *decoy,
                   char out[][2048], size_t cap);

#endif /* D2K_COMPOSE_H */
