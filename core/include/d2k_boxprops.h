/* d2k_boxprops.h — ВЕКТОР СВОЙСТВ КОРОБКИ: что о ней ИЗВЕСТНО, а не чем её
 * УЗНАЮТ.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ СТРУКТУРА И ЗАЧЕМ ОНА В core/include. Измеритель заполняет
 * свой d2k_dprops (detect/include/d2k_detect.h), но ядро заголовков detect не
 * видит — видно только обратное (detect собирается с -I../core/include). Пока
 * общей структуры не было, вектор кончался на мосту: d2k_vres несла лишь
 * найденный приём, и знание о коробке не доходило ни до планировщика, ни до
 * каталога. Следствие, замеренное 23.10.2026 на выпуске 374a6df: вторая цель
 * той же коробки задавала заново те же вопросы.
 *
 * ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Это НЕ примета узнавания. Приметы (d2k_cat_fp.sig:
 * "rst", "silent", "repeat", "volume", "rx-volume") отвечают на вопрос «та же
 * коробка?» и входят в сравнение d2k_fp_same. Вектор отвечает на другой
 * вопрос — «чем её брать?» — и в сравнение НЕ входит: иначе коробка,
 * измеренная полнее, перестала бы узнаваться в себе же.
 *
 * ТРОЙСТВЕННАЯ ЛОГИКА (§2.4). Поля-признаки принимают D2K_PROP_UNKNOWN /
 * D2K_PROP_NO / D2K_PROP_YES (d2k_verdict.h). Ноль — «не измерено», и это не
 * «нет»: локальный отказ зонда, неотправленная посылка и отказ исполнителя
 * свойством коробки не пишутся.
 *
 * ЧИСЛА — НЕ ПРИЗНАКИ. hops и reasm_boundary измеряются величиной, а не
 * да/нет, и ноль в них означает ровно «не измерено» (расстояния в нуль хопов
 * не бывает, порог пересборки в нулевой позиции не бывает). Из этих двух
 * чисел собирается параметр плана, а не выбирается форма из списка.
 *
 * ОСЬ ФОРМЫ КЛИЕНТА. План зависит не только от коробки: клиент без метки
 * времени не исполняет план со сдвигом метки назад (issue #7, поле
 * 23.10.2026 — 498 сбросов зонда на прогон). Поэтому вектор хранится С
 * ФОРМОЙ КЛИЕНТА, которой он измерен (client_shape, значения
 * D2K_LINK_SHAPE_* из d2k_link.h; ноль — форма не названа). Форму знает
 * планировщик, а не дерево: мост оставляет поле нулём. */
#ifndef D2K_BOXPROPS_H
#define D2K_BOXPROPS_H

#include <stddef.h>
#include <stdint.h>

/* All persisted response-gate measurements use this SYN scale. */
#define D2K_GATE_MEASURED_WSCALE 0

/* ТРОЙСТВЕННАЯ ЛОГИКА — ЗДЕСЬ, РЯДОМ СО СТРУКТУРОЙ, КОТОРУЮ ОНА ЗАПОЛНЯЕТ.
 * До 23.10.2026 эти три кода жили в d2k_verdict.h, и каталогу пришлось бы
 * тянуть весь вердикт (плечо, QUIC-свойства, подсказку базы) ради трёх чисел.
 * d2k_verdict.h включает этот заголовок и продолжает их отдавать всем своим
 * читателям — ни один вызывающий ничего не меняет. Числа совпадают с
 * d2k_tri измерителя (detect/include/d2k_detect.h), и расхождение ломает
 * сборку (см. d2k_bridge_tri_check в detect/bridge.c). */
#define D2K_PROP_UNKNOWN 0
#define D2K_PROP_NO      1
#define D2K_PROP_YES     2

typedef struct {
    /* Признаки: D2K_PROP_UNKNOWN / D2K_PROP_NO / D2K_PROP_YES. */
    int8_t  reassembles;            /* собирает поток из сегментов */
    int8_t  parses_l7;              /* разбирает TLS, а не только байты */
    int8_t  validates_checksum;     /* сверяет контрольную сумму TCP */
    int8_t  tolerates_reorder;      /* терпит сбитый порядок сегментов */
    int8_t  tolerates_left_overlap; /* терпит перекрытие слева */
    int8_t  counts_duplicates;      /* считает копии ретрансмитами */
    int8_t  inspects_syn;           /* смотрит данные в SYN */
    int8_t  validates_md5;          /* сверяет подпись TCP-MD5 */
    int8_t  validates_seq_window;   /* сверяет номер с окном */
    int8_t  validates_timestamps;   /* сверяет метку времени */
    int8_t  overlap_covers_sni;     /* перекрытие до конца имени берёт её */
    /* Учитывает ли коробка срочный байт TCP (urgent pointer). FALSE — не
       учитывает: байт, вставленный в середину имени, сервер из потока
       уберёт, а коробка прочтёт имя с лишним байтом и не узнает его.
       Гистограмма полевых журналов 23.10.2026: этим приёмом взято 111 целей
       из 124 всех попаданий запасного перебора, а вопроса о нём в опросе не
       было — то есть это был главный промах классификатора (§0.1). */
    int8_t  handles_urgent;
    int8_t response_gate;          /* обычный ответ молчит: полный ACK либо ответ в малом окне */
    int8_t gate_carry;             /* пропуск переживает RST; NO — измеренный промах */
    int8_t gate_hello_own;         /* достаточно приветствия клиента */
    uint16_t gate_window;          /* ноль — не измерено */
    uint32_t gate_pieces;          /* минимальное успешное K; ноль — не найдено */
    uint32_t gate_rtt_ms;          /* RTT пробы; ноль — не измерено */
    /* Величины: ноль — не измерено (см. шапку). */
    int32_t hops;                   /* расстояние до коробки в хопах */
    int32_t reasm_boundary;         /* первая позиция разреза, которая уже не проходит */
    /* Форма приветствия клиента, которым вектор измерен (D2K_LINK_SHAPE_*);
       ноль — не названа. Заполняет планировщик. */
    uint8_t client_shape;
} d2k_box_props;

/* НАКОПЛЕНИЕ ЗНАНИЯ. Сливает измеренный вектор src в записанный dst и
 * возвращает число полей, где замер ПРОТИВОРЕЧИТ записанному. Неизмеренное в
 * src ничего не стирает; противоречащее поле становится неизмеренным — два
 * замера разошлись, и знания о поле больше нет (§2.4). Величины не
 * усредняются. Форму клиента (ключ записи) слияние не касается. Возврат
 * больше нуля — повод перемерить коробку, а не тихая правка файла
 * (§0 «повторная проверка при деградации»). Правило одно на измеритель,
 * каталог и планировщик; подробности — в core/boxprops.c. */
int d2k_box_props_merge(d2k_box_props *dst, const d2k_box_props *src);

/* ИЗМЕРЕНО ЛИ ХОТЬ ЧТО-НИБУДЬ. 1 — есть измеренный признак или величина,
 * 0 — вектор пуст. Нужен тому, кто решает, заводить ли запись знания: пустая
 * запись в каталоге означала бы «коробку измеряли и ничего не нашли», а это
 * другое утверждение, чем «не измеряли» (§2.4). Форма клиента сама по себе
 * знанием не считается: это ключ записи. */
int d2k_box_props_any(const d2k_box_props *p);

/* Человеческий вид вектора для журнала: называет ТОЛЬКО измеренное, иначе
 * «не измерено» читалось бы как «нет». Возвращает длину строки; буфер не
 * переполняется, символ UTF-8 на обрезке не рвётся. */
size_t d2k_box_props_text(const d2k_box_props *p, char *buf, size_t cap);

#endif
