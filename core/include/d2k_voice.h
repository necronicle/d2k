/* d2k_voice.h — ГОЛОСОВОЙ ПУТЬ: что происходит с UDP-потоком разговора.
 *
 * ЧЕМ ЭТОТ ЗАМЕР ОТЛИЧАЕТСЯ ОТ ВСЕХ ОСТАЛЬНЫХ В ПРОЕКТЕ. Подбор по домену
 * целиком стоит на имени: имя вводит человек, имя же меняется в контроле, и
 * разница «наше имя молчит, нейтральное отвечает» и ЕСТЬ измерение. У голоса
 * имени НЕТ ВООБЩЕ — в боевом профиле так и записано, hostkey=z2k_nohost_key.
 * Рушатся обе половины сразу: и откуда брать цель, и с чем сравнивать.
 *
 * ОТКУДА ЦЕЛЬ. Голосовой сервер выдаётся на сессию, и в публичном DNS его нет
 * (замер 04.09.2026: discord.media резолвится, russiaNNNN.discord.media — нет).
 * Зашить нечего, вписать человеку нечего. Остаётся одно: взять адрес из ЖИВОГО
 * разговора, из таблицы соединений ядра. Поэтому у этого замера нет поля
 * ввода, а есть требование «сначала позвони» — и вердикт D2K_VOICE_NO_CALL,
 * который честно говорит, что мерить было нечего.
 *
 * ЭТО ЖЕ ЗАПРЕТ, А НЕ ТОЛЬКО УСТРОЙСТВО (D2K_SPEC §"адресным целям не
 * придумывать домен"): выдумать голосовой цели домен и померить его — значит
 * померить другую цель и назвать чужой результат её именем.
 *
 * С ЧЕМ СРАВНИВАТЬ — ТРИ СЛОЯ, У КАЖДОГО СВОЙ ОРАКУЛ.
 *
 *   1. Голосовой сервер, STUN как есть. Отвечает — резать нечего.
 *   2. Публичный STUN на ТОМ ЖЕ канале. Отвечает — UDP ходит, и молчание
 *      первого слоя про него самого. Молчит — на канале не ходит UDP вовсе
 *      или его режут целиком, и обходить голос отдельно бессмысленно.
 *   3. Только теперь — приёмы: фальшивка перед настоящим пакетом и число её
 *      копий. Ровно то, чем боевой профиль discord_udp и работает.
 *
 * ПОЧЕМУ ИМЕННО STUN. У него НАСТОЯЩИЙ ответ, а не тишина: сервер возвращает
 * наш же адрес, и совпадение идентификатора транзакции доказывает, что
 * ответил именно он (см. d2k_stun.h). После QUIC, где оракул пришлось
 * выцарапывать из остаточной блокировки, это подарок — и именно поэтому
 * голосовой путь устроен проще QUIC-дерева, а не потому, что его недоделали.
 *
 * ЕДИНОГЛАСИЕ ИЛИ НИЧЕГО. У датаграмм одиночная потеря — норма, а одиночный
 * проход может быть везением. Вердикт выносится при D2K_VOICE_REPEATS из
 * D2K_VOICE_REPEATS; расхождение — D2K_VOICE_FLAKY, а не «почти прошло».
 *
 * МЕТКА ОБЯЗАТЕЛЬНА ПО ТОЙ ЖЕ ПРИЧИНЕ, ЧТО ВЕЗДЕ. Без неё зонд идёт через наш
 * же обход и меряет его, а не коробку провайдера: на голосовых портах наш
 * профиль стоит ровно там же. Непомеченный прогон не молчит об этом — см.
 * d2k_voice_res.marked.
 */
#ifndef D2K_VOICE_H
#define D2K_VOICE_H

#include <stddef.h>
#include <stdint.h>

#include "d2k_meas.h"    /* d2k_tally — тот же счёт «сколько из скольких», что у QUIC */
#include "d2k_verdict.h" /* D2K_REASON_MAX */

#define D2K_VOICE_REPEATS 3

/* Сколько живых разговоров держать: больше одного бывает (второй звонок,
 * демонстрация экрана), и выбирать надо самый нагруженный, а не первый
 * попавшийся. Восемь — с запасом; стоимость нулевая, массив на стеке. */
#define D2K_VOICE_MAX_TARGETS 8

/* Потолок повторов у оракула. Отдельной величиной от D2K_VOICE_MAX_TARGETS:
 * это разные вещи, и держать их одним числом значит однажды поменять одно,
 * думая про другое. */
#define D2K_VOICE_MAX_REPEATS 8

typedef enum {
    /* Голосовой сервер отвечает — резать нечего. */
    D2K_VOICE_CLEAR = 0,
    /* Сервер молчит, публичный STUN на том же канале отвечает: UDP ходит,
       режут именно этот поток. */
    D2K_VOICE_BLOCKED,
    /* Молчит и публичный STUN: на канале не ходит UDP вообще или режут
       целиком. Обходить голос отдельно бессмысленно. */
    D2K_VOICE_NO_UDP,
    /* Живого разговора не нашлось — мерить нечего. НЕ «всё хорошо». */
    D2K_VOICE_NO_CALL,
    /* Повторы разошлись. */
    D2K_VOICE_FLAKY,
    /* ТОЧКА НЕ ОТВЕЧАЕТ ПОСТОРОННИМ, И МОЛЧАНИЕ НИЧЕГО НЕ ДОКАЗЫВАЕТ.
     *
     * Поле 17.09.2026: голосовая точка Дискорда молчит на STUN, на 48 нулей и
     * на 32 случайных байта одинаково — при ЖИВОМ разговоре через тот же
     * адрес. Она обслуживает только установленную сессию, по SSRC от гейтвея.
     * Значит шаг 1 («сервер ответил — значит достижим») не выполняется
     * никогда, и вердикт `blocked` выносился бы на исправном голосе.
     *
     * Этот класс появляется, когда молчание зонда опровергнуто ПРЯМЫМ
     * наблюдением: счётчик пакетов живого потока к той же точке растёт.
     * Тогда честный ответ — «мерить этим зондом нечем», а не «режут». */
    D2K_VOICE_NO_ORACLE,
    /* ИЗМЕРЕНИЕ НЕ ЗАКОНЧЕНО: наблюдение есть, вывода нет.
     *
     * Поток к точке идёт и ответов по нему нет — это настоящее наблюдение. Но
     * одного его мало: отделить «режут именно этот поток» от «UDP не ходит
     * вовсе» может только контроль на том же канале. Не спросили контроль —
     * значит не выбрали между двумя объяснениями, и называть первое из них
     * вердиктом нельзя. Отсутствие ответа — подозрение, недостаток данных —
     * незаконченное измерение, а не блокировка. */
    D2K_VOICE_UNMEASURED
} d2k_voice_verdict;

/* Куда слать зонд. packets — сколько пакетов ядро насчитало в потоке: по нему
 * выбирается самый живой разговор, если их несколько. */
typedef struct {
    uint32_t ip;   /* сетевой порядок, как в пакете */
    uint16_t port;
    /* КЛИЕНТ ЭТОГО ПОТОКА. Поток — пятёрка, а не адрес сервера: к одной
     * голосовой точке с роутера ходят разные устройства, и складывать их
     * записи значит прятать беду одного ответом другому. */
    uint32_t src_ip;
    uint16_t sport;
    int      packets;
    /* ОТВЕЧАЛ ЛИ КТО-НИБУДЬ С ЭТОЙ ТОЧКИ. 1 — у ядра есть поток к ней, по
     * которому шёл ОБРАТНЫЙ трафик (строка без пометки [UNREPLIED]).
     *
     * Признак, а не счётчик, и это важно: на этом роутере голосовой поток
     * уходит в железо ([FASTNAT]), и conntrack перестаёт считать пакеты —
     * замер 17.09 дал 5593, 5593, 5593, 5594 за три секунды при непрерывном
     * разговоре. Флаг состояния железо не стирает. */
    int      replied;
} d2k_voice_target;

/* Ищет живые голосовые потоки в таблице соединений (path; NULL — штатная).
 *
 * Возвращает сколько нашёл, не больше cap, по УБЫВАНИЮ числа пакетов: первым
 * идёт тот разговор, который человек прямо сейчас и ведёт.
 *
 * Смотрит только UDP и только на порты боевого профиля discord_udp: если
 * диапазоны разъедутся с профилем, зонд начнёт мерить не тот трафик, который
 * обходит движок. Свои же адреса (петля, приватные, link-local) отбрасывает —
 * голос идёт наружу, а приватный адрес назначения означает чужой NAT или наш
 * собственный редирект. */
size_t d2k_voice_targets(const char *path, d2k_voice_target *out, size_t cap);

/* Настройки прогона. Нулевая структура = «искать разговор сам, контроль по
 * умолчанию, блобы из штатного места». */
typedef struct {
    uint32_t    ip;           /* 0 — искать живой разговор */
    uint16_t    port;
    const char *ct_path;      /* NULL — /proc/net/nf_conntrack */
    const char *control;      /* NULL — умолчание (см. d2k_voice_control_default) */
    uint32_t    wait_ms;      /* 0 — 3000 */
    uint32_t    mark;
} d2k_voice_opt;

typedef struct {
    d2k_voice_verdict verdict;
    char     reason[D2K_REASON_MAX];
    uint32_t ip;
    uint16_t port;
    int      probes;   /* сколько зондов реально ушло на провод */
    int      marked;   /* 1 — метка запрошена И подтверждена на каждом зонде */
    char     arm[96];       /* найденная фальшивка, «stun:repeats=6»; пусто — не найдена */
    char     strategy[192]; /* строка стратегии для пула «Дискорд, голос»; пусто — нечего вставлять */
} d2k_voice_res;

/* Публичный STUN по умолчанию. Замер 04.09.2026 с роутера: Cloudflare на 3478
 * отвечает за 30 мс, Google на 19302 молчит целиком. Берём тот, что отвечает —
 * это число из замера, а не из документации. */
#define D2K_VOICE_CONTROL_DEFAULT "stun.cloudflare.com:3478"

/* Оракул: шлёт repeats параллельных зондов STUN на ip:port, каждый со СВОИМ
 * сокетом и СВОИМ идентификатором транзакции (чужой ответ не должен сойти за
 * наш), и считает, сколько ответило.
 *
 * pre/pre_len/copies — фальшивка ПЕРЕД запросом: copies отдельных датаграмм,
 * а не одна склеенная из copies копий (коробка считает датаграммы). pre=NULL —
 * зонд без фальшивки.
 *
 * Крючком, а не прямым вызовом, по той же причине, что d2k_quic_ask_hook:
 * тест обязан утверждать одно и то же с сетью и без неё, а метка сокета
 * (SO_MARK) требует прав, которых у теста нет. */
typedef d2k_tally (*d2k_voice_ask_fn)(uint32_t ip, uint16_t port,
                                      const uint8_t *pre, size_t pre_len, int copies,
                                      uint32_t wait_ms, uint32_t mark, int repeats,
                                      uint32_t *rtt_ms_out);
extern d2k_voice_ask_fn d2k_voice_ask_hook;

/* ЖИВ ЛИ ПОТОК РАЗГОВОРА К ЭТОЙ ТОЧКЕ ПРЯМО СЕЙЧАС.
 *
 * 1 — да (счётчик пакетов вырос между двумя снимками), 0 — нет, -1 — сказать
 * нечего (потока не видно, таблицы нет, задан явный адрес вместо поиска).
 *
 * Нужен ровно затем, чтобы не выдавать молчание зонда за блокировку: если
 * разговор идёт, значит точка достижима, и молчание — про зонд, а не про
 * коробку. Данные берутся оттуда же, откуда и цель (d2k_voice_targets), —
 * второго источника не заводится.
 *
 * Крючком по той же причине, что оракул: тест не имеет права ни ждать, ни
 * зависеть от таблицы соединений живой машины. */
typedef int (*d2k_voice_alive_fn)(const char *ct_path, uint32_t ip, uint16_t port);
/* Смысл: 1 — точка КОМУ-ТО отвечает (есть поток с обратным трафиком), 0 — есть
 * потоки, но все без ответа, -1 — потоков к ней не видно вовсе. */
extern d2k_voice_alive_fn d2k_voice_alive_hook;

/* Разрешение имени контрольного сервера в адрес. Крючком по той же причине:
 * тест не имеет права ходить в DNS. Возвращает 0 и заполняет ip/port. */
typedef int (*d2k_voice_resolve_fn)(const char *hostport, uint32_t *ip, uint16_t *port);
extern d2k_voice_resolve_fn d2k_voice_resolve_hook;

/* НАСТОЯЩИЙ оракул — умолчание d2k_voice_ask_hook. Нужен ровно тем, кто
 * подменил крючок и хочет вернуть его назад, а таких сегодня один: тест,
 * который сперва проверяет дисциплину дерева на заглушке, а потом сам оракул
 * на живых сокетах. Прятать его значило бы заставить тест завести ВТОРОЙ
 * экземпляр отправки и проверять им себя же. */
d2k_voice_ask_fn voice_ask_real(void);

/* Меряет голосовой поток. См. три слоя в шапке файла. */
d2k_voice_res d2k_voice_run(const d2k_voice_opt *opt);

#endif /* D2K_VOICE_H */
