/* d2k_crypto.h — криптография, на которой стоит разбор QUIC Initial.
 *
 * Браузеры ходят по HTTP/3 поверх QUIC, а первый пакет соединения (Initial)
 * зашифрован ключами, которые выводятся из идентификатора соединения (DCID) —
 * он лежит в заголовке открытым текстом. Расшифровать его может любая сторона
 * на пути (RFC 9001 §5.2), и в этом смысл: датапату нужно то же самое, чтобы
 * достать имя сайта и привязать к нему обход.
 *
 * Отсюда общий модуль, а не две копии: датапату эта арифметика нужна на
 * горячем пути (снять защиту заголовка, расшифровать Initial), а замеру —
 * чтобы тем же способом проверить чужой ответ (см. donor
 * z2k-detect/internal/quicprobe: тот же приём уже используется как оракул —
 * ответ сервера отличают от чужой инъекции тем, что он раскрывается ключами,
 * выведенными из НАШЕГО DCID).
 *
 * ПРОВЕРЕНО ВЕКТОРАМИ, НЕ НА ГЛАЗ. Каждая из шести функций сверена в
 * test_crypto.c с опубликованными байтами: FIPS 180-4 (SHA-256), RFC 4231
 * (HMAC-SHA256), RFC 9001 Приложение A.1 (HKDF-Extract/Expand-Label на
 * реальном DCID) и Приложение A.2 (AES-128-ECB маски защиты заголовка и
 * AES-128-GCM расшифровки настоящего клиентского Initial), FIPS-197
 * Приложение B (обычный AES-128). Криптография либо совпадает с published
 * байтами, либо неверна — третьего не бывает.
 *
 * БЕЗ ТАБЛИЦ, ЗАВИСЯЩИХ ОТ СЕКРЕТА. Классический учебный AES читает
 * S-box[secret_byte] — индекс зависит от данных, а не от счётчика раунда, и
 * именно так утекает время доступа к кэшу (атака Бернстайна на AES по кэшу).
 * Реализация здесь считает S-box формулой (обращение в GF(2^8) через
 * возведение в степень 254, аффинное преобразование — see crypto.c), и то же
 * верно для GHASH и умножения в GF(2^8)/GF(2^128) внутри GCM: только сдвиги и
 * XOR по битам операнда, ни одной таблицы, индексируемой байтом ключа,
 * открытого или защищаемого текста. На роутере это, возможно, лишняя
 * осторожность — но она ничего не стоит и снимает целый класс вопросов.
 */
#ifndef D2K_CRYPTO_H
#define D2K_CRYPTO_H

#include <stddef.h>
#include <stdint.h>

/* SHA-256 (FIPS 180-4) от произвольного числа байт. */
void d2k_sha256(const uint8_t *in, size_t n, uint8_t out[32]);

/* HMAC-SHA256 (RFC 2104 / FIPS 198-1). Ключ любой длины: короче блока (64
 * байта) — дополняется нулями, длиннее — сжимается через d2k_sha256, как
 * того требует стандарт. */
void d2k_hmac_sha256(const uint8_t *key, size_t klen,
                      const uint8_t *msg, size_t mlen, uint8_t out[32]);

/* HKDF-Extract (RFC 5869 §2.2): PRK = HMAC-Hash(salt, ikm). Соль — ключ HMAC,
 * а не сообщение; для инициализации QUIC salt — соль версии, ikm — DCID
 * (RFC 9001 §5.2). Пустая соль (slen==0) даёт корректный результат сама
 * собой: HMAC дополняет короткий ключ нулями до блока, и ноль байт нулями
 * даёт то же самое, что HashLen явных нулей из RFC 5869 — отдельной ветки не
 * нужно. */
void d2k_hkdf_extract(const uint8_t *salt, size_t slen,
                       const uint8_t *ikm, size_t ilen, uint8_t out[32]);

/* HKDF-Expand-Label из TLS 1.3 (RFC 8446 §7.1), в QUIC — без изменений
 * (RFC 9001 §5.1). Контекст ВСЕГДА пустой: для ключевого расписания QUIC
 * Initial он не используется, поэтому параметра context в сигнатуре нет.
 *
 * label — короткий ASCII-литерал из нашего же кода ("client in", "quic key",
 * "quic iv", "quic hp" и т.п.), не из сети: длина не проверяется в рантайме,
 * потому что источник — не сеть, а вызывающий, которому положено знать, что
 * шлёт. Префикс "tls13 " добавляется внутри, по стандарту. */
void d2k_hkdf_expand_label(const uint8_t secret[32], const char *label,
                            uint8_t *out, size_t out_len);

/* AES-128 в GCM (NIST SP 800-38D), IV ровно 96 бит — единственная длина,
 * которую использует QUIC (nonce = iv, поксоренный с номером пакета,
 * RFC 9001 §5.3), и стандарт для неё даёт упрощённый счётчик без отдельного
 * прохода GHASH по самому IV.
 *
 * Контракт: ct включает 16-байтовый тег ПОСЛЕДНИМИ байтами (обычная
 * конвенция AEAD seal/output), out получает ct_len-16 байт открытого текста.
 * Короче 16 байт ct не бывает — это не "обрывок предположительно нашего
 * пакета", это гарантированно не пакет, поэтому такой вызов сразу -1.
 *
 * ПРОВЕРКА ТЕГА ДО РАСШИФРОВКИ: тег сверяется по GHASH от самого шифротекста
 * (GHASH не требует его расшифровывать), и только при совпадении текст
 * пишется в out через CTR. При несовпадении out не трогается вовсе —
 * непроверенный расшифрованный текст не публикуется никогда, у вызывающего
 * нет способа случайно использовать его, не проверив код возврата.
 * Возвращает 0 — тег сошёлся, текст в out подлинный; -1 — тег не сошёлся или
 * ct короче тега. */
int d2k_aes128_gcm_decrypt(const uint8_t key[16], const uint8_t iv[12],
                            const uint8_t *aad, size_t aad_len,
                            const uint8_t *ct, size_t ct_len, uint8_t *out);

/* Один блок AES-128, ТОЛЬКО шифрование (FIPS-197). Обратный шифр (InvSubBytes
 * и т.д.) этому модулю не нужен нигде: GCM строится на CTR, который вызывает
 * прямой шифр для обеих сторон, а защита заголовка QUIC (RFC 9001 §5.4.1) —
 * это AES-ECB-шифрование сэмпла шифротекста что при наложении маски, что при
 * снятии; операция симметричная именно потому, что это XOR с одной и той же
 * маской, а не отдельное расшифрование. */
void d2k_aes128_ecb(const uint8_t key[16], const uint8_t in[16], uint8_t out[16]);

#endif
