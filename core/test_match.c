/* test_match.c — узнавание коробки по примете: сравнение отпечатков с
 * допуском (задача 2, см. .superpowers/sdd/2026-09-07-engine-c-both-transports/
 * task-2-brief.md).
 *
 * Каталог хранит МОДЕЛИ ПОВЕДЕНИЯ, а не устройства (см. шапку
 * d2k_catalog.h про d2k_cat_box) — точное сравнение примет плодило бы
 * коробку на каждое дрожание маршрута или погрешность прибора, а два разных
 * механизма с совпавшими числами не должны слиться в одну модель только
 * потому, что числа сошлись.
 *
 * Четыре проверки из брифа задачи (шаг 1), ниже ДОСЛОВНО (см. задание) —
 * они несут смысл задания и не переформулированы:
 *   1. дрожание маршрута (TTL ±D2K_TTL_SLACK) не плодит коробку, а TTL за
 *      пределами допуска — плодит;
 *   2. погрешность прибора по объёму (±D2K_VOLUME_SLACK) не плодит коробку,
 *      а объём за пределами допуска — плодит;
 *   3. разный РОД сигнала (rst против silence) с совпавшим числом не
 *      сливается допуском — допуск действует только внутри одного рода;
 *   4. настоящий каталог с роутера узнаёт каждую свою коробку саму себя и
 *      не узнаёт выдуманную чужую.
 */
#include <stdio.h>
#include <string.h>

#include "d2k_catalog.h"

static int fails;
#define CHECK(cond, msg)                                   \
    do {                                                   \
        if (!(cond)) {                                     \
            printf("ПРОВАЛ: %s\n", msg);                   \
            fails++;                                       \
        }                                                  \
    } while (0)

int main(void) {
    /* --- дрожание маршрута не плодит коробку ------------------------------- */
    {
        d2k_cat_fp a = {0}, b = {0};
        a.method = 1; a.n_sig = 1; strcpy(a.sig[0].kind, "rst"); a.sig[0].ttl = 126;
        b = a;                                                    b.sig[0].ttl = 127;
        CHECK(d2k_fp_same(&a, &b) == 1, "TTL 126 и 127 сочтены разными коробками");
        b.sig[0].ttl = 120;
        CHECK(d2k_fp_same(&a, &b) == 0, "TTL 126 и 120 сочтены одной коробкой");
    }
    /* --- погрешность прибора по объёму не плодит коробку -------------------- */
    {
        d2k_cat_fp a = {0}, b = {0};
        a.method = 2; a.n_sig = 1; strcpy(a.sig[0].kind, "volume"); a.sig[0].volume = 19;
        b = a;                                                     b.sig[0].volume = 23;
        CHECK(d2k_fp_same(&a, &b) == 1, "19 и 23 КБ сочтены разными коробками");
        b.sig[0].volume = 40;
        CHECK(d2k_fp_same(&a, &b) == 0, "19 и 40 КБ сочтены одной коробкой");
    }
    /* --- разный механизм не сливается допуском ------------------------------ */
    {
        d2k_cat_fp a = {0}, b = {0};
        a.method = 1; a.n_sig = 1; strcpy(a.sig[0].kind, "rst");     a.sig[0].ttl = 126;
        b.method = 1; b.n_sig = 1; strcpy(b.sig[0].kind, "silence"); b.sig[0].ttl = 126;
        CHECK(d2k_fp_same(&a, &b) == 0, "сброс и молчание слились в одну коробку");
    }
    /* --- поиск по каталогу находит и не находит ----------------------------- */
    {
        d2k_catalog c; char err[200] = {0};
        CHECK(d2k_catalog_load("testdata/catalog-real.json", &c, err, sizeof err) == 0, "загрузка");
        CHECK(c.n_boxes > 0, "нет коробок");
        CHECK(d2k_catalog_match(&c, &c.boxes[0].fp) == 0, "коробка не узнала саму себя");
        d2k_cat_fp alien = {0}; alien.method = 99; alien.n_sig = 1;
        strcpy(alien.sig[0].kind, "выдуманный"); alien.sig[0].ttl = 7;
        CHECK(d2k_catalog_match(&c, &alien) == -1, "чужая примета узнана как своя");
        d2k_catalog_free(&c);
    }

    if (fails) { printf("ПРОВАЛОВ: %d\n", fails); return 1; }
    printf("узнавание: все проверки прошли\n");
    return 0;
}
