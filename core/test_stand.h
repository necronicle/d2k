/* test_stand.h — общий стенд-мишень для тестов ядра: петля на локалхосте в
 * отдельном потоке, ведущая себя как коробка одного из нескольких классов.
 *
 * Общий для test_meas.c и test_verdict.c: стенд — ОДИН, у него один набор
 * режимов на всех, а не по копии на каждый тест. Это НЕ требование брифа
 * задачи (в task-2-brief.md такой фразы нет) — это прямое указание из
 * сопроводительного письма к задаче 2: «второй стенд не заводи». Первые два
 * режима — ровно то, что было в стенде задачи 1 (test_meas.c), под теми же
 * номерами и с той же логикой; задача 2 дописывает остальные сюда же, а не
 * рядом.
 *
 * mode:
 *   0 — отвечает всегда;
 *   1 — префиксный матчер: молчит, если ПЕРВЫЙ прочитанный сегмент целиком
 *       (>= 4 байт) совпадает с d2k_test_sig. Смотрит только в начало и не
 *       ждёт хвоста — разрез внутри сигнатуры его обманывает;
 *   2 — пересобирает: копит всё, что придёт по соединению, пока не наступит
 *       пауза длиннее D2K_TEST_IDLE_MS без новых байт, и ищет d2k_test_sig
 *       ГДЕ УГОДНО в накопленном, а не только в начале. Разрез на несколько
 *       кусков её не обманывает — обмануть может только другое содержимое
 *       (см. контроль другим именем в test_verdict.c);
 *   3 — молчит на любое начало с 0x16, независимо от остального содержимого:
 *       коробка, которой имя ни при чём, режет весь класс «похоже на
 *       TLS-запись» — и триггер, и контроль с ней неразличимы;
 *   4 — копит РОВНО s->want байт и только тогда отвечает; если отправитель
 *       замолчал раньше срока (потерял хвост куска на короткой записи),
 *       ответа не будет никогда — так наблюдается внешний эффект
 *       недолеченной короткой записи (см. соответствующий тест в
 *       test_meas.c). Раньше стоял под номером 2 — сдвинут, чтобы номер 2
 *       достался пересборке: за него теперь чётко в обоих файлах.
 *   5 — считает подключения (s->n_accepted, обязан быть обнулён вызывающим
 *       ДО stand_start — тот же порядок, что и s->want у режима 4). ВСЕГДА
 *       молчит (читает через общий recv() ниже, как и остальные режимы
 *       этого блока, и закрывает без ответа) — но после ПЯТОГО принятого
 *       подключения дополнительно НАВСЕГДА закрывает слушающий сокет:
 *       шестое и любое следующее подключение получит отказ уже на
 *       connect(), то есть d2k_meas_once вернёт -1, а не 0. Нужен ровно
 *       одному тесту в test_verdict.c — сочетанию «часть повторов шага —
 *       настоящая тишина, часть — ошибка транспорта» (0 < err < repeats);
 *   6 — отвечает на первые 3 подключения, дальше молчит (без ошибок
 *       транспорта). Тоже считает через s->n_accepted, тоже обнуляется
 *       вызывающим до stand_start. Нужен тесту на подтверждение clear: без
 *       него «3 из 3» и «3 из 3, а следующие два уже молчат» неразличимы.
 */
#ifndef D2K_TEST_STAND_H
#define D2K_TEST_STAND_H

#include <netinet/in.h>
#include <pthread.h>
#include <stddef.h>
#include <stdint.h>
#include <string.h>
#include <sys/socket.h>
#include <sys/time.h>
#include <time.h>
#include <unistd.h>

/* Сигнатура «похоже на TLS-приветствие», которую распознают режимы 1 и 2.
 * Общая с построением тестовых hello в обоих .c — иначе стенд и байты,
 * которые он проверяет, могли бы разойтись независимо друг от друга. */
static const uint8_t d2k_test_sig[4] = { 0x16, 0x03, 0x01, 0x00 };

/* Насколько дольше самой длинной паузы между кусками в проверках (5000 мкс —
 * см. вызовы d2k_meas/d2k_classify с gap_us=5000) стенд обязан молчать сам,
 * прежде чем решить, что читать больше нечего: без запаса в порядок
 * величины разрез опыта неотличим от «стенд поторопился ответить, не
 * дождавшись второго куска». 100 мс — это ×20 к 5 мс паузы, тот же приём,
 * что задаёт CONNECT_TIMEOUT_MS/WAIT_CEIL_MS в meas.c: запас, а не число «на
 * глаз» под конкретный тест. */
#define D2K_TEST_IDLE_MS 100

struct stand { int fd; uint16_t port; int mode; size_t want; int n_accepted; };

static void *stand_run(void *arg) {
    struct stand *s = arg;
    for (;;) {
        int c = accept(s->fd, NULL, NULL);
        if (c < 0) { return NULL; }

        if (s->mode == 4) {
            /* Пауза дольше d2k_send_timeout_s обязательна: короткая запись
               НАБЛЮДАЕТСЯ только когда SO_SNDTIMEO успевает истечь при
               недренирующем приёмнике — см. идентичный комментарий у теста
               короткой записи в test_meas.c. */
            struct timespec pause_ts = { 1, 500000000L }; /* 1.5 с */
            nanosleep(&pause_ts, NULL);
            uint8_t buf[65536];
            size_t got = 0;
            while (got < s->want) {
                ssize_t n = recv(c, buf, sizeof buf, 0);
                if (n <= 0) { break; }
                got += (size_t)n;
            }
            if (got == s->want) {
                const uint8_t ans[7] = { 0x16, 0x03, 0x03, 0x00, 0x02, 0x02, 0x00 };
                (void)send(c, ans, sizeof ans, 0);
            }
            close(c);
            continue;
        }

        if (s->mode == 2) {
            /* Пересборка: читаем, пока не наступит тишина дольше idle-окна —
               значит, отправитель дописал кусок (или всё приветствие
               целиком) — и ищем сигнатуру ГДЕ УГОДНО в накопленном. Этим и
               только этим отличается от режима 1, который смотрит лишь в
               первый сегмент. */
            uint8_t acc[8192];
            size_t got = 0;
            struct timeval tv = { 0, D2K_TEST_IDLE_MS * 1000 };
            setsockopt(c, SOL_SOCKET, SO_RCVTIMEO, &tv, sizeof tv);
            for (;;) {
                if (got >= sizeof acc) { break; }
                ssize_t n = recv(c, acc + got, sizeof acc - got, 0);
                if (n <= 0) { break; } /* таймаут тишины или обрыв — читать больше нечего */
                got += (size_t)n;
            }
            int blocked = 0;
            if (got >= sizeof d2k_test_sig) {
                for (size_t i = 0; i + sizeof d2k_test_sig <= got; i++) {
                    if (memcmp(acc + i, d2k_test_sig, sizeof d2k_test_sig) == 0) {
                        blocked = 1;
                        break;
                    }
                }
            }
            if (!blocked) {
                const uint8_t ans[7] = { 0x16, 0x03, 0x03, 0x00, 0x02, 0x02, 0x00 };
                (void)send(c, ans, sizeof ans, 0);
            }
            close(c);
            continue;
        }

        uint8_t buf[8192];
        ssize_t n = recv(c, buf, sizeof buf, 0);
        int blocked = 0;
        if (s->mode == 1 && n >= (ssize_t)sizeof d2k_test_sig &&
            memcmp(buf, d2k_test_sig, sizeof d2k_test_sig) == 0) {
            blocked = 1;
        }
        if (s->mode == 3 && n >= 1 && buf[0] == 0x16) {
            /* Коробке, которая режет весь класс «похоже на TLS-запись»,
               имя внутри не нужно — блокирует по одному ведущему байту,
               общему у триггера и контроля. Отсюда и вердикт inconclusive:
               контроль другим именем здесь ничего не отличает. */
            blocked = 1;
        }
        if (s->mode == 5) {
            /* ВСЕГДА блокирует (см. подробности в шапке файла) — но, как и
               остальные режимы этого общего блока, только ПОСЛЕ recv(): без
               него close() уходил бы с непрочитанными байтами в буфере, а
               это в POSIX-сокетах — абортивное закрытие (RST) вместо
               обычного FIN. Для одноразовой посылки это неважно, но у
               разреза на 1 клиент шлёт ВТОРОЙ кусок уже ПОСЛЕ паузы, и
               запись в сокет, получивший RST, валит процесс сигналом
               SIGPIPE — именно так падал первый вариант этого режима,
               круг правок по ревью (см. test-2-report.md). */
            blocked = 1;
            s->n_accepted++;
            if (s->n_accepted >= 5) {
                /* Слушающий сокет закрывается НАВСЕГДА — 6-е подключение
                   (третий повтор «разреза на 1») получит отказ уже на
                   connect(), d2k_meas_once вернёт -1, а не 0. Порядок
                   безопасен без гонки: между двумя send() одного разреза
                   клиент сам делает паузу gap_us (см. d2k_meas_once) — этого
                   на порядки достаточно, чтобы close(s->fd) здесь успел
                   выполниться до следующего connect() клиента. */
                close(s->fd);
            }
        }
        if (s->mode == 6) {
            /* Отвечает на первые 3 подключения (столько же, сколько
               обычных repeats в этом дереве), дальше молчит без ошибок
               транспорта — проверяет, что подтверждение
               (D2K_CLEAR_CONFIRM_REPEATS в verdict.c) действительно
               опрашивается, а не пропускается. */
            s->n_accepted++;
            blocked = s->n_accepted > 3;
        }
        if (!blocked) {
            const uint8_t ans[7] = { 0x16, 0x03, 0x03, 0x00, 0x02, 0x02, 0x00 };
            (void)send(c, ans, sizeof ans, 0);
        }
        close(c);
    }
}

static uint16_t stand_start(struct stand *s, int mode) {
    s->fd = socket(AF_INET, SOCK_STREAM, 0);
    struct sockaddr_in a;
    memset(&a, 0, sizeof a);
    a.sin_family = AF_INET;
    a.sin_addr.s_addr = htonl(0x7f000001);
    a.sin_port = 0;
    bind(s->fd, (struct sockaddr *)&a, sizeof a);
    socklen_t l = sizeof a;
    getsockname(s->fd, (struct sockaddr *)&a, &l);
    listen(s->fd, 8);
    s->mode = mode;
    /* s->want и s->n_accepted НЕ трогаем: режимы 4-6 ожидают, что
       вызывающий выставит их ДО stand_start (см. тест короткой записи и
       тесты на частичный сбой транспорта/подтверждение clear) — здесь
       было бы поздно и затёрло бы уже установленное значение. */
    s->port = ntohs(a.sin_port);
    pthread_t t;
    pthread_create(&t, NULL, stand_run, s);
    pthread_detach(t);
    return s->port;
}

#endif /* D2K_TEST_STAND_H */
