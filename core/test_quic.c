/* test_quic.c — разбор QUIC Initial проверяется НАСТОЯЩИМИ пакетами, а не
 * самодельными: криптография Initial реальна (RFC 9001), и подделанный
 * заголовок с произвольными длинами полей доказывал бы только то, что
 * разбор согласен сам с собой, а не то, что он понимает настоящий QUIC.
 *
 * Источники:
 *   - RFC 9001, приложение A.2 — клиентский Initial версии 1 целиком, тот же
 *     массив байт, что и protected_packet в test_crypto.c (см. там же
 *     обоснование: сверено с донором z2k-detect/internal/quicprobe и
 *     независимым пересчётом через crypto/aes+crypto/cipher стандартной
 *     библиотеки Go). Здесь его же гоняет ПУБЛИЧНЫЙ интерфейс модуля
 *     (d2k_quic_is_initial/d2k_quic_sni), а не отдельные примитивы.
 *   - RFC 9369, приложение A.2 — версия 2 ТОГО ЖЕ ClientHello (нарочно
 *     опубликована авторами RFC для лёгкой сверки реализаций: тот же DCID,
 *     тот же ClientHello с именем example.com, другие соль/метки/номер
 *     версии/нумерация типа пакета). Байты сверены напрямую по тексту
 *     https://www.rfc-editor.org/rfc/rfc9369.txt при разработке этого файла
 *     (раздел 3.1, 3.3.1, приложение A.1-A.2), а не набраны по памяти —
 *     это ровно та "ловушка v2", о которой предупреждает бриф задачи: без
 *     этого вектора можно было бы случайно захардкодить v1-соль/метки и не
 *     заметить ошибку, потому что единственный проверяемый пример был бы v1.
 *   - Кастомные вектора на пересборку кадров CRYPTO (v1_reordered, v1_gap,
 *     v1_unknown_tail) — тот же ClientHello (RFC 9001 A.2), но нарезанный на
 *     кадры вручную, с теми же ключами, что и в RFC 9001 A.1 (DCID тот же).
 *     v1_reordered и v1_gap собраны Initial.Marshal() донора
 *     (z2k-detect/internal/quicprobe/initial.go, уже провалидирован в
 *     задаче 1 побайтной сверкой того же RFC 9001 A.2) поверх ручной
 *     раскладки кадров — донор кодирует кадры в ТОМ порядке, в котором они
 *     лежат в Crypto []CryptoFrame, независимо от значения Offset, то есть
 *     порядок передачи и порядок смещений разведены нарочно.
 *     v1_unknown_tail собран вручную поверх тех же низкоуровневых функций
 *     донора (seal/applyHeaderProtection/deriveKeys — Marshal() кадр
 *     произвольного "сырого" типа дописать не даёт). Во всех трёх
 *     самосогласованность (пересборка по смещениям даёт исходный ClientHello,
 *     либо хвост за кадром CRYPTO — ровно ожидаемый один байт) подтверждена
 *     независимой сборкой в разовом Go-скрипте (crypto/aes+crypto/cipher
 *     стандартной библиотеки, вне репозитория) ДО переноса байт сюда — см.
 *     отчёт задачи.
 *   - v1_ack_zero_ranges и v1_ack_huge_range_count — круг правок по ревью
 *     2026-09-06: путь разбора кадра ACK (largest/delay/range_count/
 *     first_range плюс цикл по заявленным диапазонам) не был проверен ни
 *     одним вектором, только чтением кода. Собраны той же техникой, что и
 *     v1_unknown_tail (seal/applyHeaderProtection/deriveKeys донора напрямую,
 *     без Initial.Marshal — у него нет способа положить кадр ACK перед
 *     CRYPTO). Самосогласованность (после ACK лежит ровно кадр CRYPTO с
 *     ClientHello целиком; восьмибайтовый варинт range_count у второго
 *     вектора декодируется ровно в 2^62-1) подтверждена тем же приёмом —
 *     независимой расшифровкой в разовом Go-скрипте до переноса байт сюда.
 */
