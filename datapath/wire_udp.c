/* wire_udp.c — сборка UDP-датаграммы на провод.
 *
 * Тот же подход, что в wire.c, и не просто ради единообразия: байт за байтом,
 * без наложения структур на буфер (на MIPS выравнивание не гарантировано), без
 * плавающей арифметики (коробки идут без сопроцессора). wire.c переписывать не
 * нужно — здесь ровно то же самое для другого протокола транспорта.
 *
 * UDP проще TCP заголовком, но не проще смыслом: приёмы, завязанные на номера
 * последовательности TCP (сдвиг, перекрытие), для UDP не существуют — у
 * дейтаграмм нет ни последовательности, ни окна, ни опций. Единственные
 * плечи порчи, применимые к IP-заголовку датаграммы, — заниженный TTL и
 * обнулённый идентификатор; они те же самые поля, что и у TCP, потому что
 * лежат в IP, а не в транспорте.
 */
#include <string.h>

#include "d2k_wire.h"

#define IP_HDR  20
#define UDP_HDR 8

static void wr16(uint8_t *p, uint16_t v) {
    p[0] = (uint8_t)(v >> 8);
    p[1] = (uint8_t)v;
}

/* Сумма по RFC 1071, слово в слово как в wire.c. Не вынесена в общий
 * заголовок: у ctlprobe.c в этом же датапате уже есть собственные wr16/wr32
 * ровно по той же причине — модули пакетного пути не делят между собой три
 * строки арифметики ради экономии копипаста, каждый самодостаточен. */
static uint32_t sum16(const uint8_t *b, size_t n, uint32_t acc) {
    size_t i = 0;
    for (; i + 1 < n; i += 2) {
        acc += (uint32_t)b[i] << 8 | b[i + 1];
    }
    if (i < n) {
        acc += (uint32_t)b[i] << 8;
    }
    return acc;
}

static uint16_t fold(uint32_t acc) {
    while (acc >> 16) {
        acc = (acc & 0xffff) + (acc >> 16);
    }
    return (uint16_t)~acc;
}

/* Псевдозаголовок UDP (RFC 768): раскладка та же, что у псевдозаголовка TCP
 * (RFC 793) — адреса, ноль, протокол, длина. Отличие ровно в двух местах:
 * протокол здесь 17, а длина — это длина всей UDP-датаграммы (заголовок plus
 * данные), а не длина TCP-сегмента.
 *
 * Адреса, как и в wire.c, принимаются сырыми байтами: в d2k_conn они лежат в
 * сетевом порядке, и превращение их в число под wr32 перевернуло бы адрес на
 * little-endian ровно так же, как это уже один раз случилось с TCP. */
static uint32_t pseudo_sum(const uint8_t *src4, const uint8_t *dst4, size_t udp_len) {
    uint8_t ph[12];
    memcpy(ph + 0, src4, 4);
    memcpy(ph + 4, dst4, 4);
    ph[8] = 0;
    ph[9] = 17; /* UDP */
    wr16(ph + 10, (uint16_t)udp_len);
    return sum16(ph, sizeof ph, 0);
}

size_t d2k_wire_build_udp(const d2k_conn *c, const d2k_emit *e,
                          uint8_t *out, size_t cap) {
    if (!c || !e || !out) {
        return 0;
    }

    /* Четыре просьбы, которые для UDP нельзя честно исполнить, — отказ (0),
     * а не тихая сборка без запрошенного:
     *
     *   - приставка перекрытия (pre/pre_len) — приём поверх номеров
     *     последовательности TCP: сегмент едет с seq на pre_len меньше
     *     начала нагрузки, чтобы сервер счёл приставку уже полученной и
     *     отбросил её, а коробка сложила в поток. У UDP последовательности
     *     нет вовсе, и понятие «раньше по потоку» к дейтаграммам
     *     неприменимо;
     *
     *   - сдвиг номера последовательности (e->seq_shift) — тот же класс,
     *     что и приставка выше, только прямой сдвиг вместо копии байт
     *     впереди: см. комментарий у seq_shift в wire.c («сегмент уезжает за
     *     окно сервера»). У дейтаграммы нет ни последовательности, ни окна —
     *     то самое основание, по которому отвергается pre_len;
     *
     *   - D2K_POISON_TCPTS_BACK — метка времени со сдвигом назад — это
     *     опция заголовка TCP. У UDP заголовка без опций опций не
     *     существует вовсе, вставлять их некуда;
     *
     *   - D2K_POISON_BADSUM — эта сборка не умеет портить контрольную сумму
     *     по требованию (см. комментарий перед подсчётом суммы ниже, почему
     *     это решение, а не пробел).
     *
     * Собрать посылку молча, отбросив непонятное поле или бит и сделав вид,
     * что просили меньше, — значит применить план, отличный от того, что
     * попросили, и не сказать об этом: то, что описывает d2k_wire.h как
     * запрет молча подменять запрошенное на похожее. */
    if (e->pre_len != 0 || e->seq_shift != 0 ||
        (e->poison & (D2K_POISON_TCPTS_BACK | D2K_POISON_BADSUM)) != 0) {
        return 0;
    }

    const size_t udp_len = UDP_HDR + e->len;
    const size_t total = IP_HDR + udp_len;
    if (total > cap || total > 0xffff) {
        return 0;
    }
    memset(out, 0, IP_HDR + UDP_HDR);

    /* --- IPv4 --- (поле в поле как в wire.c; отличается только протокол) */
    out[0] = 0x45;                       /* версия 4, длина заголовка 5 слов */
    out[1] = 0;                          /* DSCP/ECN */
    wr16(out + 2, (uint16_t)total);
    /* Идентификатор: либо ноль по требованию порчи, либо чужой плюс единица
       — та же ловушка совпадения идентификатора, что и у TCP: сборщик
       фрагментов на стороне получателя может счесть независимые дейтаграммы
       частями одной. */
    wr16(out + 4, (e->poison & D2K_POISON_IPID_ZERO) ? 0
                                                     : (uint16_t)(c->ip_id + 1));
    /* Не фрагментировать: эта функция не умеет фрагментацию (отдельное плечо
       обхода, которого здесь ещё нет) и всегда собирает ОДНУ цельную
       дейтаграмму. Разрешить IP-фрагментацию по пути значило бы отдать сборку
       чужому сборщику фрагментов — а он на разных узлах ведёт себя по-разному
       (см. запись про перекрывающиеся IP-фрагменты на Linux) и это уже не то,
       что описывает план. */
    wr16(out + 6, 0x4000);
    /* TTL: порча задаёт значение — фальшивка умрёт по дороге, не дойдя до
       сервера, но коробку пройдёт. Без порчи — TTL исходного пакета, иначе
       свой умолчательный, как и у TCP. */
    out[8] = e->ttl ? e->ttl : (c->ttl ? c->ttl : 64);
    out[9] = 17;                         /* UDP */
    wr16(out + 10, 0);                   /* сумма считается ниже */
    memcpy(out + 12, &c->src_ip, 4);
    memcpy(out + 16, &c->dst_ip, 4);
    wr16(out + 10, fold(sum16(out, IP_HDR, 0)));

    /* --- UDP --- */
    uint8_t *u = out + IP_HDR;
    memcpy(u + 0, &c->src_port, 2);
    memcpy(u + 2, &c->dst_port, 2);
    wr16(u + 4, (uint16_t)udp_len);
    wr16(u + 6, 0);                      /* сумма считается ниже */

    if (e->len) {
        memcpy(out + IP_HDR + UDP_HDR, e->bytes, e->len);
    }

    /* Сумма UDP поверх IPv4 формально не обязательна: RFC 768 разрешает
       записать в это поле ноль и объявляет его значением «не считалась».
       Нам эта лазейка не подходит: коробка на пути не обязана верить нам на
       слово и вполне может отбрасывать дейтаграммы с нулевой или неверной
       суммой как испорченные транспортом — а тогда наша фальшивка не
       дойдёт даже до неё, не то что до сервера, и весь приём смысла не
       имеет. Поэтому сумма считается всегда, безусловно.

       D2K_POISON_BADSUM для UDP отвергается ВЫШЕ, тем же отказом, что и
       pre_len, seq_shift и D2K_POISON_TCPTS_BACK, — но не по той же причине,
       что абзац выше: заявить, что порченную дейтаграмму «тоже могла бы отбросить
       коробка», было бы такой же неизмеренной догадкой, просто в другую
       сторону. Настоящая причина измеримая: фальшивку в этом плане уже
       топит TTL (поле e->ttl выше) — плечо «укороченное время жизни» убивает
       копию раньше сервера, а значение e->ttl приходит РАЗВЁРТКОЙ плана, а
       не вычисляется здесь из входящего пакета. Эта способность в проекте
       уже есть и она уже измерена; второй механизм для той же цели прямо
       сейчас был бы кодом впереди замера. Если когда-нибудь замер покажет
       несостоятельность TTL-фальшивок на каком-то пути, порченая сумма
       станет кандидатом — и появится вместе с этим замером, а не раньше. */
    uint32_t acc = pseudo_sum(out + 12, out + 16, udp_len);
    acc = sum16(out + IP_HDR, udp_len, acc);
    uint16_t ck = fold(acc);
    /* Если результат честного подсчёта — ровно ноль, писать его как есть
       нельзя: ноль в этом поле зарезервирован под «сумма не считалась», а мы
       её только что посчитали. Дополнение до единицы кодирует ноль двумя
       битовыми образами, 0x0000 и 0xffff, и они арифметически
       взаимозаменяемы для проверки — но не для получателя, который читает
       0x0000 как признак пропуска проверки. На случайных данных это
       наступает примерно на одной дейтаграмме из 65536 (2^16 равновероятных
       значений суммы, ноль — одно из них), поэтому в обычном прогоне тестов
       не всплывёт — здесь это проверяется отдельно, на подобранной
       нагрузке, которая специально даёт ноль. */
    if (ck == 0) {
        ck = 0xffff;
    }
    wr16(u + 6, ck);

    return total;
}
