/* d2k_nat.h — КАКИМ АДРЕСОМ НАС ВИДИТ СЕРВЕР.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. Датапат вклинивает свои пакеты сырым сокетом, копируя
 * адреса из пакета, который лежит в очереди. Для трафика САМОГО роутера этого
 * достаточно: адрес там уже внешний. Для ТРАНЗИТНОГО — нет: очередь висит на
 * mangle POSTROUTING, а SNAT/MASQUERADE делается в nat POSTROUTING, то есть
 * ПОЗЖЕ. В очереди у транзитного пакета стоит ещё локальный адрес клиента.
 *
 * Замерено на роутере Марка 13.09.2026 (tcpdump на ppp0): все посылки плана
 * уходили с `192.168.1.117` вместо `88.87.93.11`. Провайдер такое выбрасывает,
 * до сервера не доходит ничего. Следствие было тяжёлым и незаметным: обход
 * работал ТОЛЬКО для трафика самого роутера, а для любого устройства за ним —
 * нет. Собственный зонд подтверждения ходит с роутера и потому получал 200 на
 * той же цели, на которой клиент за роутером получал ноль: доказательство
 * было настоящим, но не про тот путь.
 *
 * ЗАЧЕМ СПРАШИВАТЬ, ЕСЛИ АДРЕС МЫ НЕ МЕНЯЕМ. Затем, что пакет с локальным
 * адресом превращается во внешний РОВНО ОДНИМ способом: попадая в ту же
 * запись conntrack, что и поток клиента, и получая её трансляцию. Есть
 * запись — NAT сделает всё сам, и на проводе наша посылка неотличима от
 * клиентской. Нет записи — посылка уйдёт с локальным адресом и умрёт у
 * провайдера, а план будет объявлен применённым. Поэтому наличие записи
 * ПРОВЕРЯЕТСЯ, и без неё план честно отвергается.
 *
 * ПОЧЕМУ НЕ ПОДСТАВЛЯТЬ ВНЕШНИЙ АДРЕС САМИМ. Пробовано на живом роутере
 * 13.09.2026 и отвергнуто замером: пакет, собранный с уже внешним адресом,
 * выглядит для NAT НОВЫМ соединением, чей порт занят потоком клиента, и порт
 * переписывается. Собрали 88.87.93.11:61081 — на провод ушло
 * 88.87.93.11:54212, сервер ответил сбросом. То же и с
 * `-j MASQUERADE` по метке: отдельная трансляция, другой порт (клиент 57668,
 * приманки 55732). Для коробки это два разных потока, и смысл воздействия
 * пропадает целиком.
 *
 * ОТКУДА БЕРЁТСЯ. Из `/proc/net/nf_conntrack`: у записи есть прямой кортеж
 * (каким пакет пришёл) и обратный (каким сервер отвечает). Адрес и порт
 * назначения ОБРАТНОГО кортежа — это ровно то, чем нас видит сервер.
 *
 * ЦЕНА. Файл читается один раз на поток, на его первом приветствии, и ответ
 * запоминается в d2k_flow. Разбор построчный, без выделений; длина файла на
 * живом роутере — сотни строк (замер: 323 при обычной нагрузке).
 *
 * ЧЕГО ЗДЕСЬ НЕТ. IPv6 (весь датапат сегодня IPv4, см. d2k_session.h) и
 * libnetfilter_conntrack: это отдельная зависимость ради одной справки,
 * которую procfs отдаёт текстом.
 */
#ifndef D2K_NAT_H
#define D2K_NAT_H

#include <stddef.h>
#include <stdint.h>

/* Путь к таблице соединений. Параметром — ради теста: подменить файл проще и
   честнее, чем подделывать ядро. */
#define D2K_NAT_PROC "/proc/net/nf_conntrack"

/* Ищет трансляцию для потока (proto, src:sport -> dst:dport), заданного в
 * СЕТЕВОМ порядке байт, как он лежит в пакете.
 *
 * 0 — трансляция найдена: out_src/out_sport — адрес и порт, которыми поток
 * виден снаружи (они же равны исходным, если NAT к потоку не применялся).
 * 1 — таблицы соединений в системе нет вовсе: нет conntrack — нет и NAT,
 * адрес в пакете и есть настоящий.
 * -1 — таблица есть, а записи нет: про ЭТОТ поток сказать нечего, и
 * выдумывать нельзя. Так бывает при включённом nf_conntrack_fastnat —
 * ускоритель ведёт поток мимо conntrack.
 *
 * path — файл таблицы (D2K_NAT_PROC в продукте). */
int d2k_nat_outside(const char *path, uint8_t proto,
                    uint32_t src_ip, uint16_t src_port,
                    uint32_t dst_ip, uint16_t dst_port,
                    uint32_t *out_src, uint16_t *out_sport);

#endif /* D2K_NAT_H */
