/* d2k_wire.h — сборка пакета на провод.
 *
 * Берёт посылку, которую породил исполнитель, и превращает её в настоящий
 * пакет: заголовки от исходного соединения, свои номера последовательности
 * (для TCP) и своя порча. Два сборщика на два транспорта — d2k_wire_build для
 * IPv4/TCP (wire.c) и d2k_wire_build_udp для IPv4/UDP (wire_udp.c) — потому
 * что у UDP нет ни последовательности, ни окна, ни опций, и общий код под
 * оба заголовка получился бы менее понятным, чем два похожих.
 *
 * Порча — не украшение, а несущая часть приёма: сервер обязан выбросить
 * фальшивку, коробка обязана её взять. Испорченная контрольная сумма, малый
 * TTL и метка времени со сдвигом назад делают ровно это для TCP, каждая
 * по-своему; для UDP из них применим только TTL — см. комментарий у
 * d2k_wire_build_udp.
 *
 * Модуль ничего не знает ни о планах, ни о протоколах прикладного уровня. Он
 * знает только про заголовки — это единственное место в датапате, где
 * считаются контрольные суммы.
 */
#ifndef D2K_WIRE_H
#define D2K_WIRE_H

#include <stddef.h>
#include <stdint.h>

#include "d2k_plan.h"

/* Шаблон соединения: то, что берётся из исходного пакета и не меняется от
 * посылки к посылке. Адреса и порты в сетевом порядке байт — ровно так, как
 * они лежат в заголовке. */
typedef struct {
    uint32_t src_ip;   /* сетевой порядок */
    uint32_t dst_ip;
    uint16_t src_port; /* сетевой порядок */
    uint16_t dst_port;
    uint32_t ack;      /* хостовый порядок */
    uint16_t window;   /* хостовый порядок */
    uint8_t  ttl;      /* TTL исходного пакета: от него отсчитываем свой */
    uint16_t ip_id;    /* идентификатор исходного пакета */
} d2k_conn;

/* Собирает пакет в out. Возвращает длину или 0, если не поместилось.
 *
 * Ответственность за длину на вызывающем: датапат не выделяет память на
 * пакетном пути. */
size_t d2k_wire_build(const d2k_conn *c, const d2k_emit *e,
                      uint8_t *out, size_t cap);

/* Проверяет контрольную сумму TCP собранного пакета. Нужна тестам и диагностике:
 * «сумма испорчена намеренно» и «сумма испорчена по ошибке» обязаны быть
 * различимы, иначе порчу нельзя отладить. */
int d2k_wire_tcp_checksum_ok(const uint8_t *pkt, size_t len);

/* Собирает UDP-дейтаграмму в out. Возвращает длину или 0, если не поместилось
 * ИЛИ если посылку нельзя честно исполнить для этого транспорта.
 *
 * Что из порчи применимо к дейтаграмме, а что — отказ (список, а не только
 * проза, чтобы не приходилось его выводить):
 *   применимо:  e->ttl, D2K_POISON_IPID_ZERO — оба поля лежат в IP и общие
 *               с TCP;
 *   отказ (0):  e->pre_len != 0, e->seq_shift != 0, D2K_POISON_TCPTS_BACK,
 *               D2K_POISON_BADSUM — первые два (приставка и сдвиг) — один и
 *               тот же класс, манипуляция номером последовательности TCP,
 *               только с копией байт впереди либо напрямую; все четыре
 *               завязаны на то, чего у UDP нет вовсе (номера
 *               последовательности, опции TCP) либо на возможность, которой
 *               эта сборка сознательно не реализует (см. ниже).
 * Собрать посылку молча, отбросив непонятный бит, — значит применить план,
 * отличный от запрошенного, и не сказать об этом: молча подменять
 * запрошенное на похожее здесь запрещено.
 *
 * Контрольная сумма считается всегда, безусловно, хотя IPv4 формально
 * разрешает записать в неё ноль (раздел «Fields» RFC 768: «An all zero
 * transmitted checksum value means that the transmitter generated no
 * checksum» — «не считалась»): коробка на пути может отбрасывать дейтаграммы
 * с нулевой или неверной суммой, и тогда фальшивка не дойдёт даже до неё.
 *
 * D2K_POISON_BADSUM для UDP не реализован НЕ по той же причине — это была бы
 * та же неизмеренная догадка про чужую коробку, только в другую сторону.
 * Настоящая причина измеримая: фальшивку в плане уже топит TTL (значение
 * приходит РАЗВЁРТКОЙ плана — см. emit_fake в plan_apply.c, — а не
 * вычисляется здесь из входящего пакета), и эта способность уже измерена.
 * Второй механизм для той же цели сейчас был бы кодом впереди замера; если
 * замер когда-нибудь покажет несостоятельность TTL-фальшивок на каком-то
 * пути, порченая сумма станет кандидатом вместе с этим замером.
 *
 * Ответственность за длину на вызывающем, как и у d2k_wire_build: датапат не
 * выделяет память на пакетном пути. */
size_t d2k_wire_build_udp(const d2k_conn *c, const d2k_emit *e,
                          uint8_t *out, size_t cap);

#endif /* D2K_WIRE_H */
