/* d2k_sched.h — отложенная отправка.
 *
 * План умеет назначать пакетам относительное расписание: «копию сейчас, вторую
 * через 78 мс». Спать эти 78 мс в цикле очереди нельзя — встанет весь трафик
 * роутера, а не один поток. Поэтому отложенные пакеты кладутся сюда, а цикл
 * досыпает ровно до ближайшего срока и разгребает созревшее.
 *
 * Память выделяется один раз при создании. На пакетном пути выделений нет:
 * §5.2 требует пределов, а растущая очередь отправки — это не предел.
 * Переполнение ОТКАЗЫВАЕТ и считается; молчаливое вытеснение выглядело бы как
 * «план исполнился наполовину сам собой», и найти это было бы нечем.
 *
 * Порядок при равных сроках — порядок постановки. Куча сама по себе не
 * устойчива, поэтому сравнение идёт по паре (срок, номер постановки). Без
 * этого две копии с одинаковой задержкой могли бы уйти в обратном порядке, а
 * §2.5 требует, чтобы исполненное совпадало с измеренным.
 *
 * Времена — целые наносекунды. Плавающей арифметики на пакетном пути нет.
 */
#ifndef D2K_SCHED_H
#define D2K_SCHED_H

#include <stddef.h>
#include <stdint.h>

typedef struct d2k_sched d2k_sched;

/* slots — сколько пакетов можно держать одновременно,
 * slot_size — предельный размер одного пакета. */
d2k_sched *d2k_sched_new(size_t slots, size_t slot_size);
void       d2k_sched_free(d2k_sched *s);

/*  0 — принято.
 * -1 — очередь полна.
 * -2 — пакет длиннее слота.
 * Оба отказа считаются: см. d2k_sched_refusals. */
int d2k_sched_push(d2k_sched *s, uint64_t due_ns, const uint8_t *data, size_t len);

/* Забирает один созревший пакет, копируя его в буфер вызывающего.
 * 1 — забрали, 0 — созревших нет либо буфер мал (тогда пакет остаётся). */
int d2k_sched_pop_due(d2k_sched *s, uint64_t now_ns,
                      uint8_t *out, size_t outcap, size_t *len);

/* Срок ближайшего пакета; 0 — очередь пуста. */
uint64_t d2k_sched_next_ns(const d2k_sched *s);

size_t   d2k_sched_count(const d2k_sched *s);
uint64_t d2k_sched_refusals(const d2k_sched *s);

#endif /* D2K_SCHED_H */
