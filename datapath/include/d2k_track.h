/* d2k_track.h — учёт потоков.
 *
 * Таблица фиксированного размера, выделяется один раз. На пакетном пути нет ни
 * одного выделения памяти: §5.2 документа требует пределов на число потоков, а
 * растущая таблица на коробке со 128 МБ — это не предел, а отложенная смерть.
 *
 * При переполнении таблица ОТКАЗЫВАЕТ, а не вытесняет случайного соседа и не
 * растёт. Отказ виден снаружи и лечится настройкой; тихое вытеснение выглядело
 * бы как «поток перестал отслеживаться сам собой», и найти это было бы нечем.
 *
 * Времена — целые наносекунды. Плавающей арифметики на пакетном пути нет:
 * MIPS-коробки идут без сопроцессора.
 */
#ifndef D2K_TRACK_H
#define D2K_TRACK_H

#include <stddef.h>
#include <stdint.h>
#include <string.h>

#include "d2k_plan.h"
#include "d2k_quic.h"

/* Ключ потока. Адреса и порты в сетевом порядке — ровно как в заголовке, без
 * перекладываний: перекладывание уже стоило одной ошибки в контрольных суммах.
 *
 * Ключ КАНОНИЧЕН: две стороны одного соединения дают один и тот же ключ.
 * Поля названы low/high, а не src/dst, именно поэтому — «источник» у пакета
 * есть, у соединения его нет. Без канонизации ответное направление заводило бы
 * второй поток, и план мог бы примениться к одному соединению дважды.
 *
 * proto — транспорт (6 TCP, 17 UDP, см. d2k_key_make). Без него TCP-поток и
 * QUIC/UDP-поток к одному и тому же адресу с одинаковым портом получили бы
 * ОДИН ключ: у TCP и UDP независимые пространства нумерации портов, и
 * совпадение не запрещено ничем. Это не редкий случай, а обычное поведение
 * браузера: он гоняет QUIC и TCP к одному адресу наперегонки и откатывается
 * на TCP, если QUIC не идёт, — то есть ровно на интересных целях оба потока
 * существуют одновременно. Контроллер держит состояние ПО ЭТОМУ КЛЮЧУ (какой
 * план применён, какие подозрения пришли) — общий ключ означал бы, что два
 * потока разных протоколов делят и перетирают друг другу состояние.
 * proto так же различает и СОБЫТИЯ журнала: у QUIC будут свои плечи плана
 * (задача 6), никак не совпадающие с разрезами TCP, и без proto в ключе одно
 * от другого различить было бы нечем — событие несёт транспорт вместе с
 * ключом, а не отдельным видом события (см. D2K_JRN_HELLO_SNI, d2k_journal.h:
 * заводить отдельные виды под QUIC не нужно ровно по этой причине).
 *
 * ЭТУ СТРУКТУРУ НЕЛЬЗЯ НАКЛАДЫВАТЬ НА БУФЕР ПРОВОДА. Пять полей — 4+4+2+2+1 —
 * это 13 значащих байт, но выравнивание в памяти делает sizeof(d2k_key) равным
 * 16: три байта дыры, которые d2k_key_make зануляет для КОНКРЕТНОГО экземпляра
 * (memset перед заполнением полей), но которые memcpy(тело, &ключ, sizeof
 * ключ) отправил бы на провод как есть при любом другом пути построения — то
 * есть НЕ гарантированно, просто «сегодня работает». Поэтому ctlsrv.c кладёт
 * ключ в тело события ПОЛЯМИ (см. put_key в ctlsrv.c), а не наложением
 * структуры на буфер — та же причина, по которой это запрещено всему
 * остальному датапату (wire.c, wire_udp.c): на MIPS/ARM выравнивание не
 * гарантировано, а здесь вдобавок жди дыру с непредсказуемым содержимым.
 * Ширина ключа на проводе — 13 байт, именованная константа D2K_KEY_WIRE_LEN
 * (d2k_ctlsrv.h) на C-стороне и keyLen на Go-стороне (internal/control/
 * control.go) — а не буквальное число россыпью по обоим файлам. */
#include "d2k_addr.h"

typedef struct {
    uint32_t low_ip;
    uint32_t high_ip;
    uint16_t low_port;
    uint16_t high_port;
    uint8_t  proto;
    /* Zero retains the existing IPv4 key representation during migration.
       IPv6 keys use family=6 and all 16 bytes; legacy IP fields stay zero. */
    uint8_t family;
    uint8_t low_ip6[16], high_ip6[16];
} d2k_key;

static inline int d2k_key_equal(const d2k_key *a, const d2k_key *b) {
    if (a->proto != b->proto || a->low_port != b->low_port || a->high_port != b->high_port ||
        (a->family == 6) != (b->family == 6)) { return 0; }
    if (a->family == 6) {
        return !memcmp(a->low_ip6, b->low_ip6, 16) && !memcmp(a->high_ip6, b->high_ip6, 16);
    }
    return a->low_ip == b->low_ip && a->high_ip == b->high_ip;
}

int d2k_key_make_addr(d2k_key *k, uint8_t proto,
                     const d2k_addr *src, const d2k_addr *dst,
                     const uint8_t *sport_be, const uint8_t *dport_be);

/* Строит канонический ключ из пары «источник — назначение» и транспорта.
 *
 * Возвращает 1, если источник оказался НИЗКИМ концом пары, иначе 0. Этого
 * возврата вместе с d2k_flow.init_low хватает, чтобы определить направление
 * пакета, не храня адреса второй раз.
 *
 * Порядок задаётся сравнением шести байт адреса и порта в сетевом порядке:
 * оно одинаково на любой арке, в отличие от сравнения чисел. Транспорт в
 * сравнении порядка не участвует — только в самом ключе: у одной пары
 * адрес+порт порядок low/high не должен зависеть от того, TCP это или UDP. */
int d2k_key_make(d2k_key *k, uint8_t proto, const uint8_t *src_ip4, const uint8_t *dst_ip4,
                 const uint8_t *src_port_be, const uint8_t *dst_port_be);

struct d2k_flow {
    d2k_key  key;
    int      in_use;
    /* Controller-owned active probes may use exact trial plans, but they are
       not evidence for new user-traffic discovery. */
    int      controller_probe;

    uint64_t first_ns;
    uint64_t last_ns;

    /* Направления названы «прямое» и «обратное», а не «клиент» и «сервер».
     * Прямое — то, откуда пришёл ПЕРВЫЙ увиденный пакет. Поток можно
     * подхватить посреди обмена, и тогда кто кого позвал, неизвестно; врать об
     * этом в имени поля нельзя. */
    int      init_low;      /* поток начала низкая сторона пары */
    int      dir_known;     /* сторону определили по флагам, а не по порядку */
    uint32_t fwd_pkts;
    uint32_t rev_pkts;
    uint64_t fwd_bytes;
    uint64_t rev_bytes;

    int saw_syn;
    int saw_synack;

    /* Времена, по которым видно, что ответа НЕ БУДЕТ.
     *
     * rtt_ns снимается с самого потока: от SYN до SYN-ACK. Ориентир взят из
     * измерения, а не из константы, — на медленной линии константа объявила бы
     * молчанием обычную задержку. Ноль означает «не мерили»: поток могли
     * подхватить посреди обмена. */
    uint64_t syn_ns;
    uint64_t rtt_ns;
    uint64_t hello_ns;
    int      silence_told;   /* о молчании уже сообщили — не дублировать */

    /* Узнанное о протоколе. Заполняется наблюдением и не зависит от того, есть
     * ли план: §9 этапа C требует видеть транзитные соединения ДО того, как
     * появится хоть какое-то воздействие. Имя здесь не хранится намеренно —
     * 2048 потоков по 256 байт имени это полмегабайта, а датапату имя для
     * решений не нужно. Имя живёт в журнале, у которого свой предел. */
    int      saw_hello;
    uint8_t  client_shape;
    /* КЛИЕНТСКИЙ INITIAL ВИДЕН, А ИМЯ ИЗ НЕГО НЕ ПРОЧИТАНО.
     *
     * Отдельно от saw_hello, и различие несущее: saw_hello значит «приветствие
     * разобрано, имя известно», и на нём стоят и счётчики, и журнал, и снимок.
     * Настоящий клиент (поле 19.09.2026) разбрасывает ClientHello по многим
     * мелким кадрам CRYPTO поперёк двух датаграмм — локальная stateful-сборка
     * ждёт непрерывный префикс и не объявляет половину приветствием.
     *
     * Но МОЛЧАНИЕ по такому потоку — наблюдение не хуже прочих: клиент шлёт и
     * повторяет, а оттуда не приходит ничего. Без этого признака развёртка
     * молчания (sweep_udp_one) пропускала такие потоки целиком, и контроллер
     * не узнавал о беде вовсе. */
    int      saw_initial;
    int      had_sni;
    /* Snapshot delivered or rejected; completed flows consume no assembly
       slot and retransmissions cannot publish another snapshot. */
    int      hello_capture_done;
    uint32_t syn_seq;
    int      stream_attempted;
    /* Составное приветствие этого потока уже отпущено без сборки, и событие
       об этом записано. Отпускается несколько пакетов, событие — одно. */
    int      noted_unassembled;

    /* Признаки для обнаружения подозрений. Это НАБЛЮДЕНИЯ, а не диагноз:
     * §2.4 говорит, что таймаут не доказывает блокировку, а промах не
     * доказывает свойство механизма. Поля называют то, что видно. */
    uint32_t hello_seq;        /* seq приветствия — чтобы считать повторы */
    uint32_t hello_repeats;    /* приветствие послано снова */
    /* Подтверждение, с которым ушло приветствие TCP. Клиент, получивший
       данные сервера, двигает его вперёд; если при этом с обратной стороны
       в очередь не пришло ничего, ответ увёл ускоритель мимо netfilter
       (d2k_session_reply_hidden). hello_ack_valid — у приветствия был ACK. */
    uint32_t hello_ack;
    uint8_t  hello_ack_valid;
    uint8_t  reply_hidden_told;
    uint32_t rev_after_hello;  /* пакетов с обратной стороны после приветствия */
    /* Последнее клиентское/серверное событие после приветствия. Нужны для
       UDP-сценария «первый Initial пропустили, повторы режутся»: сам факт
       одного ответа не доказывает, что последующий PTO тоже получил ответ. */
    uint64_t last_fwd_after_hello_ns;
    uint64_t last_rev_after_hello_ns;
    /* Пакетов НАШЕЙ стороны после приветствия. Для UDP это и есть половина
     * критерия «шлём, а молчат»: у QUIC нет ни рукопожатия транспорта, ни
     * номеров последовательности, и единственное, чем клиент показывает, что
     * ответа он всё ещё ждёт, — повторная посылка по таймеру PTO (RFC 9002
     * §6.2, первый повтор около секунды). Приветствие без единого повтора —
     * это не «сервер молчит», а «клиент больше не спрашивал»; выдать одно за
     * другое значит назвать блокировкой закрытую вкладку.
     * Ветка TCP это поле не трогает: там ту же мысль несёт hello_repeats,
     * снятый с номеров последовательности. */
    uint32_t fwd_after_hello;

    /* КАКИМ АДРЕСОМ НАС ВИДИТ СЕРВЕР (см. d2k_nat.h).
     *
     * Для транзитного потока в очереди лежит ещё ЛОКАЛЬНЫЙ адрес клиента:
     * очередь висит на mangle POSTROUTING, а SNAT делается позже. Посылки
     * плана, собранные с этим адресом, уходят в никуда — замерено на живом
     * роутере 13.09.2026. Трансляция берётся один раз на поток и хранится
     * здесь: читать таблицу соединений на каждый пакет незачем.
     *
     * nat_state: 0 — не спрашивали, 1 — знаем, 2 — таблица есть, а записи в
     * ней нет (воздействовать нельзя: адрес выдумать не из чего), 3 —
     * таблицы соединений в системе нет вовсе, а значит нет и NAT. */
    uint32_t nat_src;
    uint16_t nat_sport;
    uint8_t  nat_state;
    /* Байты НАГРУЗКИ с обратной стороны после приветствия и тип первой
     * TLS-записи в них. Это и есть свидетельство обмена — единственный
     * критерий истины продукта (§2.3). Тип записи хранится, а не толкуется:
     * 0x16 рукопожатие и 0x15 предупреждение — разные вещи, и решать, что из
     * них успех, датапату не положено (§4.2: уровень 2 не выдавать за 4). */
    uint32_t rev_payload_after_hello;
    uint8_t  rev_first_type;
    /* Набор типов TLS-записей, встреченных В НАЧАЛЕ пакетов с обратной
     * стороны. Битами: 20 ChangeCipherSpec, 21 Alert, 22 Handshake,
     * 23 ApplicationData.
     *
     * Одного «первого типа» мало: он всегда 22, потому что первым сервер шлёт
     * ServerHello. А §4.2 прямо говорит, что проверки первых байтов
     * ServerHello НЕДОСТАТОЧНО — при блокировках после начала ответа нужен
     * проверяемый обмен данными. Прикладные данные (23) и есть тот признак,
     * по которому уровень 3 отличается от уровня 2.
     *
     * Начало пакета — не начало записи: запись может продолжаться с прошлого
     * пакета. Поэтому набор говорит «такой тип ВСТРЕЧАЛСЯ», а не «записей
     * ровно столько-то». Толковать его — дело контроллера. */
    uint8_t  rev_types;
    /* Сервер прислал ServerHello в ответ на НАШЕ приветствие. Отдельным
       полем, а не битом в rev_types: там «такой тип записи встречался», а
       здесь «запись разобрана и это ответ сервера» — разные утверждения, и
       складывать их в одно поле значит однажды принять алерт за ответ. */
    uint8_t  rev_server_hello;
    uint8_t  rev_tls_reply; /* parsed ServerHello or complete TLS data record;
                              not proof of application success */
    int      exchange_told;    /* об обмене уже сообщили */
    uint8_t  voice_ssrc[4];    /* SSRC из клиентского IP Discovery запроса */
    uint8_t  voice_ssrc_valid;
    uint8_t  voice_proof_told;
    uint8_t  stun_txid[12];
    uint8_t  stun_txid_valid;
    uint8_t  stun_proof_told;
    /* Состояние Initial/CRYPTO этого UDP-потока. Нулевой контекст не
       означает успеха: пока префикс ClientHello не собран, пакет проходит
       без имени и без применения плана. */
    d2k_quic_assembly quic_assembly;
    int      appdata_told;     /* и о прикладных данных тоже */
    int      saw_rev_rst;      /* сброс пришёл с обратной стороны */
    int      suspected;        /* подозрение уже отмечено — не дублировать */

    /* Отпечаток того, кто отвечает по этому соединению. Снимается с ПЕРВОГО
     * обратного пакета — обычно SYN-ACK. Служит ориентиром для защиты
     * D2K_GUARD_RST_ALIEN: сброс, пришедший с другим TTL, послан не тем, кто
     * до этого отвечал. Ориентир взят из самого потока и потому не может с
     * ним разойтись — в отличие от константы. */
    int      rev_profiled;
    uint8_t  rev_ttl;
    uint8_t  rev_tos;

    /* Защита, назначенная плану этого потока. */
    uint8_t  guards;
    uint32_t rst_dropped;

    /* План уже применён к этому потоку. Второй раз применять нельзя: план
     * описывает обработку начала соединения, а не каждого пакета. */
    int plan_done;
    /* Первая нагрузка клиента уже проверена на запрос HTTP (задача 51, шаг
       4): разбор — один раз на поток, только с начала потока. */
    uint8_t http_checked;
    /* KEEP-ALIVE (поле 04.10.2026: коробка смотрит каждый запрос
       соединения). http_flow — поток начался запросом HTTP на порт 80;
       http_conn — граница следующего запроса известна: он начнётся с номера
       http_next. Узнанный там запрос получает план своего имени, как первый.
       Любое сомнение (не с начала сегмента, пропуск, неизвестный конец)
       снимает http_conn до конца потока. */
    uint8_t http_flow;
    uint8_t http_conn;
    uint32_t http_next;
    uint32_t pending_fin_seq;
    uint8_t pending_fin;
    /* Когда пришёл первый FIN с этим концом: запись после него живёт окно
       повтора FIN (session.c, fin_retry_window), а не 120 с молчания. */
    uint64_t pending_fin_ns;
    /* QUIC ПОСЛЕ РУКОПОЖАТИЯ (задача 50, раунд 2): счётчики conntrack, которые
       видит d2k_session_sweep. quic_rtt_ns — от первого Initial до первого
       ответа; ct_reply_ns — когда обратный счётчик последний раз сдвинулся,
       ct_orig_mark — прямой счётчик в тот момент. */
    uint64_t quic_rtt_ns;
    uint64_t ct_reply;
    uint64_t ct_reply_ns;
    uint64_t ct_orig_mark;
    uint8_t  ct_known;
    uint8_t voice_requests; /* real queued Discovery/STUN requests, not generic media */
    uint8_t voice_media_dirs; /* RTP-shaped packets seen, 1 client / 2 server */
    uint8_t voice_media_told, voice_stable_told;
    uint64_t voice_stable_since_ns;
    uint64_t voice_ct_orig; /* latest original count, reset/activity detection */
    /* TCP ВСТАЛ НА БЮДЖЕТЕ (задача 56): пакеты С ДАННЫМИ, которые видела
       очередь (по сторонам), и все пакеты сервера ЭТОГО соединения в очереди
       — чтобы из обратного счётчика conntrack вычесть увиденное (rev_pkts
       копится через границу соединений). tcp_watch_off — поток вышел за
       полосу или закрывается: больше не спрашивать. */
    uint32_t fwd_data_pkts;
    uint32_t rev_data_pkts;
    uint32_t rev_pkts_conn;
    uint8_t  tcp_watch_off;
    /* Имени поставлен quicdeny: датаграммы клиента этого потока снимаются,
       и его молчание — наше, не коробки. */
    uint8_t  quic_deny;

    /* Внешняя транзакция удержания split QUIC: классифицировать поток можно,
       применять план к текущей датаграмме нельзя до replay первого оригинала. */
    uint8_t udp_hold_active;
    /* Следующая клиентская датаграмма — повтор первого Initial, который
       удерживался до сборки ClientHello. Она не должна терять исключение
       первого пакета conntrack из-за повторного учёта одного оригинала. */
    uint8_t udp_hold_replay_first;
    /* Клиент с меткой маршрутизации: поток идёт ядром (задача 47). */
    uint8_t routed;

    /* Поток испорчен отменой посреди нагрузки. Дальше с ним работать нельзя,
     * и это факт для контроллера, а не повод датапату что-то решать. */
    int damaged;
    /* Оригинал ЭТОЙ попытки забрал план: вердикт ядру — DROP, и байты клиента
       воспроизводим мы сами. Нужно веткам отказа, где d2k_result уже
       недоступен (созревшая отложенная посылка, ошибка вердикта): по нему
       решается, есть ли ещё чистый выход. */
    uint8_t orig_taken;
    /* О повреждении контроллеру уже сообщили. Испорченный поток продолжает
       слать пакеты, и событие на каждом забило бы единственное управляющее
       соединение: события лосси по контракту (d2k_ctl.h). */
    uint8_t damaged_told;

    /* Сколько посылок применённого плана ещё НЕ покинули машину, и был ли
     * отказ хотя бы у одной. Счёт живёт на потоке, а не рядом с очередью
     * отправки. execution_id отличает новую попытку от забытого потока с
     * тем же ключом; очередь хранит и проверяет это поколение.
     *
     * Байты, а не size_t: посылок не может быть больше вместимости
     * d2k_result.out[] (16) плюс один вердикт оригинала, всего 17.
     *
     * sends_failed взведён — «доисполнен» по этому потоку не объявляется
     * больше никогда: поздняя удача остатка не отменяет того, что план ушёл
     * на провод не целиком. */
    uint8_t sends_left;
    uint8_t sends_failed;
    /* Сколько посылок этой попытки уже покинуло машину (вердикт тоже). */
    uint8_t sends_done;
    /* UDP: попытка сорвалась, а оригинал так и не ушёл — ядро сняло его как
       дубль записи, созданной нашими фальшивками, либо наша посылка с ним не
       ушла после DROP. Датаграмма атомарна, и клиент сам повторит Initial
       целиком: этот повтор получает план (задача 42). Сбрасывается новой
       попыткой. */
    uint8_t udp_replan;
    uint64_t execution_id; /* distinguishes reuse of the same 5-tuple */
    uint8_t execution_plan_id[16];
    uint8_t execution_trial_id[16]; /* nonzero only for ephemeral address probe */
};
/* Псевдоним объявлен в d2k_plan.h опережающе — повторять его здесь нельзя:
 * C99 запрещает повторный typedef, и это ловится только сборкой обоих
 * заголовков вместе. */

typedef struct d2k_table d2k_table;

/* capacity округляется вверх до степени двойки. */
d2k_table *d2k_track_new(size_t capacity);
void       d2k_track_free(d2k_table *t);

/* Находит поток или заводит новый. NULL означает, что таблица полна — это
 * нормальный исход, а не ошибка: вызывающий пропускает пакет без обработки. */
d2k_flow *d2k_track_get(d2k_table *t, const d2k_key *k, uint64_t now_ns);

/* Только поиск, без заведения. */
d2k_flow *d2k_track_find(d2k_table *t, const d2k_key *k);

/* НОВОЕ СОЕДИНЕНИЕ НА СТАРОЙ ПЯТЁРКЕ.
 *
 * Запись потока живёт дольше соединения: эфемерный порт возвращается в оборот,
 * и следующее соединение попадает в ту же ячейку со всем, что помнит прежнее —
 * началом потока, отметкой «приветствие было», закрытой попыткой удержания,
 * трансляцией NAT. Для нового соединения всё это ложь, и молчаливая: якорь
 * указывает на чужой ISN, удержание закрыто навсегда, посылки собираются с
 * адресом прошлой записи conntrack.
 *
 * SYN без ACK и есть граница. Повтор SYN попадает сюда же, и это правильно: к
 * моменту повтора у соединения ещё ничего нет, терять нечего.
 *
 * Сохраняется только то, что принадлежит ЗАПИСИ, а не соединению: ключ,
 * времена жизни ячейки, счётчики наблюдения, сторона пары и учёт посылок,
 * который может пережить смену соединения (execution_id для того и заведён).
 * Остальное обнуляется целиком — так новое поле не забудут добавить в список
 * сброса. */
void d2k_track_new_connection(d2k_flow *f);

/* Убирает поток из таблицы. Закрытие соединения — обычное дело (RST, FIN), и
 * ждать истечения по молчанию для него незачем: ячейка нужна другим. */
void d2k_track_remove(d2k_table *t, const d2k_key *k);

/* Освобождает потоки, молчавшие дольше idle_ns. Возвращает сколько освободил.
 *
 * on_expire, если задан, зовётся ДО освобождения каждой ячейки. Это
 * единственный момент, когда можно посмотреть на поток целиком: «приветствие
 * было, ответа не пришло» — факт, который становится известен только в конце.
 * Обратный вызов на пакетном пути не стоит: уборка идёт раз в секунду. */
size_t d2k_track_expire(d2k_table *t, uint64_t now_ns, uint64_t idle_ns,
                        void (*on_expire)(void *ctx, const d2k_flow *f),
                        void *ctx);

/* Освобождает потоки, для которых gone() вернул не ноль. Возвращает сколько
   освободил. Для записей со своим сроком, короче общего молчания. */
size_t d2k_track_remove_if(d2k_table *t, int (*gone)(void *ctx, const d2k_flow *f),
                           void *ctx);

/* Обойти живые потоки, ничего не удаляя. Нужно, чтобы заметить молчание НЕ
   дожидаясь забвения потока: ждать 120 секунд ради вывода «ответа не было»
   значит держать человека перед пустой страницей всё это время. */
void d2k_track_walk(d2k_table *t, void (*fn)(void *ctx, d2k_flow *f), void *ctx);

size_t d2k_track_count(const d2k_table *t);
size_t d2k_track_capacity(const d2k_table *t);

/* Сколько раз таблица отказала из-за переполнения. Счётчик нужен панели: без
 * него «мы не видим поток» и «мы его не взяли» неразличимы. */
uint64_t d2k_track_refusals(const d2k_table *t);

#endif /* D2K_TRACK_H */
