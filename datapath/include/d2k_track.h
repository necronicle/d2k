/* d2k_track.h — учёт потоков.
 *
 * Таблица фиксированного размера, выделяется один раз. На пакетном пути нет ни
 * одного выделения памяти: §5.2 документа требует пределов на число потоков, а
 * растущая таблица на коробке со 128 МБ — это не предел, а отложенная смерть.
 *
 * При переполнении таблица ОТКАЗЫВАЕТ, а не вытесняет случайного соседа и не
 * растёт. Отказ виден снаружи и лечится настройкой; тихое вытеснение выглядело
 * бы как «поток перестал отслеживаться сам собой», и найти это было бы нечем.
 *
 * Времена — целые наносекунды. Плавающей арифметики на пакетном пути нет:
 * MIPS-коробки идут без сопроцессора.
 */
#ifndef D2K_TRACK_H
#define D2K_TRACK_H

#include <stddef.h>
#include <stdint.h>

#include "d2k_plan.h"

/* Ключ потока. Адреса и порты в сетевом порядке — ровно как в заголовке, без
 * перекладываний: перекладывание уже стоило одной ошибки в контрольных суммах.
 *
 * Ключ КАНОНИЧЕН: две стороны одного соединения дают один и тот же ключ.
 * Поля названы low/high, а не src/dst, именно поэтому — «источник» у пакета
 * есть, у соединения его нет. Без канонизации ответное направление заводило бы
 * второй поток, и план мог бы примениться к одному соединению дважды. */
typedef struct {
    uint32_t low_ip;
    uint32_t high_ip;
    uint16_t low_port;
    uint16_t high_port;
} d2k_key;

/* Строит канонический ключ из пары «источник — назначение».
 *
 * Возвращает 1, если источник оказался НИЗКИМ концом пары, иначе 0. Этого
 * возврата вместе с d2k_flow.init_low хватает, чтобы определить направление
 * пакета, не храня адреса второй раз.
 *
 * Порядок задаётся сравнением шести байт адреса и порта в сетевом порядке:
 * оно одинаково на любой арке, в отличие от сравнения чисел. */
int d2k_key_make(d2k_key *k, const uint8_t *src_ip4, const uint8_t *dst_ip4,
                 const uint8_t *src_port_be, const uint8_t *dst_port_be);

struct d2k_flow {
    d2k_key  key;
    int      in_use;

    uint64_t first_ns;
    uint64_t last_ns;

    /* Направления названы «прямое» и «обратное», а не «клиент» и «сервер».
     * Прямое — то, откуда пришёл ПЕРВЫЙ увиденный пакет. Поток можно
     * подхватить посреди обмена, и тогда кто кого позвал, неизвестно; врать об
     * этом в имени поля нельзя. */
    int      init_low;      /* поток начала низкая сторона пары */
    uint32_t fwd_pkts;
    uint32_t rev_pkts;
    uint64_t fwd_bytes;
    uint64_t rev_bytes;

    int saw_syn;
    int saw_synack;

    /* Узнанное о протоколе. Заполняется наблюдением и не зависит от того, есть
     * ли план: §9 этапа C требует видеть транзитные соединения ДО того, как
     * появится хоть какое-то воздействие. Имя здесь не хранится намеренно —
     * 2048 потоков по 256 байт имени это полмегабайта, а датапату имя для
     * решений не нужно. Имя живёт в журнале, у которого свой предел. */
    int      saw_hello;
    int      had_sni;

    /* Признаки для обнаружения подозрений. Это НАБЛЮДЕНИЯ, а не диагноз:
     * §2.4 говорит, что таймаут не доказывает блокировку, а промах не
     * доказывает свойство механизма. Поля называют то, что видно. */
    uint32_t hello_seq;        /* seq приветствия — чтобы считать повторы */
    uint32_t hello_repeats;    /* приветствие послано снова */
    uint32_t rev_after_hello;  /* пакетов с обратной стороны после приветствия */
    int      saw_rev_rst;      /* сброс пришёл с обратной стороны */
    int      suspected;        /* подозрение уже отмечено — не дублировать */

    /* План уже применён к этому потоку. Второй раз применять нельзя: план
     * описывает обработку начала соединения, а не каждого пакета. */
    int plan_done;

    /* Поток испорчен отменой посреди нагрузки. Дальше с ним работать нельзя,
     * и это факт для контроллера, а не повод датапату что-то решать. */
    int damaged;
};
/* Псевдоним объявлен в d2k_plan.h опережающе — повторять его здесь нельзя:
 * C99 запрещает повторный typedef, и это ловится только сборкой обоих
 * заголовков вместе. */

typedef struct d2k_table d2k_table;

/* capacity округляется вверх до степени двойки. */
d2k_table *d2k_track_new(size_t capacity);
void       d2k_track_free(d2k_table *t);

/* Находит поток или заводит новый. NULL означает, что таблица полна — это
 * нормальный исход, а не ошибка: вызывающий пропускает пакет без обработки. */
d2k_flow *d2k_track_get(d2k_table *t, const d2k_key *k, uint64_t now_ns);

/* Только поиск, без заведения. */
d2k_flow *d2k_track_find(d2k_table *t, const d2k_key *k);

/* Убирает поток из таблицы. Закрытие соединения — обычное дело (RST, FIN), и
 * ждать истечения по молчанию для него незачем: ячейка нужна другим. */
void d2k_track_remove(d2k_table *t, const d2k_key *k);

/* Освобождает потоки, молчавшие дольше idle_ns. Возвращает сколько освободил.
 *
 * on_expire, если задан, зовётся ДО освобождения каждой ячейки. Это
 * единственный момент, когда можно посмотреть на поток целиком: «приветствие
 * было, ответа не пришло» — факт, который становится известен только в конце.
 * Обратный вызов на пакетном пути не стоит: уборка идёт раз в секунду. */
size_t d2k_track_expire(d2k_table *t, uint64_t now_ns, uint64_t idle_ns,
                        void (*on_expire)(void *ctx, const d2k_flow *f),
                        void *ctx);

size_t d2k_track_count(const d2k_table *t);
size_t d2k_track_capacity(const d2k_table *t);

/* Сколько раз таблица отказала из-за переполнения. Счётчик нужен панели: без
 * него «мы не видим поток» и «мы его не взяли» неразличимы. */
uint64_t d2k_track_refusals(const d2k_table *t);

#endif /* D2K_TRACK_H */
