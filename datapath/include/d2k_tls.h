/* d2k_tls.h — распознавание TLS и вычисление якорей.
 *
 * Модуль отвечает на один вопрос: где в этих байтах лежит то, на что ссылается
 * план. Он НЕ решает, что с пакетом делать, и не знает про планы вовсе —
 * исполнитель протоколов не разбирает, протокольный модуль не исполняет.
 *
 * Главное свойство: всё, чего модуль не может ответить уверенно, он объявляет
 * неизвестным. Уверенный неправильный ответ здесь хуже честного «не знаю»:
 * исполнитель, получив «не знаю», откажется применять план, а получив
 * неправильное смещение — разрежет приветствие не там и испортит соединение,
 * не сообщив об этом никому.
 *
 * Отсутствие имени — НЕ ошибка. Так выглядят ECH, часть клиентов и любое
 * соединение к адресу без имени. Это нормальное состояние модели (§5.3).
 */
#ifndef D2K_TLS_H
#define D2K_TLS_H

#include <stddef.h>
#include <stdint.h>

typedef struct {
    /* Похоже ли начало на запись TLS вообще. */
    int is_tls_record;
    /* Тип записи: 0x16 рукопожатие, 0x17 данные приложения и так далее. */
    uint8_t record_type;

    /* Разобрано ли это как ClientHello. */
    int is_client_hello;

    /* Имя из расширения server_name. have_sni == 0 означает «не найдено или
       не разобрано целиком» — и то и другое одинаково запрещает опираться на
       смещение. */
    int    have_sni;
    size_t sni_off;
    size_t sni_len;

    /* Конец первой записи TLS от начала переданных байтов. Вычисляется только
       если запись целиком помещается во вход: иначе якорь указывал бы за
       пределы того, что у нас есть. */
    int    have_record_end;
    size_t record_end;

    /* Середина сообщения ClientHello — якорь, полезный там, где имени нет.
       Вычисляется только для целиком помещающегося рукопожатия. */
    int    have_hello_middle;
    size_t hello_middle;
} d2k_tls_info;

/* Всегда возвращает 0: «это не TLS» и «TLS, но разобрать не удалось» — не
 * ошибки инструмента, а результаты разбора. Отрицательный код оставлен на
 * случай неверных аргументов. */
int d2k_tls_parse(const uint8_t *b, size_t len, d2k_tls_info *out);

#endif /* D2K_TLS_H */
