/* d2k_raw.h — отправка собственных пакетов.
 *
 * Сырой сокет с IP_HDRINCL: заголовок наш, маршрут выбирает ядро. Только
 * Linux, как и d2k_nfq.h.
 *
 * ЧЕГО ЭТОТ СПОСОБ НЕ УМЕЕТ. По raw(7) ядро при IP_HDRINCL переписывает часть
 * полей заголовка независимо от того, что мы положили:
 *
 *     IP Checksum      — всегда;
 *     Total Length     — всегда;
 *     Source Address   — когда ноль;
 *     Packet ID        — КОГДА НОЛЬ.
 *
 * Последнее прямо задевает порчу D2K_POISON_IPID_ZERO: план просит нулевой
 * идентификатор, а на провод уходит выбранный ядром. §2.5 запрещает молча
 * приближать неподдерживаемую операцию другой, поэтому способ отправки
 * ОБЪЯВЛЯЕТ свои пределы, а вызывающий обязан отказаться активировать план,
 * который в них не укладывается. Тихо отправить «почти то же самое» нельзя:
 * измеренное перестало бы соответствовать исполненному.
 *
 * Сумму TCP это не задевает — её считаем мы, и ядро её не трогает. Значит
 * D2K_POISON_BADSUM доезжает до провода как задумано.
 *
 * Снять ограничение можно только уходом на AF_PACKET, то есть сборкой
 * канального заголовка вручную. Это отдельная работа с отдельной проверкой на
 * устройстве, и до неё ограничение живёт объявленным, а не забытым.
 */
#ifndef D2K_RAW_H
#define D2K_RAW_H

#include <stddef.h>
#include <stdint.h>

/* Поля, которыми этот способ отправки не распоряжается. */
#define D2K_RAW_CANT_IPID  (1u << 0)
#define D2K_RAW_CANT_IPSUM (1u << 1)

/* Запасной предел длины посылки, когда MTU прочитать не удалось: 1500 байт,
 * Ethernet по RFC 894. Не «разумное число»: это тот самый предел, который
 * стоит на линии у подавляющего большинства коробок, и из него же выведены
 * все MTU меньше (PPPoE 1492 = 1500 − 8). Число унаследовано, а не выбрано.
 *
 * Запас нужен затем, что отказ прочитать MTU — не повод отправлять вслепую:
 * без объявленного предела вернулась бы ровно та картина, ради которой всё
 * это заведено, — «план применён» одновременно с «sendto: Message too
 * large». */
#define D2K_RAW_MTU_FALLBACK 1500

/* Пол предела длины: минимальный MTU, который обязан нести любой узел IPv4
 * (RFC 791 §3.2 — 576 байт). Ниже опускаться некуда: предел, упавший до
 * бессмысленно малого, отверг бы вообще все планы и молча выключил бы обход.
 * Нужен затем, что предел ОПУСКАЕТСЯ по ответу ядра (EMSGSIZE), а единичный
 * странный ответ не должен решать судьбу всей работы. */
#define D2K_RAW_MTU_FLOOR 576

typedef struct d2k_raw d2k_raw;

/* mark — метка SO_MARK на исходящих пакетах. Ненулевая метка нужна, чтобы
 * собственные пакеты можно было исключить из своей же очереди правилом
 * firewall: §5.5 требует, чтобы зонды не обучали систему повторно, а §10 —
 * чтобы собственный трафик не попадал под собственное преобразование.
 * Ноль означает «не ставить метку» и годится только для лаборатории.
 *
 * ifname — интерфейс, чей MTU берётся ПРЕДЕЛОМ ДЛИНЫ ПОСЫЛКИ (см.
 * d2k_raw_maxlen). NULL означает «взять наименьший MTU среди поднятых
 * интерфейсов, кроме loopback».
 *
 * ЭТО РЕШЕНИЕ С ЦЕНОЙ, а не очевидность. Три пути были:
 *
 *   спросить маршрут до каждой цели НА ПАКЕТНОМ ПУТИ — самый точный, и
 *   отвергнут: датапат полез бы за числом, меняющимся раз в жизни
 *   соединения, на каждую посылку. Но раз на НАПРАВЛЕНИЕ спросить можно и
 *   нужно — см. d2k_raw_route_maxlen ниже;
 *
 *   зашить константу — отвергнут: константа режет длинные формы там, где
 *   они прошли бы, а на линии с 9000 пропускала бы то, что не влезет;
 *
 *   снять MTU интерфейса ОДИН РАЗ при старте — выбрано. Цена: MTU может
 *   смениться под нами (PPPoE переподнялся, поднялся туннель), и тогда
 *   предел разойдётся с настоящим до перезапуска службы. Наименьший из
 *   поднятых — сознательно ЗАНИЖЕННАЯ оценка: ошибка в эту сторону
 *   отвергает форму, которая прошла бы, и это видно в отказе; ошибка в
 *   другую сторону возвращает молчаливый EMSGSIZE. */
d2k_raw *d2k_raw_open(uint32_t mark, const char *ifname, char *err, size_t errcap);
void     d2k_raw_close(d2k_raw *r);

/* Биты D2K_RAW_CANT_*. */
uint32_t d2k_raw_limits(const d2k_raw *r);

/* Предел длины посылки ДЛЯ КОНКРЕТНОГО НАПРАВЛЕНИЯ: меньшее из общего
 * предела (d2k_raw_maxlen) и MTU маршрута к dst.
 *
 * Зачем отдельно от общего. Общий — наименьший MTU среди поднятых
 * интерфейсов, и он ошибается в обе стороны: поднявшийся туннель опускает
 * предел трафику, который через него не идёт, а маршрут с PMTU меньше любого
 * локального интерфейса не опускает его вовсе — и упирается в ядро уже
 * ПОСРЕДИ исполнения плана, где чистого выхода нет.
 *
 * Цена: три системных вызова на НОВОЕ направление (пакетов не отправляется ни
 * одного — connect на UDP это местный поиск маршрута). Дальше ответ лежит в
 * кольце и на пакетном пути остаётся сравнение чисел. Ячейка опускается по
 * ответу ядра EMSGSIZE так же, как общий предел, и сама не растёт.
 *
 * Никогда не ноль: там, где маршрут неизвестен (нет IP_MTU, отказ connect,
 * бессмысленно малый ответ), возвращён будет общий — оценка занижённая, но
 * честная.
 *
 * ВЫШЕ общего предела ответ маршрута поднимается только тогда, когда общий
 * предел УГАДАН (наименьший MTU среди поднятых). Это не вольность: угаданный
 * предел ошибается в обе стороны, и ответ ядра про КОНКРЕТНЫЙ маршрут — знание
 * лучшего сорта. Если же интерфейс НАЗВАН оператором (--iface), предел
 * объявлен, и маршрут его не перепрыгивает: иначе флаг был бы рекомендацией.
 *
 * Замерено (контейнер gcc:14, 13.09.2026): поднятый dummy с MTU 1200 опускал
 * ОБЩИЙ предел до 1200, тогда как настоящее направление шло через устройство
 * с MTU 65535 и ядро отвечало про него честно. То есть без этой функции
 * датапат резал бы формы, которые проходят, из-за интерфейса, к делу не
 * относящегося. */
size_t   d2k_raw_route_maxlen(d2k_raw *r, const uint8_t dst[4]);

/* Сколько байт унесёт ОДНА посылка этим способом отправки — весь пакет
 * целиком, вместе с заголовком IP. Объявляется рядом с D2K_RAW_CANT_* не
 * случайно: это такой же предел способа отправки, как и поля, которыми он не
 * распоряжается, и вызывающий обязан сверяться с ним так же — отказом
 * активировать план, который в него не укладывается (d2k_plan_max_emit,
 * d2k_plan.h). Никогда не ноль. */
size_t d2k_raw_maxlen(const d2k_raw *r);

/* Отправляет готовый IPv4-пакет. Адрес назначения берётся из его заголовка.
 * 0 — отправлено, -1 — ошибка (причина в err). */
int d2k_raw_send(d2k_raw *r, const uint8_t *pkt, size_t len,
                 char *err, size_t errcap);
/* Prepare required socket options without sending. Call for EVERY packet
 * before starting a plan so unavailable NODEFRAG/mark cannot cause a
 * half-executed fake+fragment combination. Whole packets keep ordinary NAT. */
int d2k_raw_prepare(d2k_raw *r, const uint8_t *pkt, size_t len,
                    char *err, size_t errcap);

uint64_t d2k_raw_sent(const d2k_raw *r);
uint64_t d2k_raw_errors(const d2k_raw *r);

#endif /* D2K_RAW_H */
