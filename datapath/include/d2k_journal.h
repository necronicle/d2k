/* Коды причины, по которой применённый план НЕ ДОИСПОЛНЕН — то есть хотя бы
 * одна его посылка не покинула машину. Едут наружу телом D2K_EV_REFUSED сразу
 * за ключом потока (datapath/ctlsrv.c) и разбираются на приёме
 * (core/link.c).
 *
 * Код, а не текст, по той же причине, что и у подозрений выше: контроллер
 * обязан РАЗЛИЧАТЬ причины, а не сравнивать человеческие формулировки.
 *
 * D2K_REFUSE_NONE выделен нарочно и значит «причина не кодирована»: так
 * выглядит и запись старого датапата, и обычный отказ ПРИМЕНИТЬ план («плана
 * для этой цели нет»), который случается на каждом транзитном потоке и ничего
 * не говорит о нашем зонде. Контроллер обязан читать ноль именно так: это НЕ
 * «отправка не удалась по неизвестной причине». Остальные три кода означают
 * ровно одно — ОТКАЗ НА НАШЕЙ СТОРОНЕ, и по такому исходу нельзя записывать
 * ни свойство коробки, ни негодность плана: измерения просто не было. */
#define D2K_REFUSE_NONE      0  /* причина не кодирована (в т.ч. план не применялся) */
#define D2K_REFUSE_SEND      1  /* ядро отвергло посылку */
#define D2K_REFUSE_QUEUE     2  /* очередь отложенной отправки не приняла посылку */
#define D2K_REFUSE_TOO_LONG  3  /* посылка длиннее того, что унесёт способ отправки */
/* ПОТОК ИСПОРЧЕН: часть плана ушла на провод, остаток не ушёл, и чистого
 * выхода нет — отпустить оригинал значит послать те же байты дважды, не
 * отпустить значит потерять остаток. Отдельный код, а не «не кодирована»:
 * контроллер обязан отличать это и от обычного «плана для цели нет» (код 0,
 * случается на каждом транзитном потоке), и от «посылка не ушла, но поток
 * цел». Испорченный поток не даёт ни успеха, ни неудачи коробки (§2.4), но
 * запрещает применять к нему что-либо ещё. */
#define D2K_REFUSE_DAMAGED   4
/* ИСПОЛНИТЕЛЬ ОТКАЗАЛСЯ ПРИМЕНИТЬ НАЙДЕННЫЙ ПЛАН К ЭТОМУ ПАКЕТУ: якорь
 * невычислим, форма приветствия не та, байты собраны под другой вход и так
 * далее (причина — строкой в note записи, d2k_plan_apply её называет всегда).
 *
 * Отличается от нуля тем, что ноль значит «плана для цели нет» — обычное
 * состояние любого транзитного потока. Здесь план НАЙДЕН и ОТВЕРГНУТ нами, и
 * для потока СВОЕГО ЗОНДА это и есть результат опыта: зонд ушёл голым, а
 * коробка срезала его как без обхода. Поле 13.10.2026, forum.ru-board.com:
 * такой отказ случался 10 раз за 15 минут, события о нём не было вовсе
 * (refuse() молчал о зондовых потоках), и контроллер после одного повтора
 * записывал НАШ отказ в вину кандидату — рабочий приём (плотная серия с
 * битой суммой, три ServerHello на проводе) был выброшен.
 *
 * Код постоянный: тот же план на том же приветствии будет отвергнут снова.
 * Свойство коробки по нему не пишется — измерения не было (§2.4). */
#define D2K_REFUSE_NOT_APPLIED 5
/* ПОТОК КЛИЕНТА НЕ НЕСЁТ ТОГО, ЧТО ПЛАН ТРЕБУЕТ: план объявляет требования
 * к потоку (d2k_plan_flow_needs — выводятся из бит порчи), а этот поток им
 * не отвечает: сдвиг метки времени назад просит метку, которой клиент не
 * предлагает. Поле issue #7, 22.10.2026: ПК без метки времени — 13 из 13
 * «план не применён», телефоны с меткой — план исполняется. Прежде это
 * было нулём d2k_wire_build и текстом «буфер отправки кончился».
 *
 * Отдельный код, а не NOT_APPLIED: тот говорит о ПАКЕТЕ (якорь, форма), этот
 * — о КЛИЕНТЕ. Постоянен для этого клиента: тот же план на том же потоке
 * будет отвергнут снова. Свойство коробки по нему не пишется — измерения не
 * было; для контроллера это знак перемерить цель для этого клиента, а не
 * докладывать «план подтверждён» (замысел 2026-10-23, п. 5.3). */
#define D2K_REFUSE_FLOW_UNFIT 6
/* Local prerequisite unavailable (e.g. confirmed NAT tuple for fragments).
 * Transient, not a property of the remote path or a permanent plan defect. */
#define D2K_REFUSE_CONTEXT 7

