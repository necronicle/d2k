enum {
    /* Приветствие с именем — TLS (ClientHello) или QUIC (Initial). Транспорт
     * не различается видом события: он лежит в самом ключе (d2k_key.proto,
     * d2k_track.h) — заводить отдельный вид под QUIC незачем и опасно, это
     * разошлось бы при первой же правке, если бы кто-то забыл держать два
     * места в согласии. */
    D2K_JRN_HELLO_SNI = 1,
    /* Приветствие TLS без имени — нормально (§5.3). Только TLS: у QUIC
     * d2k_quic_sni не различает «имени нет» от «не расшифровалось этими
     * ключами» (см. d2k_quic.h) — и то, и другое просто НЕ порождает никакого
     * события журнала (см. session.c, handle_udp), а не этот вид. */
    D2K_JRN_HELLO_NONAME,
    /* План применён. Какой именно — в plan_id записи; кладёт его
     * d2k_journal_add_applied. */
    D2K_JRN_PLAN_APPLIED,
    D2K_JRN_PLAN_REFUSED,      /* план не применён, причина в note */
    /* Обмен пошёл: с обратной стороны пришла нагрузка после приветствия.
     * code — тип первой TLS-записи, num — сколько байт. Это НАБЛЮДЕНИЕ, а не
     * приговор «работает»: §4.2 требует различать уровни доказательства, и
     * различает их тот, кто принимает решение, а не тот, кто смотрит.
     * Для UDP: code=0, num — длина первой обратной датаграммы, в том числе
     * пустой; протокол ответа здесь НЕ проверен. */
    D2K_JRN_EXCHANGE,
    /* Пойманная форма приветствия. Байты лежат не здесь: журнал ограничен по
     * размеру записи, а приветствие бывает в килобайт. Здесь только отметка,
     * что поймано, а байты забирает d2k_session_shape. */
    D2K_JRN_SHAPE,
    /* Подозрение на сбой. Именно подозрение: §2.4 запрещает превращать
     * наблюдение в диагноз. Что именно замечено — в note. */
    D2K_JRN_SUSPECT,
    /* СУДЬБА ИСПОЛНЕНИЯ. PLAN_APPLIED остаётся локальной записью подготовки,
     * но не отправляется контроллеру как доказательство исполнения.
     * Только DONE преобразуется в D2K_EV_APPLIED (новый wire-код 0x0009):
     * ОС приняла все сырые посылки, включая отложенные, и вердикт оригинала.
     * UNSENT — когда хотя бы одна операция не выполнена; code несёт
     * D2K_REFUSE_*, plan_id — ID этой попытки. DONE не доказывает доставку. */
    D2K_JRN_PLAN_DONE,
    D2K_JRN_PLAN_UNSENT,
    /* Поток испорчен недоисполнением. Пишется В МОМЕНТ установления
       повреждения, а не при следующем пакете: замолчавший поток следующего
       пакета может не прислать вовсе, и факт потерялся бы. Один раз на
       попытку — события лосси по контракту (d2k_ctl.h). */
    D2K_JRN_PLAN_DAMAGED,
    /* ПОЯВЛЕНИЕ ПОТОКА БЕЗ РАСПОЗНАННОГО ПРОТОКОЛА (этап 42): первая нагрузка
       клиента TCP/UDP — не TLS/HTTP/QUIC/STUN/голос, не зонд. Один раз на
       поток, не на пакет; с наблюдённой стороной клиента (d_client_side, ноль
       — не известна). Это ФАКТ СУЩЕСТВОВАНИЯ: ни протокола, ни успеха, ни
       подозрения в нём нет, и подбора он не запускает. Объём ограничен в
       session.c (D2K_FLOW_FACT_*), подавленное считается. */
    D2K_JRN_FLOW,
    /* ИТОГ ПОЗДНЕГО НАБЛЮДЕНИЯ ТОЧНОГО ПОТОКА (этап 49): code — D2K_LATEOBS_*
       (d2k_lateobs.h), num — сколько повторов сегмента с данными видно,
       d_client_side — сторона клиента. Один на наблюдение. */
    D2K_JRN_LATE_OBS,
    D2K_JRN_PREFLIGHT_START,
    D2K_JRN_PREFLIGHT_HANDOVER,
    D2K_JRN_PREFLIGHT_GAVE_UP
};

/* Применялся ли план к потоку, о котором подозрение. Ноль — «не сказано»:
   так выглядит подозрение от службы, которая про это поле не знает. */
/* Observed initiating endpoint in the canonical flow key. */
#define D2K_CLIENT_SIDE_UNKNOWN 0
#define D2K_CLIENT_SIDE_LOW 1
#define D2K_CLIENT_SIDE_HIGH 2
#define D2K_PLANNED_UNKNOWN 0
#define D2K_PLANNED_YES     1
#define D2K_PLANNED_NO      2

#define D2K_JOURNAL_FLOW_IDENTITY 1
typedef struct {
    uint8_t flow_epoch[16];
    uint64_t flow_incarnation;
    uint64_t at_ns;
    uint64_t execution_id;
    d2k_binding_context binding;
    d2k_key  key;
    uint8_t  kind;
    /* Для D2K_JRN_SUSPECT — код причины подозрения (D2K_SUSPECT_*), для
     * D2K_JRN_PLAN_UNSENT — код причины недоисполнения (D2K_REFUSE_*). Для
     * остального ноль. Одно поле на два разных пространства кодов: их
     * различает вид записи, и без вида ни один из них не читается вовсе. */
    uint8_t  code;
    uint8_t  name_len;
    /* Число при записи: байты обмена для D2K_JRN_EXCHANGE, K для PREFLIGHT_*. Ноль для
     * остального. */
    uint32_t num;
    uint64_t preflight_elapsed_ns; /* preflight: time since client SYN */

    /* Подробности наблюдения — то, ЧЕМ подозрительный пакет отличался от
     * остальных в том же потоке. Для подозрения по сбросу это и есть
     * отпечаток поведения (§3.3): без него в каталоге лежал бы факт «был
     * сброс», по которому одну коробку от другой не отличить.
     *
     * Ориентир (ref_ttl) взят из ЭТОГО ЖЕ потока, поэтому разность
     * осмысленна и на чужой линии, где абсолютные значения другие. */
    uint8_t  d_ttl;      /* TTL подозрительного пакета */
    uint8_t  d_ref_ttl;  /* TTL того, что отвечало по этому соединению */
    uint8_t  d_tos;
    uint16_t d_ipid;
    /* EXCHANGE: сервер прислал ServerHello (см. d2k_jrn_detail ниже). */
    uint8_t  d_server_hello;
    /* ПРИМЕНЯЛСЯ ЛИ ПЛАН К ЭТОМУ ПОТОКУ (D2K_PLANNED_*).
     *
     * Значимо у D2K_JRN_SUSPECT и заведено измеренной причиной. Поле
     * 18.09.2026: подозрение приходило через две секунды после подтверждения
     * плана — о потоке, начатом ДО того, как план доехал. Такой поток шёл без
     * обхода, и уликой против плана он не является; контроллер же считал его
     * деградацией и прекращал наблюдение.
     *
     * Три состояния, а не флаг: «не сказано» нужно старой службе, у которой
     * поля нет. Молча принять её ноль за «план не применялся» значило бы
     * сменить смысл её подозрений задним числом (§2.4). */
    uint8_t  d_planned;
    uint8_t  d_client_shape;
    uint8_t  d_client_side;
    /* Идентификатор применённого плана (REC_ID). Значим при
     * kind == D2K_JRN_PLAN_APPLIED и у записей о судьбе посылок
     * (D2K_JRN_PLAN_DONE/D2K_JRN_PLAN_UNSENT), у остального нули.
     *
     * Отдельным полем, а не через name: имя приходит из сети и потому
     * чистится под печать — всё вне 0x20..0x7e заменяется точкой (см.
     * d2k_journal_add ниже). Идентификатор двоичный, такая чистка испортила
     * бы его молча, и «план применился» приписалось бы не тому плану. */
    uint8_t  plan_id[D2K_PLAN_ID_LEN];
    uint8_t  trial_id[D2K_TRIAL_ID_LEN];
    char     name[D2K_JRN_NAME_MAX + 1];
    /* Строковый литерал причины. Владения нет и не нужно: причины приходят
     * литералами из датапата и живут столько же, сколько программа. */
    const char *note;
} d2k_jrn_entry;

