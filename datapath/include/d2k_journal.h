/* d2k_journal.h — диагностический журнал наблюдений.
 *
 * Кольцо фиксированного размера в памяти. Ни одной записи на диск: §2.3
 * запрещает персистить отрицательный результат, а журнал наблюдений состоит
 * из них почти целиком — «увидели приветствие», «имени нет», «план не
 * применён». Пережить перезапуск он не должен и не будет.
 *
 * Зачем он вообще: §9 этапа C требует диагностического журнала, а §8 — вида
 * «сейчас в работе». Без него сводка отвечает «145 пакетов, 23 потока» и не
 * отвечает на вопрос «а что там было». Счётчики говорят сколько; журнал
 * говорит что именно.
 *
 * Кольцо, а не растущий список: §5.2 требует предела на размер истории. Когда
 * место кончилось, самая старая запись затирается, и число потерянных
 * считается — «журнал полон» и «ничего не происходило» обязаны различаться.
 *
 * Имя цели хранится обрезанным. Полное имя датапату не нужно ни для одного
 * решения, а хранить чужие доменные имена дольше и шире, чем требуется, —
 * лишний риск в публичном продукте.
 */
#ifndef D2K_JOURNAL_H
#define D2K_JOURNAL_H

#include <stddef.h>
#include <stdint.h>

#include "d2k_track.h"

/* Обрезка имени. 63 значащих байта покрывают почти все настоящие имена и
 * держат запись в пределах одной строки вывода. */
#define D2K_JRN_NAME_MAX 63

enum {
    D2K_JRN_HELLO_SNI = 1,     /* приветствие TLS с именем */
    D2K_JRN_HELLO_NONAME,      /* приветствие TLS без имени — нормально (§5.3) */
    D2K_JRN_PLAN_APPLIED,      /* план применён */
    D2K_JRN_PLAN_REFUSED       /* план не применён, причина в note */
};

typedef struct {
    uint64_t at_ns;
    d2k_key  key;
    uint8_t  kind;
    uint8_t  name_len;
    char     name[D2K_JRN_NAME_MAX + 1];
    /* Строковый литерал причины. Владения нет и не нужно: причины приходят
     * литералами из датапата и живут столько же, сколько программа. */
    const char *note;
} d2k_jrn_entry;

typedef struct d2k_journal d2k_journal;

/* cap == 0 создаёт журнал, который ничего не хранит, и это законный режим:
 * на коробке со 128 МБ журнал можно выключить, не выключая наблюдение. */
d2k_journal *d2k_journal_new(size_t cap);
void         d2k_journal_free(d2k_journal *j);

/* name/name_len — имя цели, если оно есть. Обрезается молча: обрезка здесь
 * не потеря данных, а объявленное свойство. */
void d2k_journal_add(d2k_journal *j, uint64_t at_ns, const d2k_key *key,
                     uint8_t kind, const uint8_t *name, size_t name_len,
                     const char *note);

/* Записи от старой к новой. i от 0 до d2k_journal_count()-1. */
size_t               d2k_journal_count(const d2k_journal *j);
const d2k_jrn_entry *d2k_journal_at(const d2k_journal *j, size_t i);

/* Сколько записей затёрто по кругу. */
uint64_t d2k_journal_dropped(const d2k_journal *j);

#endif /* D2K_JOURNAL_H */
