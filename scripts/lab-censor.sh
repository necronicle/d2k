#!/bin/sh
# lab-censor.sh — АВТОНОМНЫЙ ПОИСК ОБХОДА на игрушечном цензоре, без роутера.
#
# Зачем. Полевой прогон стоит окна, в котором у автора дома нет обхода. Всё,
# что можно проверить до него, надо проверить до него. lab-pair.sh доказывает,
# что пара разговаривает; здесь проверяется то, ради чего d2k существует:
# пустой каталог → заблокированная цель → автономно найденное воздействие.
#
# Цензор игрушечный и назван таковым: правило iptables -m string режет ПАКЕТ,
# в котором встретилось имя. Это не модель реального DPI, а его самая простая
# форма — и она честно обходится тем же, чем обходится настоящая: если имя
# разнесено между сегментами, ни в одном пакете целой строки нет.
#
# Чего здесь НЕТ: настоящего цензора, настоящей линии, переносимости на
# клиента. Зелёный результат значит «механизм поиска работает от начала до
# конца», а не «обход работает у пользователя».
#
# Требует Docker. Ничего не трогает на хосте и на роутере.
set -eu

HERE=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
ROOT=$(CDPATH='' cd -- "$HERE/.." && pwd)

if ! docker info >/dev/null 2>&1; then
    echo "lab-censor.sh: нужен запущенный Docker (docker info не отвечает)" >&2
    exit 1
fi

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
tar -C "$ROOT" -cf - --exclude='.git' --exclude='*.o' --exclude='state' . | tar -C "$WORK" -xf -

cat > "$WORK/censor.sh" <<'DRIVER'
#!/bin/sh
set -e
cd /w

fail() { echo "ПРОВАЛ: $*" >&2; dump; exit 1; }

# Контрольное имя проверяется С ПОВТОРАМИ. Сервер обслуживает соединения по
# очереди, и сразу после зарезанной попытки он вполне может быть ещё занят —
# одна проба отличала бы «цензор режет лишнее» от «сервер не успел» только
# случайно.
control_passes() {
    n=0
    while [ $n -lt 5 ]; do
        if timeout 5 openssl s_client -connect "127.0.0.1:$PORT" \
               -servername control.example -tls1_3 </dev/null >/dev/null 2>&1; then
            return 0
        fi
        n=$((n+1)); sleep 1
    done
    return 1
}
# НАСТОЯЩИЙ КЛИЕНТ (критерий 2 MVP).
#
# openssl s_client отвечает на вопрос «дошло ли приветствие». Критерий 2
# спрашивает другое: получил ли обычный клиент ОЖИДАЕМОЕ СОДЕРЖИМОЕ, проверив
# сертификат и имя. Поэтому здесь curl, а не s_client, и сверяется ТЕЛО
# ответа, а не код возврата: сервер лаборатории отдаёт ровно "ok".
#
# Три отличия от нашего зонда, и каждое — предмет проверки:
#   - чужая реализация TLS: наш зонд с ней не сходится по построению;
#   - проверка подлинности (--cacert): зонд её не делает вовсе (0006);
#   - ПРИВЕТСТВИЕ ДРУГОЙ ДЛИНЫ — вчетверо длиннее зондового. Ровно на этом
#     различии ломается переносимость (седьмая находка), и здесь оно живое.
real_client() {
    body=$(timeout 10 curl -sS --cacert /tmp/c.pem \
        --resolve "$1:$PORT:127.0.0.1" "https://$1:$PORT/" 2>/tmp/curl.err) || return 1
    [ "$body" = "ok" ] || return 1
    return 0
}

dump() {
    echo "--- ошибки отправки (все) ---"
    grep -iE "sendto|d2kd: " /tmp/d2kd.log 2>/dev/null | sort | uniq -c | head -20 || true
    echo "--- d2kd ---"; tail -40 /tmp/d2kd.log 2>/dev/null || true
    echo "--- d2kc ---"; tail -60 /tmp/d2kc.log 2>/dev/null || true
    echo "--- правила ---"; iptables -t mangle -S 2>/dev/null || true
}

NAME=zablokirovano.example
NAME2=vtoraya-zablokirovannaya.example
PORT=4443
QUEUE=2001
MARK=0x2d

echo "== подготовка =="
apt-get update -qq >/dev/null 2>&1
apt-get install -y -qq iptables libssl-dev ethtool iproute2 curl >/dev/null 2>&1

# ОФЛОАД НА ПЕТЛЕ СКЛЕИВАЕТ НАШИ СЕГМЕНТЫ ОБРАТНО.
#
# Приём «разнести имя между сегментами» работает ровно потому, что коробка
# видит пакеты по отдельности. На loopback включены GRO и TSO: ядро собирает
# наши три посылки в один большой пакет ДО того, как его увидит netfilter, и
# цензор снова находит имя целиком. То есть без этой строки лаборатория
# проверяет не обход, а офлоад.
#
# На роутере у этого та же природа и то же лечение: fastnat/PPE уводят поток
# мимо conntrack и склеивают сегменты, и полевая процедура снимает их отдельным
# шагом (docs/field/2026-09-12-mvp-acceptance-procedure.md).
ethtool -K lo gro off tso off gso off >/dev/null 2>&1 || true

# ПЕТЛЯ С MTU 65536 ОТДАЁТ СЕГМЕНТЫ, КАКИХ НЕ БЫВАЕТ НА ЛИНИИ.
#
# Измерено здесь же (tcpdump на lo, 13.09.2026): первый полёт сервера уходит
# ОДНИМ сегментом в 1923 байта. Предел копирования датапата — 1600
# (MAX_PKT, datapath/d2kd.c), и он не занижен: на любом реальном канале
# пакет крупнее 1500 не приходит вовсе. Такой сегмент датапат честно
# пропускает как обрезанный — и обмена не видит НИ ОДНОГО, сколько бы обход
# ни работал. То есть без этой строки лаборатория меряет MTU петли.
#
# 1500 — Ethernet, то же, что у роутера на проводе (на PPPoE 1492, ещё
# меньше). Приветствие curl при этом (1581 байт, замерено там же) перестаёт
# помещаться в один сегмент — и это тоже правда линии, а не искажение:
# современный клиент с постквантовым key_share шлёт имя во ВТОРОМ сегменте
# ровно так же.
ip link set lo mtu 1500 2>/dev/null || true

# Цель: настоящий сервер TLS 1.3, ФОРКАЮЩИЙ.
#
# openssl s_server однопоточен, и это ломает опыт целиком: зарезанное цензором
# рукопожатие оставляет его ждать внутри SSL_accept, и следующие соединения —
# включая контрольное — не обслуживаются вовсе. Отличить «цензор режет» от
# «сервер занят» стало бы нечем.
#
# Свой сертификат: проверка подлинности здесь не предмет опыта (её и наш зонд
# не делает, см. 0006). Предмет — доходит ли приветствие до сервера.
# Ключ EC P-256, а не RSA. Наш зонд — минимальный клиент TLS 1.3 (X25519 +
# TLS_AES_128_GCM_SHA256) с браузерным набором signature_algorithms; на
# RSA-сертификате socat отвечал тревогой 40 (handshake_failure) КАЖДЫЙ раз,
# когда приветствие до него доходило, и это маскировало успех обхода под
# неудачу.
#
# SAN ОБЯЗАТЕЛЕН, и это не формальность: критерий 2 требует НАСТОЯЩЕГО
# клиента с проверкой сертификата и имени, а настоящий клиент (curl поверх
# OpenSSL 3) на одно лишь CN не смотрит с 2000-х. Без SAN он отвергал бы
# соединение по причине, не имеющей к обходу никакого отношения.
SAN="DNS:$NAME,DNS:$NAME2,DNS:control.example"
if [ "${D2K_LAB_WRONGCERT:-0}" = "1" ]; then
    # ИНСЦЕНИРОВКА ТЕРМИНИРУЮЩЕЙ КОРОБКИ.
    #
    # Коробка, которая не режет, а сама завершает TLS и отдаёт страницу
    # блокировки, выглядит для зонда РОВНО как рабочий обход: рукопожатие
    # сошлось, приложение ответило 200. Отличить её можно единственным
    # измерением — именем в сертификате.
    #
    # Инсценируется это не отдельным сервером, а тем же сервером с чужим
    # именем в сертификате: предмет опыта — что делает d2k, когда сервер
    # представился не тем, кого спрашивали, а не то, как устроен посредник.
    SAN="DNS:control.example"
    echo "сертификат цели НЕ содержит её имени (инсценировка терминирующей коробки)"
fi
openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 \
    -keyout /tmp/k.pem -out /tmp/c.pem \
    -days 1 -nodes -subj "/CN=$NAME" \
    -addext "subjectAltName=$SAN" >/dev/null 2>&1
# СЕРВЕР — openssl s_server, а НЕ socat.
#
# Замерено прямо здесь: наш зонд доходит до приложения (уровень 3, статус 200)
# против openssl s_server и получает тревогу 40 против socat OPENSSL-LISTEN на
# том же сертификате и той же линии. То есть socat отвергает наше приветствие
# по причине, не имеющей отношения к обходу, и весь опыт превращается в
# «зонд не дошёл» на каждом плече, включая рабочие.
#
# s_server обслуживает соединения ПО ОЧЕРЕДИ, и это терпимо только потому, что
# цензор ниже роняет соединение сбросом, а не молчанием: зависших рукопожатий
# не остаётся.
# ФОРКАЮЩИЙ сервер, свой. Почему не готовые — в шапке spike/labtls.c:
# s_server обслуживает по очереди и виснет на зарезанном рукопожатии,
# socat отвергает приветствие нашего зонда тревогой 40.
cc -std=c99 -O2 -Wall -Wextra -o /tmp/labtls spike/labtls.c -lssl -lcrypto
/tmp/labtls "$PORT" /tmp/c.pem /tmp/k.pem >/tmp/server.log 2>&1 &
SRV=$!
i=0
while ! (timeout 3 openssl s_client -connect "127.0.0.1:$PORT" </dev/null >/dev/null 2>&1) && [ $i -lt 50 ]; do
    i=$((i+1)); sleep 0.2
done
[ $i -lt 50 ] || fail "сервер цели не поднялся" 

echo "== ЛАБОРАТОРИЯ ПРОВЕРЯЕТ СВОЙ ИНСТРУМЕНТ =="
# Наш зонд — минимальный клиент TLS 1.3, и он вправе не сойтись с конкретным
# сервером по причинам, не имеющим к обходу никакого отношения. Если это
# случится, весь опыт будет показывать «зонд не дошёл до приложения» на КАЖДОМ
# плече, включая рабочие, — то есть врать. Проверяем прямо, без цензора и без
# датапата: доходит ли наш зонд до приложения на голой линии.
cat > /tmp/probecheck.c <<'PC'
#include <stdio.h>
#include "d2k_verify.h"
int main(void) {
    d2k_ver_result r = d2k_verify_probe("127.0.0.1", 4443, "control.example", 4000, 0);
    printf("уровень %d, статус %d, причина: %s\n", (int)r.level, r.status, r.reason);
    d2k_verify_close(&r);
    return r.level == D2K_VER_APPLICATION ? 0 : 1;
}
PC
cc -std=c99 -O2 -Icore/include -Idatapath/include -o /tmp/probecheck /tmp/probecheck.c \
   core/verify.c core/tls13.c core/x25519.c core/crypto.c core/hello.c core/meas.c 2>/dev/null || \
cc -std=c99 -O2 -Icore/include -Idatapath/include -o /tmp/probecheck /tmp/probecheck.c \
   core/verify.c core/tls13.c core/x25519.c core/crypto.c core/hello.c core/meas.c core/link.c core/compose.c
if ! /tmp/probecheck; then
    fail "СОБСТВЕННЫЙ ЗОНД не доходит до приложения на ГОЛОЙ линии — опыт бессмыслен: он покажет неудачу на каждом плече, включая рабочие"
fi
echo "инструмент исправен: зонд доходит до приложения без цензора"

echo "== сборка =="
cc -std=c99 -O2 -Wall -Wextra -Werror -Idatapath/include -Icore/include \
   -o /tmp/d2kd datapath/d2kd.c datapath/nfq.c datapath/raw.c \
   datapath/plan_parse.c datapath/plan_apply.c datapath/tls.c datapath/wire.c \
   datapath/wire_udp.c datapath/track.c datapath/session.c datapath/nl.c \
   datapath/sched.c datapath/journal.c datapath/plans.c datapath/ctl.c \
   datapath/ctlsrv.c core/quic.c core/crypto.c
make -s -C core d2kc >/dev/null

echo "== цензор: режем пакет, в котором встретилось имя =="
# ОЧЕРЕДЬ И ЦЕНЗОР — В РАЗНЫХ ХУКАХ, и это не стиль, а необходимость.
#
# Замерено здесь же: `-j NFQUEUE --queue-bypass` БЕЗ слушателя не «пропускает
# дальше по цепочке», а завершает обход хука целиком — правило, стоящее в той
# же цепочке следом, не выполняется вовсе. Поставив цензор за очередью в одной
# цепочке, мы получали бы «цензор не режет» ровно тогда, когда датапат не
# запущен, то есть в самый неудачный момент.
#
# Поэтому: очередь в mangle OUTPUT, цензор в mangle POSTROUTING. Для локально
# рождённого пакета порядок хуков — raw OUTPUT, mangle OUTPUT, nat OUTPUT,
# filter OUTPUT, mangle POSTROUTING. Пакеты, которые датапат выпускает сам,
# идут сырым сокетом и начинают путь заново с raw OUTPUT, в mangle OUTPUT
# отсекаются по метке и доходят до цензора в POSTROUTING — то есть цензор
# видит ИМЕННО то, что выпустил датапат.
iptables -t mangle -N D2KLAB 2>/dev/null || iptables -t mangle -F D2KLAB
iptables -t mangle -A OUTPUT -j D2KLAB
# Свои пакеты мимо очереди — иначе выпущенное датапатом вернётся ему же.
iptables -t mangle -A D2KLAB -m mark --mark "$MARK" -j RETURN
iptables -t mangle -A D2KLAB -p tcp --dport "$PORT" \
    -m connbytes --connbytes 0:20 --connbytes-dir original --connbytes-mode packets \
    -j NFQUEUE --queue-num "$QUEUE" --queue-bypass

# ОБРАТНОЕ НАПРАВЛЕНИЕ — ОБЯЗАТЕЛЬНО, и это стоило отдельного разбора.
#
# Первая редакция ставила очередь только на исходящее, и датапат не видел
# ответов сервера ВООБЩЕ: «обменов 0» получалось даже на контрольном прогоне
# без цензора, где соединения проходили. А обмен — это половина
# доказательства: без него ни один кандидат подтвердить невозможно, сколько бы
# обход ни работал.
#
# Ровно так же устроен боевой набор правил (files/S99d2k): цепочка на
# исходящее по --dports и цепочка на входящее по --sports.
iptables -t mangle -N D2KLAB_IN 2>/dev/null || iptables -t mangle -F D2KLAB_IN
iptables -t mangle -A INPUT -j D2KLAB_IN
iptables -t mangle -A D2KLAB_IN -m mark --mark "$MARK" -j RETURN
iptables -t mangle -A D2KLAB_IN -p tcp --sport "$PORT" \
    -m connbytes --connbytes 0:20 --connbytes-dir reply --connbytes-mode packets \
    -j NFQUEUE --queue-num "$QUEUE" --queue-bypass
# ЦЕНЗОР — НА ПРИЁМНОЙ СТОРОНЕ, и это не мелочь.
#
# Замерено здесь же: DROP локально рождённого пакета в ИСХОДЯЩЕМ пути
# возвращает отправителю EPERM из sendto. Датапат честно считает это ошибкой
# отправки, объявляет опыт несостоявшимся и уходит к следующему кандидату —
# то есть лаборатория меряла бы собственную реакцию на локальный отказ, а не
# обход цензуры. Настоящий DPI роняет пакет на проводе, и отправитель об этом
# не узнаёт.
#
# Для петли путь такой: OUTPUT → POSTROUTING → (петля) → PREROUTING → INPUT.
# Роняем в PREROUTING: отправка уже состоялась, до сервера не дошло — ровно
# то, что делает цензор.
if [ "${D2K_LAB_NOCENSOR:-0}" = "1" ]; then
    echo "цензор ВЫКЛЮЧЕН (D2K_LAB_NOCENSOR=1): это контрольный прогон —"
    echo "он отвечает на вопрос «доходят ли наши пакеты до сервера вообще»."
elif [ "${D2K_LAB_REASM:-0}" = "1" ]; then
    # ЦЕНЗОР С ПАМЯТЬЮ. Собирает поток по номерам последовательности и ищет имя
    # в СОБРАННОМ — то есть разрезом не обходится вовсе. Плюс расстояние: пакет
    # с укороченным TTL он ОСМАТРИВАЕТ (сборка отравлена) и роняет, потому что
    # до сервера такой пакет не доживёт. Подробности и обоснование каждой
    # мелочи — в шапке spike/labdpi.c.
    #
    # 62 хопа — это «коробка в двух хопах от нас, сервер далеко»: пакет с
    # ttl=62 (плечо fake+ttl62 из запасного перебора) коробку видит, сервера
    # не достигает. Число не выдумано: оно взято из самого плеча.
    cc -std=c99 -O2 -Wall -Wextra -Werror -Idatapath/include \
       -o /tmp/labdpi spike/labdpi.c datapath/nfq.c datapath/nl.c
    /tmp/labdpi 2002 "$NAME" 62 > /tmp/labdpi.log 2>&1 &
    DPI=$!
    sleep 1
    iptables -t mangle -A PREROUTING -p tcp --dport "$PORT" \
        -j NFQUEUE --queue-num 2002 --queue-bypass
    echo "цензор С ПАМЯТЬЮ поднят (сборка потока + расстояние 62)"
else
    # ЦЕНЗОР СБРАСЫВАЕТ СОЕДИНЕНИЕ, а не роняет пакет молча.
    #
    # Две причины, обе измеренные. Первая: подделанный RST — самая обычная
    # форма блокировки на живых линиях, и d2k именно её и опознаёт приметой
    # «rst». Вторая: молчаливый DROP оставляет однопоточный s_server висеть
    # внутри SSL_accept, и следующие соединения не обслуживаются вовсе —
    # отличить «цензор режет» от «сервер занят» становится нечем.
    #
    # REJECT доступен в filter, не в mangle; для петли пакет доходит до INPUT,
    # и сброс уходит клиенту оттуда.
    # ЦЕНЗОР В mangle PREROUTING С DROP, и оба выбора измерены.
    #
    # Хук: в исходящем пути DROP локально рождённого пакета возвращает
    # отправителю EPERM, и датапат честно считает это СВОЕЙ ошибкой отправки —
    # лаборатория мерила бы собственную реакцию, а не обход. В filter INPUT
    # правило со строкой не срабатывает вовсе (счётчик правила остаётся нулём;
    # проверено отдельно). Работает PREROUTING: отправка уже состоялась, до
    # сервера не дошло — ровно то, что делает цензор.
    #
    # Действие: DROP, а не REJECT. Молчаливая потеря — та форма, в которой
    # блокировку видит клиент, и та, на которой d2k учится отличать её от
    # недоступности контролем по другому имени.
    iptables -t mangle -A PREROUTING -p tcp --dport "$PORT" \
        -m string --string "$NAME" --algo bm -j DROP
    # ВТОРАЯ ЦЕЛЬ, той же коробкой. Нужна для второго критерия MVP: ранее
    # неизвестная цель обязана получить пробу готового плана ДО новых
    # вопросов. Без второй цели это утверждение проверить нечем.
    iptables -t mangle -A PREROUTING -p tcp --dport "$PORT" \
        -m string --string "$NAME2" --algo bm -j DROP
fi

echo "== цензор работает? =="
if [ "${D2K_LAB_NOCENSOR:-0}" = "1" ]; then
    echo "пропущено: цензор выключен"
elif timeout 5 openssl s_client -connect "127.0.0.1:$PORT" -servername "$NAME" \
       -tls1_3 </dev/null >/dev/null 2>&1; then
    fail "цензор не режет: соединение с заблокированным именем прошло"
elif ! control_passes; then
    fail "цензор режет ЛИШНЕЕ: контрольное имя тоже не проходит"
elif real_client "$NAME"; then
    fail "цензор не режет НАСТОЯЩЕГО клиента: без обхода curl уже получил содержимое — критерию 2 нечего доказывать"
elif ! real_client control.example; then
    fail "настоящий клиент не работает даже на контрольном имени: опыт мерил бы curl, а не обход ($(cat /tmp/curl.err 2>/dev/null))"
else
    echo "цензор на месте: заблокированное имя не проходит ни s_client, ни настоящему клиенту; контрольное проходит обоим"
fi

CAT=/tmp/lab-catalog.json
rm -f "$CAT"
SOCK=/tmp/lab-ctl.sock; rm -f "$SOCK"

echo "== датапат в режиме apply =="
# ИНСЦЕНИРОВКА ОТКАЗА ПО ДЛИНЕ (критерий 6). Заводим интерфейс с заведомо
# малым MTU и указываем его датапату: предел отправки станет 600 байт, и
# планы с фальшивкой в двойную длину правды перестанут в него влезать.
#
# Это инсценировка НАШЕЙ неудачи, а не свойства коробки. Проверяемое
# утверждение ровно одно: ложного подтверждения от этого не появляется.
IFACE_ARG=""
if [ "${D2K_LAB_TINYMTU:-0}" = "1" ]; then
    ip link add labtiny type dummy 2>/dev/null || true
    # 100 байт. Дорога сюда была поучительной, и цифры не подобраны:
    #   600 — куски клиентского приветствия в полтора килобайта ещё
    #         помещаются, часть плеч исполняется честно;
    #   300 — не помещается приветствие КЛИЕНТА, но помещаются куски
    #         приветствия НАШЕГО ЗОНДА, оно втрое короче. План при этом
    #         подтверждается на зонде — и это не ложное подтверждение, а
    #         настоящее, просто для другого контекста (см. запись в
    #         docs/field/2026-09-13-lab-censor.md про переносимость);
    #   100 — не помещается ничьё воздействие, и подтверждению взяться
    #         неоткуда.
    ip link set labtiny mtu 100 up 2>/dev/null || true
    IFACE_ARG="--iface labtiny"
    echo "предел отправки сужен до MTU 100 (инсценировка отказа по длине)"
fi
# Журнал включён: без него «подготовлен 15, доисполнен 1» остаётся загадкой,
# а с ним видно судьбу КАЖДОЙ попытки.
# shellcheck disable=SC2086
/tmp/d2kd --mode apply --control "$SOCK" --queue "$QUEUE" --mark 45 $IFACE_ARG \
    --journal 400 --duration 300 > /tmp/d2kd.log 2>&1 &
DPID=$!
i=0; while [ ! -S "$SOCK" ] && [ $i -lt 100 ]; do i=$((i+1)); sleep 0.1; done
[ -S "$SOCK" ] || fail "датапат не открыл управляющий сокет"

echo "== контроллер, каталог ПУСТОЙ =="
./core/d2kc --control "$SOCK" --catalog "$CAT" > /tmp/d2kc.log 2>&1 &
CPID=$!
sleep 1

echo "== обращение пользователя к заблокированной цели =="
# ОБРАЩАЕТСЯ НАСТОЯЩИЙ КЛИЕНТ, а не наш зонд и не s_client. Это меняет опыт по
# существу: снимок приветствия, которым d2k будет мерить, снимается с ТОГО
# ЖЕ клиента, которому потом предстоит работать. Мерить коротким приветствием
# зонда, а проверять длинным приветствием браузера — это и есть седьмая
# находка лаборатории.
for n in 1 2 3; do
    real_client "$NAME" >/dev/null 2>&1 || true
    sleep 2
done

# Поиск идёт своим ходом: ждём результата, а не спим наугад.
i=0
while [ $i -lt 60 ]; do
    grep -q "подтверждено\|привязк" /tmp/d2kc.log 2>/dev/null && break
    i=$((i+1)); sleep 2
done

# ВТОРАЯ ЦЕЛЬ — уже после того, как коробка узнана по первой.
if [ "${D2K_LAB_NOCENSOR:-0}" != "1" ]; then
    echo "== вторая цель: обращение к ещё неизвестному имени =="
    for n in 1 2 3; do
        real_client "$NAME2" >/dev/null 2>&1 || true
        sleep 2
    done
    i=0
    while [ $i -lt 40 ]; do
        grep -q "готовых планов" /tmp/d2kc.log 2>/dev/null && break
        i=$((i+1)); sleep 2
    done
fi

# КРИТЕРИЙ 4 — ДО остановки служб и сервера. Проверять «работает ли
# контрольная цель» после того, как сервер убит, значит проверять не то:
# первая редакция ровно так и проваливалась.
#
# Обход, который чинит одно и ломает другое, продуктом не является. Здесь это
# не абстракция: датапат стоит в разрыве ВСЕГО трафика на этот порт, включая
# тот, к которому плана нет.
if ! control_passes; then
    fail "контрольная цель перестала работать при живом обходе"
fi
echo "критерий 4 показан: контрольная цель работает при живом обходе"

# КРИТЕРИЙ 2 — НАСТОЯЩИЙ КЛИЕНТ, и тоже ДО остановки служб.
#
# Утверждение здесь сильнее всех остальных в этой лаборатории: не «поиск
# работает» и не «привязка записалась», а «обычный клиент получил ожидаемое
# содержимое через цензора, проверив сертификат и имя».
#
# Провал этой проверки при непустом каталоге — это НЕ провал опыта, а ровно
# седьмая находка в живом виде: подтверждение на зонде есть, работы у клиента
# нет. Поэтому он назван своими словами и валит прогон: молча пройти мимо
# такого значило бы выдать каталог за обход.
rm -f /tmp/lab-crit2
if [ "${D2K_LAB_WRONGCERT:-0}" = "1" ]; then
    echo "критерий 2 пропущен: сертификат намеренно чужой, обхода быть не должно"
elif [ "${D2K_LAB_TINYMTU:-0}" = "1" ]; then
    echo "критерий 2 пропущен: предел отправки сужен намеренно, воздействий нет"
elif [ "${D2K_LAB_NOCENSOR:-0}" = "1" ]; then
    echo "критерий 2 пропущен: цензора нет, проверять нечего"
elif real_client "$NAME"; then
    echo "КРИТЕРИЙ 2 ПОКАЗАН: настоящий клиент получил ожидаемое содержимое"
    echo "через цензора, проверив сертификат и имя ($NAME)"
    echo "КРИТЕРИЙ 2 ПОКАЗАН" > /tmp/lab-crit2
elif [ "${D2K_LAB_REASM:-0}" = "1" ]; then
    # В режиме собирающей коробки это ОТКРЫТЫЙ вопрос, а не поломка стенда:
    # плечо, найденное зондом, клиенту может не достаться. Итог печатается
    # ниже вместе со статистикой цензора — прогон обязан дойти до него, а не
    # оборваться здесь.
    echo "КЛИЕНТ ОБХОДА НЕ ПОЛУЧИЛ — разбор ниже"
else
    fail "НЕПЕРЕНОСИМОСТЬ: настоящий клиент обхода не получил ($(cat /tmp/curl.err 2>/dev/null)). В каталоге может стоять «подтверждено» — у человека обхода нет"
fi

kill "$CPID" 2>/dev/null || true; wait "$CPID" 2>/dev/null || true
kill "$DPID" 2>/dev/null || true; wait "$DPID" 2>/dev/null || true
kill "$SRV" 2>/dev/null || true

dump

grep -q "подозрение\|начинаю поиск" /tmp/d2kc.log || \
    fail "d2k не заметил проблемного трафика — поиск не начался"

# ГЛАВНОЕ УТВЕРЖДЕНИЕ: найден ли обход. Не «поиск шёл», не «события были» —
# появилась ли в каталоге ПОДТВЕРЖДЁННАЯ привязка.
echo "--- каталог ---"
cat "$CAT" 2>/dev/null || echo "(каталога нет)"

if [ "${D2K_LAB_REASM:-0}" = "1" ]; then
    kill "$DPI" 2>/dev/null || true
    echo "--- цензор с памятью ---"; cat /tmp/labdpi.log 2>/dev/null || true
    # ЗДЕСЬ ПРОВЕРЯЕТСЯ НЕ «НАШЁЛСЯ ЛИ ОБХОД», А ЧЕСТНОСТЬ.
    #
    # Найдётся ли плечо против СОБИРАЮЩЕЙ коробки — открытый вопрос, ради
    # которого этот режим и заведён; объявлять его провалом лаборатории
    # нельзя. Обязательно другое: если привязка появилась, у настоящего
    # клиента ОБЯЗАН быть обход. Привязка без обхода — то самое ложное
    # подтверждение, ради которого вся седьмая находка.
    if [ -s "$CAT" ] && grep -q '"target"' "$CAT"; then
        if grep -q "КРИТЕРИЙ 2 ПОКАЗАН" /tmp/lab-crit2 2>/dev/null; then
            echo "ПЛЕЧО ПРОТИВ СОБИРАЮЩЕЙ КОРОБКИ НАЙДЕНО И ПЕРЕНОСИМО:"
            echo "привязка записана И настоящий клиент получил содержимое."
        else
            echo "НАХОДКА: привязка записана, а настоящий клиент обхода НЕ ПОЛУЧИЛ."
            echo "Это ложное подтверждение по переносимости: плечо исполнилось зонду"
            echo "и не исполнилось клиенту. Разбор — в docs/field/2026-09-13-lab-censor.md."
            grep -n "потоку клиента\|не помещается\|подозрение при подтверждённом" \
                /tmp/d2kc.log 2>/dev/null | tail -5 || true
        fi
    else
        echo "ПЛЕЧА ПРОТИВ СОБИРАЮЩЕЙ КОРОБКИ НЕ НАШЛОСЬ — это находка, а не поломка:"
        echo "запас воздействий d2k не покрывает коробку, которая собирает поток."
    fi
    exit 0
fi

if [ "${D2K_LAB_WRONGCERT:-0}" = "1" ]; then
    # СЕРВЕР ПРЕДСТАВИЛСЯ ЧУЖИМ ИМЕНЕМ — подтверждению взяться неоткуда.
    #
    # Требуется ровно два факта: ни одной привязки и НАЗВАННАЯ причина. Пустой
    # каталог сам по себе доказывает мало (мало ли почему поиск не сошёлся) —
    # поэтому проверяется и то, что несовпадение имени прозвучало вслух.
    if [ -s "$CAT" ] && grep -q '"target"' "$CAT"; then
        fail "разговор с сервером ЧУЖОГО имени записан подтверждением — каталог наполняется страницами блокировки"
    fi
    grep -q "представился ЧУЖИМ" /tmp/d2kc.log || \
        fail "имя в сертификате не сошлось, а причина нигде не названа"
    echo "показано: сервер ЧУЖОГО имени не даёт подтверждения, и причина названа"
    exit 0
fi

if [ "${D2K_LAB_TINYMTU:-0}" = "1" ]; then
    # КРИТЕРИЙ 6. Предел отправки заведомо мал, значит воздействия не
    # состоялись. Требуется ровно одно: НИ ОДНОГО подтверждения. Пустой
    # каталог здесь — правильный ответ, а не неудача опыта.
    if [ -s "$CAT" ] && grep -q '"target"' "$CAT"; then
        fail "при несостоявшихся воздействиях появилась привязка — ложное подтверждение"
    fi
    grep -q "не активирован\|опыт невозможен\|не помещается" /tmp/d2kd.log /tmp/d2kc.log || \
        fail "отказ по длине нигде не назван — молчаливая потеря воздействия"
    echo "критерий 6 показан: отказ по длине не создал подтверждения и назван вслух"
    exit 0
fi

if [ ! -s "$CAT" ]; then
    fail "каталог пуст: автономного обхода не найдено"
fi
grep -q '"bindings"' "$CAT" || fail "в каталоге нет привязок"

# ВТОРОЙ КРИТЕРИЙ: готовый план узнанной коробки пробуется ДО новых вопросов.
# Проверяем не «в каталоге стало две привязки» — это был бы результат любого
# порядка, — а ИМЕННО ПОРЯДОК: сообщение о готовых планах обязано появиться
# раньше первого вопроса по второй цели.
if [ "${D2K_LAB_NOCENSOR:-0}" != "1" ]; then
    if ! grep -q "готовых планов" /tmp/d2kc.log; then
        echo "ВНИМАНИЕ: вторая цель не получила пробы готового плана — критерий 3 НЕ показан"
    else
        ready_at=$(grep -n "готовых планов" /tmp/d2kc.log | head -1 | cut -d: -f1)
        ask_at=$(grep -n "$NAME2.*спрашиваю коробку" /tmp/d2kc.log | head -1 | cut -d: -f1)
        if [ -n "$ask_at" ] && [ "$ready_at" -gt "$ask_at" ]; then
            fail "вторая цель пошла в вопросы РАНЬШЕ пробы готового плана — порядок обучения нарушен"
        fi
        echo "критерий 3 показан: готовый план коробки пробуется до новых вопросов"
    fi
fi

# КРИТЕРИЙ 5: перезапуск сохраняет знание и НЕ расширяет его область.
# Считаем привязки до и после: их число обязано совпасть. Рост означал бы, что
# перезапуск сам себе что-то дописал; падение — что знание потеряно.
binds_before=$(grep -c '"target"' "$CAT")
cp "$CAT" /tmp/lab-catalog-before.json
/tmp/d2kd --mode apply --control "$SOCK" --queue "$QUEUE" --mark 45 \
    --journal 100 --duration 20 > /tmp/d2kd2.log 2>&1 &
DPID2=$!
i=0; while [ ! -S "$SOCK" ] && [ $i -lt 100 ]; do i=$((i+1)); sleep 0.1; done
./core/d2kc --control "$SOCK" --catalog "$CAT" > /tmp/d2kc2.log 2>&1 &
CPID2=$!
sleep 8
kill "$CPID2" 2>/dev/null || true; wait "$CPID2" 2>/dev/null || true
kill "$DPID2" 2>/dev/null || true; wait "$DPID2" 2>/dev/null || true

binds_after=$(grep -c '"target"' "$CAT")
echo "привязок до перезапуска $binds_before, после $binds_after"
[ "$binds_after" -ge "$binds_before" ] || fail "перезапуск ПОТЕРЯЛ подтверждённое знание"
[ "$binds_after" -le "$binds_before" ] || fail "перезапуск САМ дописал привязки — знание расширено без замера"
grep -q "поставлено планов по подтверждённым привязкам" /tmp/d2kc2.log || \
    fail "после перезапуска планы каталога не поставлены датапату"
echo "критерий 5 показан: перезапуск сохранил знание и не расширил его"

echo "ВСЁ ЗЕЛЕНО: обход найден автономно, привязка записана в каталог"
