// Package plan — формат Plan: что d2k делает с пакетами одного соединения.
//
// Здесь только Go: этот пакет ПОРОЖДАЕТ обе формы плана — каноническую TLV и
// человеческую текстовую. Исполнитель на C читает исключительно TLV
// (docs/decisions/0002): разборщик текста в компоненте, чей вход приходит из
// сети, — лишняя поверхность для ошибок ровно там, где падение кладёт транзит.
//
// План версионирован двумя числами, и они отвечают на разные вопросы. Schema —
// как разбирать байты. MinExec — какие операции обязан уметь исполнитель.
// Старый исполнитель может понимать раскладку и всё равно не уметь нужного,
// и именно это ловит второе поле.
package plan

// Anchor — семантический якорь позиции. Разрезы задаются якорем и смещением,
// а не байтовым числом: у донора боевое плечо ставит seqovl=681, и 681 — это
// длина целого приветствия к чужому имени, верная ровно для того хоста, где
// измерялась. Якорь переносится, число — нет.
type Anchor uint16

const (
	AnchorPayloadStart Anchor = 0
	AnchorSNIStart     Anchor = 1
	AnchorSNIEnd       Anchor = 2
	AnchorHelloMiddle  Anchor = 3
	AnchorRecordEnd    Anchor = 4
)

// Placement — где стоит фальшивка. Не косметика: замер донора показал, что
// отдельная посылка перед перекрытием работает там, где та же приманка внутри
// перекрывающего сегмента не работает.
type Placement uint8

const (
	PlaceBefore  Placement = 0
	PlaceBetween Placement = 1
)

// Order — порядок посылки кусков. Обратный означает, что хвост приветствия
// уходит раньше головы: коробка, читающая поток как он приходит, сигнатуру не
// соберёт, а сервер соберёт — для него порядок не важен.
type Order uint8

const (
	OrderForward Order = 0
	OrderReverse Order = 1
)

// Флаги порчи. Смысл один: сервер такой сегмент выбросит, а коробка возьмёт.
const (
	PoisonBadSum    uint8 = 1 << 0
	PoisonTCPTSBack uint8 = 1 << 1
	PoisonIPIDZero  uint8 = 1 << 2
)

// Флаги защиты потока. Защита — не преобразование исходящего: это решение о
// ЧУЖОМ входящем пакете, и потому отдельная сущность, а не порча.
//
// GuardRSTAlien: снимать входящий RST, чей отправитель не тот, что отвечал по
// этому же соединению. Ориентир берётся из самого потока — из SYN-ACK, который
// сервер прислал минуту назад, — а не из константы. Это важно: у донора та же
// идея была сделана правилом по идентификатору IP 0..15, и оно снимало
// НАСТОЯЩИЕ сбросы Linux-серверов, которые ходят с id 0, а подделку с id 54321
// не ловило вовсе. Ориентир, взятый из чужого потока, не может разойтись с
// этим потоком.
const (
	GuardRSTAlien uint8 = 1 << 0
)

// Position — семантическая позиция разреза.
type Position struct {
	Anchor Anchor
	Offset int16
}

// Payload — байты приманки, адресуемые по номеру. Номера начинаются с
// единицы: ноль в поле ссылки означает «ничего».
type Payload struct {
	ID    uint16
	Bytes []byte
}

// Poison — набор порчи, адресуемый по номеру. Отдельная сущность, а не поле
// внутри фальшивки: один и тот же набор применяется к разным посылкам, а
// описанный дважды он однажды разойдётся.
type Poison struct {
	ID       uint16
	TTL      uint8 // 0 — не трогать
	Flags    uint8
	SeqShift int32
}

// Fake — отдельная посылка-фальшивка.
//
// Repeats и GapUS — параметры плана, а не константы. Донор зафиксировал:
// боевое плечо обходится двумя копиями с паузой 78 мс, а плотной очереди нужно
// семь. Если у счётчика коробки есть временное окно, плотная очередь и
// растянутая пара для неё не одно и то же.
type Fake struct {
	PayloadID uint16
	PoisonID  uint16 // 0 — без порчи
	Repeats   uint8
	GapUS     uint32
	Placement Placement
}

// Seqovl — сегмент, начинающийся левее настоящих данных и накрывающий их.
// Длина перекрытия равна длине приманки и задаётся ею, а не числом: задать
// числом и добить остаток набивкой — не то же самое, запись получается битой
// и коробка отбрасывает её целиком.
type Seqovl struct {
	PayloadID uint16
	PoisonID  uint16 // 0 — без порчи
}

// Plan — версионированная структура, а не строка команд.
type Plan struct {
	Schema  uint16
	MinExec uint16

	ID        [16]byte
	Transport uint8 // 6 — TCP, 17 — UDP
	Proto     uint8 // 0 — неизвестен, 1 — TLS, 2 — QUIC

	Payloads []Payload
	Poisons  []Poison
	Splits   []Position
	Fakes    []Fake
	Seqovls  []Seqovl
	Order    Order

	// Защита потока от подделанных ответов. Не преобразование исходящего:
	// это решение о ЧУЖОМ входящем пакете.
	Guards uint8
}

// NeedExec — какую версию исполнителя требует ЭТОТ план. Не константа сборки:
// план без новых операций обязан оставаться исполнимым старым исполнителем,
// иначе каждое расширение формата разом ломало бы уже проверенные планы.
func (p Plan) NeedExec() uint16 {
	if p.Guards != 0 {
		return 2
	}
	return 1
}

// Версии, которые порождает и понимает эта сборка.
const (
	SchemaCurrent uint16 = 1
	// Версия исполнителя, которую умеет ЭТА сборка. План объявляет свою
	// потребность через NeedExec.
	ExecVersion uint16 = 2
)
