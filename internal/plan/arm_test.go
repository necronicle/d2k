package plan

import (
	"encoding/hex"
	"strings"
	"testing"
)

// Сценарий приёмки: один пакет с настоящим приветствием клиента. Смещение и
// длина имени переданы протокольным модулем — исполнитель протоколов не
// разбирает.
const сценарийПлеча = "pkt 2000 43 11 " +
	"16030100450100004103031111111111111111111111111111111111111111111111111111111111111111000002130101000016000000110000000e00000b6865747a6e65722e636f6d\n"

func TestПлечоВыраженоПланом(t *testing.T) {
	checkGolden(t, "rzd_arm.golden", runLab(t, readFixture(t, "rzd_arm.plan"), сценарийПлеча))
}

// Приманка обязана доехать до провода целиком и с именем внутри. Проверяем не
// «что-то выпустилось», а что выпущены именно те байты: подставное имя —
// несущая часть плеча, и его потеря обесценивает всё остальное.
func TestИмяИзБелогоСпискаДоезжаетДоПровода(t *testing.T) {
	out := runLab(t, readFixture(t, "rzd_arm.plan"), сценарийПлеча)
	name := hex.EncodeToString([]byte("disk.rzd.ru"))
	if !strings.Contains(out, name) {
		t.Fatalf("подставного имени нет в выпущенных байтах:\n%s", out)
	}
	// И оно не должно случайно оказаться в настоящей нагрузке: настоящее имя
	// в сценарии другое.
	if strings.Contains(out, hex.EncodeToString([]byte("hetzner.com"))) {
		t.Error("настоящее имя выпущено фальшивкой — перепутаны приманка и нагрузка")
	}
}

// Главная проверка задачи: тест обязан РАЗЛИЧАТЬ плечи. Если план с убранной
// составляющей даёт тот же вывод, тест подтверждает сам себя и ничего не
// стоит.
func TestПлечоРазличаетсяПоСоставляющим(t *testing.T) {
	полное := runLab(t, readFixture(t, "rzd_arm.plan"), сценарийПлеча)

	for _, c := range []struct{ имя, файл string }{
		{"без фальшивки — контрольное плечо", "rzd_arm_nofake.plan"},
		{"без порчи — фальшивка дойдёт до сервера", "rzd_arm_nopoison.plan"},
		{"огрызок вместо целого приветствия", "rzd_arm_stub.plan"},
	} {
		got := runLab(t, readFixture(t, c.файл), сценарийПлеча)
		if got == полное {
			t.Errorf("%s: вывод не изменился — тест не различает плечи", c.имя)
		}
	}
}
