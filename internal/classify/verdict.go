package classify

// Verdict — класс блокировки, опознанный по форме отклика.
//
// Вердикта «блокировка по адресу» здесь НЕТ намеренно. Донор такой выносит, но
// §2.3 запрещает d2k утверждать это: неудача конечного набора вопросов не
// доказывает, что режут адрес, а сохранённое утверждение мешало бы честной
// повторной попытке завтра. Соответствующий случай называется тем, что о нём
// известно: содержимое ни при чём.
type Verdict string

const (
	// VerdictClear — триггер проходит как есть. Обходить нечего.
	VerdictClear Verdict = "clear"
	// VerdictPrefix — префиксный матчер без пересборки: разрез внутри
	// сигнатуры её ломает. Самый дешёвый в обходе случай.
	VerdictPrefix Verdict = "prefix"
	// VerdictWholePacket — матчер требует пакет целиком: проходит ЛЮБОЙ
	// разрез, границы сигнатуры нет.
	VerdictWholePacket Verdict = "whole_packet"
	// VerdictOpaque — разрез не помогает, но контроль проходит: решение по
	// содержимому, поток пересобирается. Разрез бесполезен, нужен слой
	// вопросов о свойствах (перекрытие, порядок, сумма) — Task 4.
	VerdictOpaque Verdict = "opaque"
	// VerdictInconclusive — контроль не прошёл, базовой линии нет. Отличить
	// «режут наши байты» от «молчит всё» нечем, и выдавать догадку за вердикт
	// нельзя (§2.4).
	VerdictInconclusive Verdict = "inconclusive"
	// VerdictFlaky — измерения не воспроизводятся. Соврать здесь хуже, чем
	// промолчать.
	VerdictFlaky Verdict = "flaky"
	// VerdictUnreachable — до цели нет даже TCP. Мерить нечего.
	VerdictUnreachable Verdict = "unreachable"
)

// Step — один заданный вопрос и его исход. Трасса нужна человеку: «вердикт
// opaque» без хода рассуждения непроверяем.
type Step struct {
	What string
	Pass int
	Fail int
}
