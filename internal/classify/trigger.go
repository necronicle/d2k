// Package classify измеряет ФУНКЦИЮ РЕШЕНИЯ коробки вместо перебора стратегий.
//
// Перебор ищет в пространстве стратегий: гоняет N плеч и смотрит, какое
// прошло. Это N соединений, каждое со своим таймаутом, и результат ничего не
// говорит о том, ПОЧЕМУ плечо сработало — значит на соседней линии он не
// переносится.
//
// Здесь постановка другая. Коробка — это функция: берёт байты соединения и
// решает «пропустить» или «убить». Функцию можно зондировать напрямую, не имея
// на руках ни одной рабочей стратегии, если есть две вещи:
//
//	триггер — байты, которые надёжно вызывают блокировку;
//	оракул  — чем «прошло» отличается от «убито».
//
// Меняя ТОЛЬКО способ записи одного и того же триггера, читаем структуру
// матчера, а из структуры следует семейство обхода (§3.5).
package classify

import (
	"bytes"
	"errors"

	"github.com/necronicle/d2k/internal/plan"
)

// Trigger — байты, которыми спрашиваем, и координаты имени внутри них.
//
// Координаты нужны поиску границы: резать вслепую по всей длине дороже, чем
// начать с окрестностей имени, а без координат нельзя и назвать место разреза
// осмысленно.
type Trigger struct {
	Payload []byte
	SNI     string
	SNIOff  int
	SNILen  int
}

// TLSTrigger — приветствие с заданным именем.
func TLSTrigger(sni string) (Trigger, error) {
	if sni == "" {
		return Trigger{}, errors.New("триггеру нужно имя")
	}
	h, err := plan.Hello(sni, 0x30)
	if err != nil {
		return Trigger{}, err
	}
	off := bytes.Index(h, []byte(sni))
	if off < 0 {
		return Trigger{}, errors.New("имя не нашлось в собранном приветствии")
	}
	return Trigger{Payload: h, SNI: sni, SNIOff: off, SNILen: len(sni)}, nil
}

// Control — приветствие с ДРУГИМ именем на ту же цель.
//
// Контроль отвечает на вопрос «а содержимое вообще при чём?»: если и он
// молчит, наши байты ни при чём. Внешнего сервера здесь нет и быть не может
// (§3.5) — меняется только имя, адрес тот же.
func Control(sni string) (Trigger, error) { return TLSTrigger(sni) }
