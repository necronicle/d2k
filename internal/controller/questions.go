package controller

// Различающие вопросы к коробке.
//
// Смысл здесь не в наборе готовых плеч, а в поиске РАСХОЖДЕНИЯ между тем, как
// сообщение читает коробка, и тем, как его читает сервер. Обход существует
// ровно там, где эти два разбора расходятся; значит и искать надо расхождение,
// а не перебирать чужие рецепты.
//
// §3.5: «для каждого изученного поведения нужен минимально достаточный набор
// вопросов, позволяющий выбрать известный план или отличить модель от других
// кандидатов. Вопросы адаптивны: следующий задаётся, когда его ответ способен
// изменить выбор».
//
// Каждый вопрос стоит одного зонда и отвечает на ОДНУ вещь. Ответы копятся в
// Traits, и уже из них собирается план. Плана «как у донора» не существует:
// существует набор свойств коробки, из которых план выводится.

// Trait — ответ на один вопрос. Троичный намеренно: «не спрашивали» и «нет» —
// разные состояния, и §2.4 запрещает превращать первое во второе.
type Trait int

const (
	TraitUnknown Trait = iota
	TraitYes
	TraitNo
)

func (t Trait) String() string {
	switch t {
	case TraitYes:
		return "да"
	case TraitNo:
		return "нет"
	default:
		return "не спрашивали"
	}
}

// Traits — что известно о разборе у коробки.
//
// Это НЕ диагноз её устройства (§2.4), а список наблюдений вида «на такой
// вопрос она отвечает так». Из них выводится, куда резать.
type Traits struct {
	// ByName — решает ли коробка по имени. Нет означает, что дело в адресе, и
	// никакая работа с именем не поможет.
	ByName Trait
	// ReadsFirstHello — берёт ли она первое приветствие в соединении. Если
	// да, приманка впереди перекрывает настоящее имя.
	ReadsFirstHello Trait
	// ChecksSum — проверяет ли контрольную сумму TCP. Если нет, приманку
	// можно сделать невидимой для сервера испорченной суммой.
	ChecksSum Trait
	// Reassembles — собирает ли она сегменты. Если нет, имя можно разрезать
	// по границе сегмента: сервер соберёт, коробка нет.
	Reassembles Trait
}

// Question — один различающий вопрос.
type Question struct {
	// Name — как вопрос называется в журнале решений.
	Name string
	// Why — что именно этот вопрос отсекает. Нужно человеку, читающему
	// журнал: «пробую вопрос 3» ничего не объясняет.
	Why string
}

// nextQuestion выбирает следующий вопрос: тот, чей ответ способен изменить
// дальнейший выбор. Вопрос, ответ на который ничего не меняет, не задаётся —
// каждый зонд это время пользователя.
func nextQuestion(t Traits) (Question, bool) {
	// Первым — самый дешёвый и самый решающий. Если коробка блокирует адрес,
	// а не имя, то все остальные вопросы бессмысленны: работа с именем не
	// поможет никогда. Сегодня отсутствие этого вопроса стоило трёх зондов
	// на цель, которую невозможно пробить в принципе.
	if t.ByName == TraitUnknown {
		return Question{
			Name: "по имени или по адресу",
			Why:  "если решает адрес, работа с именем не поможет никогда",
		}, true
	}
	if t.ByName == TraitNo {
		// Ответ получен и он закрывает тему.
		return Question{}, false
	}
	if t.ReadsFirstHello == TraitUnknown {
		return Question{
			Name: "первое приветствие или последнее",
			Why:  "если первое, приманка впереди перекроет настоящее имя",
		}, true
	}
	if t.Reassembles == TraitUnknown {
		return Question{
			Name: "собирает ли сегменты",
			Why:  "если нет, имя можно разрезать по границе сегмента",
		}, true
	}
	return Question{}, false
}
