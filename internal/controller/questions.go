package controller

import "github.com/necronicle/d2k/internal/classify"

// Различающие вопросы к коробке.
//
// Смысл здесь не в наборе готовых плеч, а в поиске РАСХОЖДЕНИЯ между тем, как
// сообщение читает коробка, и тем, как его читает сервер. Обход существует
// ровно там, где эти два разбора расходятся; значит и искать надо расхождение,
// а не перебирать чужие рецепты.
//
// §3.5: «для каждого изученного поведения нужен минимально достаточный набор
// вопросов, позволяющий выбрать известный план или отличить модель от других
// кандидатов. Вопросы адаптивны: следующий задаётся, когда его ответ способен
// изменить выбор».
//
// Каждый вопрос стоит одного зонда и отвечает на ОДНУ вещь. Ответы копятся в
// Traits, и уже из них собирается план. Плана «как у донора» не существует:
// существует набор свойств коробки, из которых план выводится.

// Trait — ответ на один вопрос. Троичный намеренно: «не спрашивали» и «нет» —
// разные состояния, и §2.4 запрещает превращать первое во второе.
type Trait int

const (
	TraitUnknown Trait = iota
	TraitYes
	TraitNo
)

func (t Trait) String() string {
	switch t {
	case TraitYes:
		return "да"
	case TraitNo:
		return "нет"
	default:
		return "не спрашивали"
	}
}

// Traits — что известно о разборе у коробки.
//
// Это НЕ диагноз её устройства (§2.4), а список наблюдений вида «на такой
// вопрос она отвечает так». Из них выводится, куда резать.
type Traits struct {
	// ByName — решает ли коробка по имени.
	//
	// Вопрос решается ТОЛЬКО именем, которое на этой линии заведомо проходит.
	// Безобидного мало: при блокировке по объёму коробка сбрасывает любое
	// непривилегированное имя, и зонд уверенно соврёт «дело в адресе».
	// Замер донора: 300.ya.ru и disk.rzd.ru проходят, ya.ru — нет; список
	// конкретный, а не «всё российское».
	//
	// Поэтому TraitNo ставится, только когда проходящее имя ИЗВЕСТНО и всё
	// равно не прошло. Пока оно неизвестно, ответа нет — и это записывается
	// как отсутствие ответа, а не как «дело в адресе» (§2.4).
	ByName Trait

	// VolumeCut — наблюдался обрыв по объёму. Своя ось поиска: она про имя, а
	// не про разрез.
	VolumeCut bool

	// VolumeAsked — вопрос про объём уже задавали. Отдельно от VolumeCut:
	// «не спрашивали» и «не режут» — разные состояния (§2.4).
	VolumeAsked bool

	// PassingName — имя, с которым объём проходит на ЭТО направление.
	//
	// Свойство направления, а не линии. Прогон 06.09.2026 по 35 сетям с одной
	// линии в одну минуту: disk.rzd.ru проводит объём в 12 сетях и не проводит
	// в 21. Считать имя свойством линии — ровно та ошибка, из-за которой одно
	// удачное имя объявляется универсальным и потом «чинит» то, что и так
	// работало.
	PassingName string

	// Props — вектор ответов на пять вопросов о свойствах пересобирающей
	// коробки (classify.PropProbes). Раньше здесь стояли три поля
	// (ReadsFirstHello, ChecksSum, Reassembles) — свои, доморощенные вопросы
	// о том же самом. Их ответы нигде не читались: nextQuestion их
	// СПРАШИВАЛ, а ни один синтез план из них не выводил — вопрос без
	// потребителя не измерение, а ритуал. classify.Properties — тот же
	// вопрос, но заданный настоящим зондом (classify.Run) и действительно
	// потребляемый: см. classify.Compose и verdictCandidates в controller.go.
	Props classify.Properties
}

// Question — один различающий вопрос.
type Question struct {
	// Name — как вопрос называется в журнале решений.
	Name string
	// Why — что именно этот вопрос отсекает. Нужно человеку, читающему
	// журнал: «пробую вопрос 3» ничего не объясняет.
	Why string
}

// nextQuestion выбирает следующий вопрос: тот, чей ответ способен изменить
// дальнейший выбор. Вопрос, ответ на который ничего не меняет, не задаётся —
// каждый зонд это время пользователя.
func nextQuestion(t Traits) (Question, bool) {
	// Первым — вопрос, который отсекает больше всего: встаёт ли транспорт
	// вообще. Если даже он не встаёт, дело ниже TLS и все остальные вопросы
	// бессмысленны. Этот вопрос решается ЛЮБЫМ именем и потому задаётся
	// первым — в отличие от вопроса про имя против адреса, которому нужно
	// заведомо проходящее имя.
	if t.ByName == TraitUnknown {
		return Question{
			Name: "встаёт ли транспорт",
			Why:  "если не встаёт даже он, дело ниже TLS и имя ни при чём",
		}, true
	}
	if t.ByName == TraitNo {
		// Ответ получен и он закрывает тему.
		return Question{}, false
	}
	// Вопроса про объём здесь нет намеренно: он меряется ФОНОМ и лестницу не
	// задерживает (см. askVolume). Его ответ, когда придёт, перебивает
	// очередь кандидатов, а не занимает в ней место.
	// Дальше — вопросы про разбор. Вопрос «имя или адрес» сюда НЕ входит: без
	// заведомо проходящего имени он неразрешим, а проходящее имя выясняется
	// отдельной осью поиска (см. PassingName). Задавать неразрешимый вопрос и
	// толковать его ответ — это выдумывать, а не измерять.
	if t.VolumeCut {
		// Обрыв по объёму — своя ось, и она про ИМЯ. Вопросы про разбор здесь
		// ничего не решают: подстановка имени сама и есть вопрос, а ответ на
		// него читается по объёму следующего потока. Лишний зонд тут —
		// лишнее ожидание у человека.
		return Question{}, false
	}
	// Вопросов про разбор (первое приветствие, буфер пересборки) здесь больше
	// нет: их место занял classify.Run — настоящий зонд вместо двух вопросов
	// без потребителя (см. комментарий у Traits.Props). Он тоже меряется
	// ФОНОМ, как и объём (см. askClassify в classify_probe.go), и здесь,
	// среди вопросов очереди, места не занимает.
	return Question{}, false
}
