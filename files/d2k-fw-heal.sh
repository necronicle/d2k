#!/bin/sh
# d2k-fw-heal.sh — восстановление правил NFQUEUE, когда их снесли.
#
# ЗАЧЕМ. Keenetic (NDM) периодически сбрасывает чужие правила iptables. Датапат
# при этом остаётся жив, очередь остаётся привязанной, служба рапортует
# «работает» — а в очередь не приходит НИ ОДНОГО пакета, и обход молча мёртв до
# ручного перезапуска. Поймано на роутере автора 12.09.2026: через 1 ч 40 мин
# после перезагрузки цепочки D2K_IN/D2K_OUT стояли подцепленными, а правил
# NFQUEUE внутри них не было ни одного; instagram не открывался вовсе.
#
# Механизм и его оговорки унаследованы у z2k (files/z2k-nfqueue-selfheal.sh и
# files/000-zapret2.sh), где они выведены полевыми отказами, а не рассуждением:
#
#   1. Событийное восстановление первично (хук netfilter.d), периодическое —
#      страховка на случай сброса, который хук не разбудил.
#   2. Действовать ТОЛЬКО когда правил действительно нет: иначе получается
#      шторм перезапусков, который сам рвёт соединения (z2k, r-60).
#   3. Не топтать свежее восстановление: общий замок и минимальный интервал.
#      Замок протухает, иначе упавший экземпляр запирает лечение навсегда.
#   4. PATH у cron и у NDM-хука не содержит /opt/bin, где лежит iptables
#      (reference_cron_path_entware) — дописываем сами.
#
# Всё переопределяемо окружением: этим пользуется проверка в контейнере
# (scripts/check_firewall.sh), которая гоняет настоящие правила, а не их разбор.

case ":${PATH}:" in
    *:/opt/sbin:*) ;;
    *) PATH="/opt/sbin:/opt/bin:/sbin:/usr/sbin:/bin:/usr/bin${PATH:+:}${PATH}" ;;
esac
export PATH

INIT_SCRIPT="${INIT_SCRIPT:-/opt/etc/init.d/S99d2k}"
HEAL_LOCK="${HEAL_LOCK:-/tmp/d2k-fw-heal.lock}"
HEAL_LAST="${HEAL_LAST:-/tmp/d2k-fw-heal.last}"
# Секунды. Оба числа унаследованы у z2k вместе со смыслом: 15 — чтобы не
# наступать на только что прошедшее восстановление, 60 — чтобы снять замок
# упавшего экземпляра.
MIN_INTERVAL="${MIN_INTERVAL:-15}"
LOCK_STALE="${LOCK_STALE:-60}"

now_s() { date +%s 2>/dev/null || echo 0; }

# Служба сама знает, стоят ли её правила ЦЕЛИКОМ (fw_installed в S99d2k
# проверяет и зацепки цепочек, и правила очереди в обе стороны по обоим
# протоколам). Второй реализации этой проверки здесь нет намеренно: разойдись
# они — сторож лечил бы не то, что сломано.
[ -x "$INIT_SCRIPT" ] || exit 0

# Датапат не работает — лечить нечего и не для кого: правила без него
# отправляли бы пакеты в никуда.
"$INIT_SCRIPT" status 2>/dev/null | grep -q "датапат: работает" || exit 0

# Правила на месте — выходим молча. Это самый частый случай, и он обязан быть
# самым дешёвым.
"$INIT_SCRIPT" status 2>/dev/null | grep -q "правила: стоят" && exit 0

last=$(cat "$HEAL_LAST" 2>/dev/null || echo 0)
now=$(now_s)
if [ $((now - last)) -lt "$MIN_INTERVAL" ]; then
    exit 0
fi

if ! mkdir "$HEAL_LOCK" 2>/dev/null; then
    # Замок занят. Протухший снимаем: иначе упавший экземпляр запирает лечение
    # насовсем, и это отказ хуже того, от которого сторож защищает.
    lock_age=$((now - $(date -r "$HEAL_LOCK" +%s 2>/dev/null || echo "$now")))
    if [ "$lock_age" -gt "$LOCK_STALE" ]; then
        rmdir "$HEAL_LOCK" 2>/dev/null
    fi
    exit 0
fi

echo "$now" > "$HEAL_LAST"
"$INIT_SCRIPT" reapply >/dev/null 2>&1
rc=$?
rmdir "$HEAL_LOCK" 2>/dev/null

if [ "$rc" = 0 ]; then
    echo "d2k: правила снесены извне и восстановлены сторожем" >&2
fi
exit "$rc"
