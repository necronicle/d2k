#!/bin/sh
# Собирает таблицу по логам одного захода матрицы.
#
# Скорость берётся из вывода оркестратора (в логе прогона её затирает
# параллельная запись ssh), CPU и RSS — пик по тикам, пакеты — максимум.
# Пакеты печатаются намеренно: конфигурации сравнимы только при равной
# нагрузке, и колонка сразу показывает, если какая-то её недобрала.
set -u

LOGS=${1:?путь к каталогу логов}
CONSOLE=${2:?файл с выводом оркестратора}

printf '%-14s %9s %7s %8s %8s %9s\n' конфигурация пакетов CPU% RSS_КиБ дропов "МБ/с"
awk '/^=== /{name=$2} /скорость \(Б\/с\)/{s=0;n=0;for(i=4;i<=NF;i++){s+=$i;n++} if(n) printf "%s %.1f\n", name, s/n/1048576}' "$CONSOLE" |
while read -r nm sp; do
    f="$LOGS/$nm.log"
    [ -f "$f" ] || continue
    pk=$(sed -n 's/.*пакетов=\([0-9]*\).*/\1/p' "$f" | sort -rn | head -1)
    cpu=$(sed -n 's/.*cpu=\([0-9.]*\)%.*/\1/p' "$f" | sort -rn | head -1)
    rss=$(sed -n 's/.*rss=\([0-9]*\)КиБ.*/\1/p' "$f" | sort -rn | head -1)
    dr=$(sed -n 's/.*дроп-очереди=\([0-9]*\).*/\1/p' "$f" | sort -rn | head -1)
    printf '%-14s %9s %7s %8s %8s %9s\n' "$nm" "${pk:-—}" "${cpu:-—}" "${rss:-—}" "${dr:-—}" "$sp"
done
